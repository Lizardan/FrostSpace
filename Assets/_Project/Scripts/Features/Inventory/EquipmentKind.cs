    /// </summary>
    public enum EquipmentKind
    {
        /// <summary>Сонар курьерский: круговая волна сканирования, клавиша Q.</summary>
        Scanner = 0,

        /// <summary>Карта пояса: миникарта в правом верхнем углу.</summary>
        Map = 1,
    }
}
