using UnityEngine;

namespace FrostSpace.Features.Map
{
    /// <summary>
    /// Метка «этот объект — геометрия клетки, собранная из FBX».
    ///
    /// Префаб клетки — самостоятельный ассет: в нём живут и меши, и авторские
    /// актёры, и компоненты. Чтобы инструменты обновления не спутали одно с
    /// другим, граница владения задана явно. Всё, что помечено `CellMesh`,
    /// принадлежит конвейеру (`Tools/Unity/sync_cell_prefabs.cs`): меш, материалы,
    /// коллайдер и трансформ такого объекта обновляются из FBX. Всё остальное —
    /// авторское: актёры, свет, логика, добавленные дети — инструмент не трогает
    /// и не удаляет.
    ///
    /// Без этой метки обновление неизбежно становится пересборкой: единственный
    /// способ отличить «меш из FBX» от «меша, который дизайнер добавил руками» —
    /// знать это заранее. Пересборка уже стоила 27 636 трис: префаб собрали
    /// раньше FBX, меши переименовали, ссылки повисли молча.
    /// </summary>
    [DisallowMultipleComponent]
    public sealed class CellMesh : MonoBehaviour
    {
    }
}
