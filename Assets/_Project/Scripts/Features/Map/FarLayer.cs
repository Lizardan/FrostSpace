using FrostSpace.Features.Locomotion;
using UnityEngine;

namespace FrostSpace.Features.Map
{
    /// <summary>
    /// Дальний слой наследия: силуэты якорей, которые всегда в 380 м от игрока.
    ///
    /// Зачем он нужен. Якорь стоит в 849-1697 м, а сцена обрывает геометрию на
    /// 400 м (`farClip`), так что на своём месте он не отрисуется никогда. В
    /// кадре его заменяет карточка на 380 м, отмеренная по угловому размеру
    /// настоящего тела (ADR 0036 п.6, числа — `world_layout.far_layer()`).
    ///
    /// Зачем он движется. Карточка маленькая и близкая, настоящий якорь —
    /// огромный и далёкий: у них одинаковый только угол, и параллакс у карточки
    /// в четыре с лишним раза сильнее. Стоя на месте, она поползла бы по небу
    /// уже на сотне метров дороги — станция «Север-7» уехала бы вправо от своей
    /// горловины. Поэтому слой переставляется за игроком по XZ и не
    /// поворачивается: угол остаётся обещанным, а вместе с ним и всё, что слой
    /// изображает.
    ///
    /// Высота корня не берётся из позиции игрока: подъём на гребень (+8.5 м)
    /// сдвинул бы макушку силуэта на 1.3°, а настоящий якорь при этом не
    /// поднимается. Основание карточек живёт на нуле сцены, как и обещано
    /// расстановкой.
    /// </summary>
    [DisallowMultipleComponent]
    public sealed class FarLayer : MonoBehaviour
    {
        [Tooltip("Игрок; пусто — ищется в сцене по ходовой части")]
        [SerializeField] private Transform _player;

        private void Awake()
        {
            if (_player == null)
            {
                var body = FindAnyObjectByType<RobotLocomotion>();
                _player = body != null ? body.transform : null;
            }
        }

        private void LateUpdate()
        {
            if (_player == null)
                return;
            var p = _player.position;
            transform.position = new Vector3(p.x, 0f, p.z);
        }
    }
}
