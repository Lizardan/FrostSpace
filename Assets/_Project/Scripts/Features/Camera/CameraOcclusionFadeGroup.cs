using UnityEngine;

namespace FrostSpace.Features.View
{
    /// <summary>
    /// Части одного объекта, которые получают вырез вместе.
    ///
    /// Фейдер перекрытий вырезает круг вокруг игрока по одному рендереру. Для
    /// составных сооружений этого мало: стена дома, его окна и дверь — разные
    /// рендереры, и без группы окно внутри круга осталось бы висеть в воздухе.
    /// Компонент вешается на корень такого объекта и перечисляет части, которым
    /// нужно включать шейдер выреза одновременно.
    ///
    /// Интерьерные пропы в список не входят: они не перекрывают игрока и не должны
    /// вырезаться. Сам объект при этом не исчезает целиком — шейдер убирает только
    /// круг на экране, остальное остаётся видимым.
    /// </summary>
    [DisallowMultipleComponent]
    public sealed class CameraOcclusionFadeGroup : MonoBehaviour
    {
        [Tooltip("Рендереры, которые получают шейдер выреза все сразу, если перекрытие создал любой из них")]
        [SerializeField] private Renderer[] _renderers;

        public Renderer[] Renderers => _renderers;
    }
}
