using UnityEngine;

namespace FrostSpace.Features.View
{
    /// <summary>
    /// Части одного объекта, которые растворяются вместе.
    ///
    /// Фейдер перекрытий гасит то, что попало между камерой и игроком, по одному
    /// рендереру. Для составных сооружений этого мало: стена дома, его окна и дверь
    /// — разные рендереры, и без группы на месте исчезнувшей стены остаются висеть
    /// светящиеся окна. Компонент вешается на корень такого объекта и перечисляет
    /// части, которые должны гаснуть и возвращаться как одно целое.
    ///
    /// Интерьерные пропы в список не входят: когда дом растворяется, они остаются
    /// видимыми — получается разрез, в котором игрок виден.
    /// </summary>
    [DisallowMultipleComponent]
    public sealed class CameraOcclusionFadeGroup : MonoBehaviour
    {
        [Tooltip("Рендереры, которые скрываются все сразу, если перекрытие создал любой из них")]
        [SerializeField] private Renderer[] _renderers;

        public Renderer[] Renderers => _renderers;
    }
}
