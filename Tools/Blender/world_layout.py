def project_to_line(x: float, z: float, pts):
    """Ближайшая точка ломаной: (расстояние, путь до неё, направление сегмента)."""
    best = None
    s = 0.0
    for (a, b) in zip(pts, pts[1:]):
        (dx, dz) = (b[0] - a[0], b[1] - a[1])
        ln = math.hypot(dx, dz)
        t = 0.0 if ln == 0.0 else max(0.0, min(1.0,
                             ((x - a[0]) * dx + (z - a[1]) * dz) / (ln * ln)))
        d = math.hypot(x - (a[0] + dx * t), z - (a[1] + dz * t))
        if best is None or d < best[0]:
            best = (d, s + ln * t, (dx / ln, dz / ln) if ln else (0.0, 1.0))
        s += ln
    return best


def point_at_distance(pts, s: float):
    """Точка ломаной на пути `s` от начала."""
    for (a, b) in zip(pts, pts[1:]):
        ln = math.hypot(b[0] - a[0], b[1] - a[1])
        if s <= ln:
            t = s / ln if ln else 0.0
            return (a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t)
        s -= ln
    return pts[-1]


def _smooth_profile(ys, base: float) -> list:
    """Сглаживание по продольному пути: ядро cos² на базе `base` с обоих концов."""
    half = base * 0.5
    out = []
    for i in range(len(ys)):
        (ws, acc) = (0.0, 0.0)
        for j in range(len(ys)):
            d = abs(ys[j][0] - ys[i][0])
            if d > half:
                continue
            w = math.cos(d / half * math.pi * 0.5) ** 2
            ws += w
            acc += w * ys[j][1]
        out.append(acc / ws)
    return out


def _limit_grade(ys, ds: float, gmax: float, passes: int = 6,
                 pins: dict = None) -> None:
    """Уложить профиль в предел уклона: двусторонний проход с ограничением шага.

    Сглаживание убериает короткие волны, но не спорит с длинным склоном плиты:
    там нужен именно потолок уклона, иначе стол на 5 км даёт 5 % там, где
    рельсовому пути положено 4. Проход туда и обратно по несколько раз сходится
    к профилю, который круче предела быть не может.

    `pins` — отметки, которые сдвигать нельзя (пол двора). Без них ограничитель
    съехал бы и их: дорога, прирезанная к уровню депо, получила бы в воронке
    двора 16 % там, где ей положено 6. С пинами перепад растаскивается по
    соседним точкам, и крутизна остаётся за пределами двора, где ей место.
    """
    for _ in range(passes):
        for i in range(1, len(ys)):
            ys[i] = min(max(ys[i], ys[i - 1] - gmax * ds), ys[i - 1] + gmax * ds)
        for i in range(len(ys) - 2, -1, -1):
            ys[i] = min(max(ys[i], ys[i + 1] - gmax * ds), ys[i + 1] + gmax * ds)
        if pins:
            for (i, y) in pins.items():
                ys[i] = y


def line_samples(pts, step: float = GRADE_SAMPLE):
    """Точки продольного профиля: (путь от начала, x, z) с шагом `step`.

    Отдельно от отметок: привязка стола к двору (`anchor_tables`) меряет двор по
    его геометрии, а не по пути, и ей нужны сами точки. Один обход ломаной на
    оба числа означал бы, что отметки и точки сошлись бы только случайно.
    """
    acc = [(0.0, pts[0][0], pts[0][1])]
    s = 0.0
    for (a, b) in zip(pts, pts[1:]):
        ln = math.hypot(b[0] - a[0], b[1] - a[1])
        n = max(1, int(ln / step + 0.5))
        for k in range(1, n + 1):
            t = k / n
            s += ln / n
            acc.append((s, a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t))
    return acc


def grade_table(samples, base: float, gmax: float) -> list:
    """Продольный профиль стола: путь от начала и отметка в каждой точке."""
    ys = _smooth_profile([(s, plate_height(x, z)) for (s, x, z) in samples],
                         base)
    _limit_grade(ys, samples[1][0] - samples[0][0], gmax)
    return list(zip([p[0] for p in samples], ys))


def level_at(table, s: float) -> float:
    """Отметка стола на пути `s`: линейная интерполяция по таблице профиля."""
    if s <= table[0][0]:
        return table[0][1]
    if s >= table[-1][0]:
        return table[-1][1]
    for i in range(len(table) - 1):
        (s0, y0) = table[i]
        (s1, y1) = table[i + 1]
        if s0 <= s <= s1:
            t = 0.0 if s1 == s0 else (s - s0) / (s1 - s0)
            return y0 + (y1 - y0) * t
    return table[-1][1]


#: Скругление углов трассы: расстояние, на котором колено подходит к вершине
#: ломаной, и число точек дуги. Это не косметика: метла шириной 15,2 м на угле
#: в 36° даёт клин наружу на 20 м — «клюв», которого у железной дороги быть не
#: может, потому что у неё повороты имеют радиус, а не вершину.
RAIL_FILLET = 120.0
ROAD_FILLET = 80.0
FILLET_SAMPLES = 8


def fillet(pts, dist: float, samples: int = FILLET_SAMPLES):
    """Центральная линия трассы: вершины ломаной заменены плавными дугами.

    Дуга — квадратичная кривая Безье между касательными точками через саму
    вершину: касательная непрерывна, радиус получается из угла и длины колена,
    и ни одного трезубого клина метла не рисует. От вершины отказываться нельзя
    — она и есть трасса, узлы стоят на ней, — поэтому касательные точки берутся
    на `dist` вдоль обоих колен, а на коротких коленах урезаются до трети,
    чтобы дуга не съела соседний угол.
    """
    if len(pts) < 3:
        return list(pts)
    out = [tuple(pts[0])]
    for k in range(1, len(pts) - 1):
        (ax, az) = out[-1]
        (vx, vz) = pts[k]
        (bx, bz) = pts[k + 1]
        la = math.hypot(vx - ax, vz - az) or 1.0
        lb = math.hypot(bx - vx, bz - vz) or 1.0
        ta = min(dist, la * 0.35)
        tb = min(dist, lb * 0.35)
        a = (vx - (vx - ax) / la * ta, vz - (vz - az) / la * ta)
        b = (vx + (bx - vx) / lb * tb, vz + (bz - vz) / lb * tb)
        out.append(a)
        for n in range(1, samples):
            t = n / samples
            out.append(((1 - t) ** 2 * a[0] + 2 * t * (1 - t) * vx + t ** 2 * b[0],
                        (1 - t) ** 2 * a[1] + 2 * t * (1 - t) * vz + t ** 2 * b[1]))
        out.append(b)
    out.append(tuple(pts[-1]))
    return out


#: Центральные линии, по которым считается стол, клетки и тепло. Объявленные
#: ломаные `RAIL`/`ROADS` остаются проектной трассой: узлы и инварианты говорят
#: про них, а геометрия строится по скруглённой.
RAIL_LINE = fillet(list(RAIL), RAIL_FILLET)
ROAD_LINES = [fillet(list(p), ROAD_FILLET) for p in ROADS]


def _transport_lines():

    """Описание транспортных линий: трасса, габарит выемки и свой профиль.

    Тепла линия здесь не получает: `warm_distance` считает тепло по дорогам, а
    путевой коридор холоден по канону, и поле «warm» только сбило бы с толку.
    """
    out = [{"k": "rail", "kind": "rail", "pts": list(RAIL_LINE), "cut": RAIL_CUT,
            "grade": RAIL_GRADE}]
    for (n, pts) in enumerate(ROAD_LINES):
        out.append({"k": "road %d" % n, "kind": "road", "pts": list(pts),
                    "cut": ROAD_CUT, "grade": ROAD_GRADE})
    for ln in out:
        (base, gmax) = ln["grade"]
        ln["samples"] = line_samples(ln["pts"])
        ln["table"] = grade_table(ln["samples"], base, gmax)
        ln["len"] = ln["table"][-1][0]
        m = ln["cut"][1] + 1.0
        xs = [p[0] for p in ln["pts"]]
        zs = [p[1] for p in ln["pts"]]
        ln["bbox"] = (min(xs) - m, max(xs) + m, min(zs) - m, max(zs) + m)
    return out


#: Считается один раз при импорте: профиль линии — это производная плиты, и
#: пересчитывать его на каждую вершину террейна нельзя.
TRANSPORT = _transport_lines()

#: Полная длина каждой линии, м: по ней меряется близость к тупику.
LINE_LEN = {ln["k"]: ln["samples"][-1][0] for ln in TRANSPORT}


def transport_floor(x: float, z: float):
    """Стол под точкой: линия, расстояние до оси, путь, отметка и доля хозяина.

    Хозяин — та линия, чей откос в этой точке круче перехватывает плиту (то есть
    с максимальной долей), а не ближайшая по оси: там, где дорога входит в
    путевой коридор, решение должен принимать более широкий коридор.
    """
    best = None
    for ln in TRANSPORT:
        (x0, x1, z0, z1) = ln["bbox"]
        if x < x0 or x > x1 or z < z0 or z > z1:
            continue
        (d, s, _dir) = project_to_line(x, z, ln["pts"])
        mask = 1.0 - smooth01(ln["cut"][0], ln["cut"][1], d)
        if mask <= 0.0:
            continue
        if best is None or mask > best[0]:
            best = (mask, ln, d, s)
    if best is None:
        return None
    (mask, ln, d, s) = best
    return {"k": ln["k"], "kind": ln["kind"], "dist": d, "s": s,
            "level": level_at(ln["table"], s), "mask": mask}


def _corridor(f, x: float, z: float):
    """(дно, доля) коридора в точке с учётом тёплых дворов.

    Путь режет двор, как любую землю: балласт обязан читаться врезанным, а не
    положенным на ровный пол. Дорога не делает с тёплым двором **ничего** —
    ни режет, ни выравнивает по своему столу. Гасится именно доля, а не только
    глубина: стол линии один на всю ширину коридора, а пол двора наклонён вдоль
    пути (4,7 % в депо), поэтому выравнивание по столу дало бы вдоль дороги
    лоток глубиной до 0,7 м — замер на кромке двора депо.

    Отсюда и правило для полотна: у своего тупика в тёплом дворе дорога сходит
    на него (`flush_blend`), и её стол прирезан к полу двора (`anchor_tables`).

    Одна функция на две вещи: по ней считает и поле высот, и проверка
    `_corridor_check` в `build_world_cells`. Иначе проверка мерила бы одно
    правило, а сборка применяла другое.
    """
    depth = CUT_DEPTH[f["kind"]]
    if f["kind"] in FLUSH_KINDS:
        # У тупика выемка не гасится в ноль, а сходит до слоя покрытия: земля
        # остаётся на 10 см ниже полотна, и пара «дорога/земля» не ложится в две
        # плоскости в двух сантиметрах (порог мерцания — 6 см). Отметка при
        # этом сходится точно: стол у тупика — пол двора плюс `ROAD_ON_PAD`, а
        # дно — стол минус `ROAD_ON_PAD`, то есть ровно пол двора при любом
        # весе — у двора ничего не проседает и не вспучивается.
        b = flush_blend(f["k"], f["s"])
        depth = ROAD_ON_PAD + (depth - ROAD_ON_PAD) * b
    return (f["level"] - depth, f["mask"])


def corridor(x: float, z: float):
    """(дно, доля) коридора в точке мира; `None`, если коридора здесь нет."""
    f = transport_floor(x, z)
    if f is None:
        return None
    return _corridor(f, x, z)


def transport_cut(x: float, z: float, h: float) -> float:
    """Высота точки с учётом стола: коридор режет рельеф, а не рельеф коридор.

    Дно ниже стола на `CUT_DEPTH` по классу линии: стол — это поверхность, по
    которой едут, а рельеф срезается до постели под ней.
    """
    f = transport_floor(x, z)
    if f is None:
        return h
    (floor, mask) = _corridor(f, x, z)
    return h + (floor - h) * mask


def line_crossings(pts, step: float = 1.0):
    """Границы решётки, которые линия переходит: (точка, клетка до, клетка после).

    Точка ищется половинным делением, а не «ближайшим образцом»: на 1 м шага
    погрешность по оси — полметра, а стык двух чанков обязан сойтись до
    миллиметра, иначе на границе клетки вступит ступенька.
    """
    hits = []
    prev = None
    for (a, b) in zip(pts, pts[1:]):
        ln = math.hypot(b[0] - a[0], b[1] - a[1])
        n = max(1, int(ln / step + 0.5))
        for k in range(n + 1):
            t = k / n
            p = (a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t)
            c = cell_of(*p)
            if prev is not None and prev[1] != c:
                (p0, c0) = prev
                (lo, hi) = (0.0, 1.0)
                for _ in range(60):
                    mid = 0.5 * (lo + hi)
                    pm = (p0[0] + (p[0] - p0[0]) * mid,
                          p0[1] + (p[1] - p0[1]) * mid)
                    if cell_of(*pm) == c0:
                        lo = mid
                    else:
                        hi = mid
                pm = (p0[0] + (p[0] - p0[0]) * hi,
                      p0[1] + (p[1] - p0[1]) * hi)
                hits.append((pm, c0, c))
            prev = (p, c)
    return hits



#: Как далеко от узла должна пройти линия, чтобы пол двора равняли по её столу.
#: 120 м — это дальше самой длинной юбки в половину: узел, стоящий в 300 м от
#: нити, к ней не прирезан, и раскатывать ему площадку по чужой отметке нельзя.
NODE_ON_LINE = 120.0


def node_host(n):
    """Хозяйская линия узла: (линия, путь до ближайшей точки), если линия рядом.

    Порядок зависимостей развёрнут в пользу пути: не он подстраивается под
    площадку, а площадка ровняется по нему. Иначе коридор, прорезающий двор,
    оставлял в нём ступеньку — на станции до 8 м.
    """
    best = None
    for ln in TRANSPORT:
        (d, s, _dir) = project_to_line(n["x"], n["z"], ln["pts"])
        if best is None or d < best[0]:
            best = (d, ln, s)
    if best is None or best[0] > NODE_ON_LINE:
        return None
    return (best[1], best[2])


#: Хозяин каждой тёплой площадки — считается один раз: `pad_height` зовётся на
#: каждую вершину террейна и перебирать линии внутри неё нельзя.
PAD_HOST = {n["k"]: node_host(n) for n in NODES}


#: Ближе этого к тупику дорога не режет двор, а сходит на него, м.
FLUSH_END = 40.0


def flush_blend(key: str, s: float) -> float:
    """1 — линия режет землю, 0 — сошла на тёплый двор у своего тупика.

    Тупик — место, где линии больше нет: резать там нечего, а выемка осталась
    бы обрывом или каналом у самого створа — ровно то, из-за чего дорога не
    въезжала в депо. Гашение идёт по **пути от конца линии**, а не по площадке:
    сквозная дорога через двор свой настил не меняет и по-прежнему лежит на
    своём ложе — так приняты и посёлок, и станция.
    """
    total = LINE_LEN.get(key, 1.0e9)
    return smooth01(0.0, FLUSH_END, min(s, total - s))


def _pad_offset(ln, s: float) -> float:
    """Насколько стол линии выше пола двора, когда она на нём лежит.

    Насквозь — на всю глубину дна (`CUT_DEPTH`): полотно стоит над полом, и
    выемка под ним врезана. У тупика — только слой покрытия (`ROAD_ON_PAD`):
    дорога сходит на двор, и её полотно обязано быть на нём, а не на плите.

    Два числа и один вес, потому что земля считается тем же весом
    (`_corridor`): тогда зазор «полотно над землёй» равен
    `CUT_DEPTH·b·(1−b) + ROAD_ON_PAD` и не бывает меньше `ROAD_ON_PAD` — 8 см,
    то есть за порогом мерцания (6 см) при любом весе, а не в среднем.
    """
    if ln["kind"] not in FLUSH_KINDS:
        return 0.0
    b = flush_blend(ln["k"], s)
    return ROAD_ON_PAD + (CUT_DEPTH[ln["kind"]] - ROAD_ON_PAD) * b


def pad_level(n, x: float, z: float) -> float:
    """Пол двора в точке: стол хозяйской линии, то есть её головка рельса.

    Двор — это отсыпанная площадка **в уровне пути**, а не плоский блин: через
    депо линия идёт с уклоном 4 % и падает поперёк двора на 13 м. Площадка,
    зажатая в одну отметку, оставляла в дворе либо каньон (там, где стол ниже),
    либо насыпь (там, где выше), и путь входил в двор стеной. Здесь двор
    наклонён вдоль линии и горизонтален поперёк: у построек нет перекоса поперёк
    фасада, а у пути нет стенки.

    Пол двора — это стол хозяйской линии без поправки на покрытие: дорога,
    идущая сквозь двор, стоит над ним на своём ложе (`CUT_DEPTH`), а та, что
    кончается в нём, сходит на двор (`flush_blend`, `_pad_offset`).

    Уровень — именно головка, а не дно коридора. Пробовал опускать пол до дна,
    чтобы путевой коридор внутри двора исчез совсем: путь при этом ложился на
    двор валком в 0,88 м, и приёмка «путь читается прорезанным в снегу, а не
    положенным на стол» на этом варианте падает глазами, а не числами. С полом в
    уровне головки двор несёт те же 0,6 м выемки, что и перегон, и балласт
    выступает над ним на те же 0,26 м, что и в принятом кадре прибытия.
    """
    host = PAD_HOST.get(n["k"])
    if host is None:
        return plate_height(n["x"], n["z"])
    (ln, _s) = host
    (_d, s, _dir) = project_to_line(x, z, ln["pts"])
    return level_at(ln["table"], s)


def node_level(n) -> float:
    """Отметка пола узла в его центре — то же число, что `pad_level` в нуле."""
    return pad_level(n, n["x"], n["z"])


def _pads():
    """(узел, отметка, юбка) — считается один раз при импорте.

    Во-первых, звать `plate_height` на каждую точку каждой клетки нельзя:
    генератор террейна получил бы квадратичное время. Во-вторых, юбка площадки
    растёт до тех пор, пока съезд с плиты на площадку не станет пологим
    (`PAD_GRADE`): у узла на склоне перепад в 13 м на сорокаметровой юбке — это
    стена, в которую робот упирается носом, а не площадь. Перепад меряется по
    всем восьми краям и по фактическому полу двора (`pad_level`), а не по центру:
    у двора в уровне наклонной линии край против уклона и край по уклону
    различаются на несколько метров.
    """
    out = []
    for n in NODES:
        if not n["rect"] or n["k"] in PAD_SKIP:
            continue
        level = node_level(n)
        (x0, x1, z0, z1) = n["rect"]
        (cx, cz) = ((x0 + x1) * 0.5, (z0 + z1) * 0.5)
        skirt = PAD_SKIRT
        for _ in range(8):
            edge = [(x0 - skirt, z0 - skirt), (x1 + skirt, z0 - skirt),
                    (x0 - skirt, z1 + skirt), (x1 + skirt, z1 + skirt),
                    (x0 - skirt, cz), (x1 + skirt, cz),
                    (cx, z0 - skirt), (cx, z1 + skirt)]
            drop = max(abs(plate_height(ex, ez) - pad_level(n, ex, ez))
                       for (ex, ez) in edge)
            if drop <= skirt * PAD_GRADE or skirt >= PAD_SKIRT_MAX:
                break
            skirt = min(PAD_SKIRT_MAX, max(skirt * 1.5, drop / PAD_GRADE))
        out.append((n, level, skirt))
    return out


_PADS = _pads()

#: Отметка пола каждой тёплой площадки в её центре: число для манифеста,
#: миникарты и превью. Внутри двора пол меняется вдоль линии (`pad_level`), и
#: одно число описывает двор только в его нуле.
PAD_LEVEL = {n["k"]: y for (n, y, _s) in _PADS}


def pad_skirt(k: str) -> float:
    """Фактическая юбка площадки узла: её меряет `check_world.py`."""
    for (n, _y, s) in _PADS:
        if n["k"] == k:
            return s
    return 0.0


def pad_height(x: float, z: float) -> float:
    """Плита с раскатанными по ней тёплыми дворами, но ещё без коридоров.

    Двор обязан быть ровным поперёк себя по той же причине, что и пол депо в
    принятом кадре: на 6.6 км волны дают под постройками десятки сантиметров, и
    робот, стоящий на плите, либо проваливается в неё, либо висит над ней.
    Внутри границ узла — ровно `pad_level`, снаружи за юбкой — ровно плита.
    """
    h = plate_height(x, z)
    for (n, level, skirt) in _PADS:
        d = _rect_dist(x, z, n["rect"])
        if d >= skirt:
            continue
        y = level if PAD_HOST.get(n["k"]) is None else pad_level(n, x, z)
        h += (y - h) * (1.0 - smooth01(0.0, skirt, d))
    return h


def anchor_tables() -> None:
    """Прирезать стол каждой линии к полу двора, через который она проходит.

    Порядок зависимостей разворачивается ещё раз, и на этот раз в пользу двора:
    без привязки дорога от ворот депо держит собственный сглаженный профиль и
    стартовала бы на 3,7 м **ниже** пола двора. Двор в уровне пути — это насыпь
    над локальной низиной, а коридор дороги режет её до своего дна, так что от
    ворот по двору бежал бы канал глубиной в человеческий рост, по которому
    никуда не выехать. Здесь дорога получает отметку двора там, стоит во дворе,
    и сходится со своим профилем за юбкой площадки — уезжает из депо пологим
    съездом, как и должно быть. Отметка — ровно пол двора, без добавки на
    глубину выемки: дорога в тёплом дворе лежит на площадке (`corridor`), и её
    полотно встаёт над двором слоем покрытия (`ROAD_ON_PAD`), а не плитой в
    полметра и не вровень с землёй.

    Хозяйская линия прирезке не подлежит: двор держит её стол, и тянуть её к
    себе же означало бы поднять путь на полметра над его же отметкой. Правятся
    только чужие линии — те, что проходят через чужой двор по своему профилю.

    После привязки профиль ещё раз укладывается в предел уклона, и точки внутри
    двора остаются неприкосновенными (`pins`): юбка площадки короткая (40-60 м),
    и перепад в 4 м, отданный на неё, дал бы въезд в депо круче 10 %. Ограничитель
    растягивает спуск за границы двора, где он и должен быть виден.

    Вызывается один раз при импорте, после `_PADS`: отметки дворов считаются по
    ещё не прирезанным профилям, обратный порядок дал бы цикл.
    """
    for ln in TRANSPORT:
        ys = []
        pins = {}
        for (i, (s, x, z)) in enumerate(ln["samples"]):
            best = None
            for (n, _level, skirt) in _PADS:
                if PAD_HOST.get(n["k"]) is not None and PAD_HOST[n["k"]][0] is ln:
                    continue        # этот двор держит линию, а не линия двор
                d = _rect_dist(x, z, n["rect"])
                if d >= skirt:
                    continue
                w = 1.0 - smooth01(0.0, skirt, d)
                if best is None or w > best[0]:
                    best = (w, pad_level(n, x, z) + _pad_offset(ln, s))
            y = ln["table"][i][1]
            if best is None:
                ys.append(y)
                continue
            ys.append(y + (best[1] - y) * best[0])
            if best[0] > 1.0 - 1e-6:
                pins[i] = best[1]
        ds = ln["samples"][1][0] - ln["samples"][0][0]
        _limit_grade(ys, ds, ln["grade"][1], pins=pins)
        ln["table"] = list(zip([p[0] for p in ln["samples"]], ys))


anchor_tables()


def world_height(x: float, z: float) -> float:
    """Высота снега: пол тёплых дворов, прорезанный транспортными коридорами.

    Порядок — площадки, потом коридор, и он важнее самой формулы. Коридор
    последний, потому что путь входит в двор так же, как в любую другую землю:
    режет её до своей постели. При обратном порядке двор оказывался хозяином
    коридора: головка рельса оставалась на полметра выше площадки, и состав
    висел над полом узла.
    """
    return transport_cut(x, z, pad_height(x, z))


def pad_blend(x: float, z: float) -> float:
    """Доля, которой площадка узла хозяин в точке: 0 — чистая плита или коридор.

    Отдельная функция нужна не генератору, а проверке: коридор проходит через
    тёплые узлы, и внутри их площадки пол узла перекрывает стол намеренно (двор
    обязан держаться своей отметки). Мерить «выемка совпала со столом» надо там,
    где площадки нет, иначе проверка падала бы на собственном порядке слоёв.
    """
    best = 0.0
    for (n, _level, skirt) in _PADS:
        d = _rect_dist(x, z, n["rect"])
        if d >= skirt:
            continue
        best = max(best, 1.0 - smooth01(0.0, skirt, d))
    return best


def in_crack(x: float, z: float) -> bool:
    """Точка в корыте разлома (не в валу): сюда не должна заходить тёплая линия."""
    return FL.dist_to_polyline(x, z, CRACK["pts"]) < CRACK["half"] * 0.9


