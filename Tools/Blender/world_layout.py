"""Раскладка мира: якоря наследия, линии, тёплый каркас, чанки и поля высот.

Форма наследия — **A · «Якоря Пояса»**, утверждена владельцем 2026-11-01 на схеме
шага 0. Колония 07 стоит на нижнем ярусе Пояса — транзитной инфраструктуры
ушедших. На земле остались **якоря**: опорные башни от 30 до 700 м, между ними
оборванные коммуникации. Станция «Север-7» — обжитый нижний ярус одного якоря;
депо `Frontier` — пригрузочная платформа у основания соседнего, срезанного до
человеческого размера; поезд — служебный транспорт яруса, вставший там, где
линия не достроена. Роботы живут только там, до чего дотянулись, и не понимают,
для чего были верхние ярусы. Это и есть «наследие ушедших» в числах, а не в лоре.

Координаты — **мировые** (Unity x, z), метры. Начало — станция «Север-7» в (0, 0):
она центр и сетки чанков, и раскладки узлов `WORLD.md`. Ноль сцены `Frontier`
(двор депо) = мир (-1200, -1800), клетка (-2, -3). `to_frontier` и `to_world` —
единственный мост между двумя кадрами. Это поправка владельца к таблице ADR 0030
п.2 и к размеру 2.4x2.4 км того же ADR; оформляется ADR 0036.

Высоты **не дублируются**. Чаша депо целиком приходит из
`frontier_layout.ground_height` и не трогается: принятый кадр прибытия (гребень
140-260 м, прорывы на азимутах 50 и 181.6 градуса, плоское дно коридора)
остаётся ровно тем, что утверждено сценой. Снаружи радиуса 300 м от нуля сцены к
ней добавляется макрельеф плиты — иначе 6.6 км мира читаются как плоское поле.
Граница между чашей и плитой — не стена, а плавный гейт, и `invariants()`
следит, что внутри 300 м высота побито совпадает с полем сцены.

Чанк = клетка 600 м. Сторона привязана к дальности: наблюдатель в углу клетки
видит на `farClipPlane = 400` м (STYLE.md), поэтому загруженный блок обязан
кончаться не ближе 400 м от него. Та же сторона держит топологию: узлы стоят в
центрах клеток, и при 400 или 800 м «блок» меняет размер, а вместе с ним и
координата депо.

Наследие при этом живёт в два слоя, и это не оптимизация, а физика кадра: до
станции 1697 м, а геометрия в сцене обрывается на 400 м. Ближний круг (руины
15-60 м, пенёк якоря на 228 м) — настоящая геометрия, к нему идут ногами.
Дальний — карточка на 380 м, отмеренная по угловому размеру якоря
(`far_layer`), и она обязана двигаться вместе с наблюдателем: у неё параллакс в
разы сильнее настоящего, и стоя на месте она ползла бы по небу во время поездки
по дороге. Числа слоя считаются отсюда, меши — `far_parts.py`, поведение —
`Features/Map/FarLayer.cs`.

Чистые числа, без `bpy`: читают генераторы мешей, `check_world.py`,
`world_manifest.json`, превью и — через JSON — `Features/Map`. Раскладку сцены
отсюда никто не генерирует и не переставляет: ADR 0005 и ADR 0035.
"""

