#: быть видно, и тело читается целиком — с депо оно занимает 10.7° вертикали, то
#: есть работает дальним массивом, а не обрезанной стеной. Дальние якори держим
#: в полосе 180-260 м: это силуэты за `farClip`, а не геометрия.
H_MAIN = 320.0
H_MID = 260.0

#: Ярусы-ступени нижнего яруса (доли высоты): широкие, обжитые, с перилами и
#: тёплой лампой. Выше них тело переходит в стержень.
STEPS = (0.12, 0.24, 0.35)

#: Кольцевые обходы стержня: редкие. Это повтор модуля, которым читается
