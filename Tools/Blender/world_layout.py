def sky_dir(bearing_deg: float, elev_deg: float) -> tuple[float, float, float]:
    """Единичное направление на небосводе в осях Unity: (x, y, z).

    Азимут — от +Z на восток, как в `polar`; высота — от горизонта. Скайбокс
    сравнивает с этим вектором нормаль пикселя, поэтому адрес небесного тела
    живёт в тех же числах, что и всё остальное, а не в строке материала.
    """
    b = math.radians(bearing_deg)
    e = math.radians(elev_deg)
    return (math.sin(b) * math.cos(e), math.sin(e), math.cos(b) * math.cos(e))


