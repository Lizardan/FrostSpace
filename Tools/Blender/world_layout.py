# ---------------------------------------------------------------- тёплый каркас

def _rect_dist(x: float, z: float, rect) -> float:
    """Отрицательно внутри прямоугольника, положительно — расстояние до него."""
    return max(rect[0] - x, x - rect[1], rect[2] - z, z - rect[3])


def warm_distance(x: float, z: float) -> float:
    """Сколько метров до тёплого каркаса; 0 и меньше — в тепле.

    «Тепло» на этом шаге — данность мира, а не система: здания, помещения,
    площадки узлов и все дороги безопасны, вне них начинается остывание.
    Рельсовая линия в этом списке не участвует и не будет участвовать: по канону
    это часть открытого холодного мира, и без вагона по ней не идут. Полоски, UI
    и смертей здесь нет; эта функция — единственное, что позже прочитает
    механика, и те же числа уйдут в ADR 0036 как границы-холод.
    """
    best = min(_rect_dist(x, z, n["rect"]) for n in NODES if n["rect"])
    for pts in ROAD_LINES:
        best = min(best, FL.dist_to_polyline(x, z, pts) - WARM_ROAD_HALF)
    return best


def is_warm(x: float, z: float) -> bool:
    return warm_distance(x, z) <= 0.0


