def configure_stdout() -> None:
    """Тот же приём, что `selftest.configure_stdout`: консоль Windows по другой
    кодовой странице показывает русский отчёт как кашу, и следующий агент правит
    не раскладку, а вывод."""
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except (AttributeError, OSError):
            pass


