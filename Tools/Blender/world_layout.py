def smooth01(edge0: float, edge1: float, value: float) -> float:
    """Сглаживание тем же smootherstep, что внутри `frontier_layout`.

    Приватный хелпер чужого модуля не зовётся (в проекте так не делают), но поля
    высот обязаны смешиваться одинаково: иначе на стыке чаши и плиты появился бы
    излом, который никто не заказывал.
    """
    if edge1 <= edge0:
        return 1.0 if value >= edge1 else 0.0
    t = min(max((value - edge0) / (edge1 - edge0), 0.0), 1.0)
    return t * t * (3.0 - 2.0 * t)


def macro_height(x: float, z: float) -> float:
    """Сумма долгих волн плиты в мировой точке, метры."""
    h = 0.0
    for (amp, period, bearing, phase) in MACRO_WAVES:
        b = math.radians(bearing)
        s = (x * math.sin(b) + z * math.cos(b)) / period * 2.0 * math.pi
        h += amp * math.sin(s + phase)
    return h


def crack_drop(x: float, z: float) -> float:
    """Насколько плита НИЖЕ нормы в разломе: корыто минус вал по краю."""
    d = FL.dist_to_polyline(x, z, CRACK["pts"])
    q = d / CRACK["half"]
    trench = CRACK["depth"] * max(0.0, 1.0 - q * q)
    lip = CRACK["lip"] * math.exp(-(((d - CRACK["half"] * 1.15) /
                                     (CRACK["half"] * 0.45)) ** 2))
    return trench - lip


