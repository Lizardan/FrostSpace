#: Шаг, которым ломаная превращается в список клеток. Концы сегментов для
#: этого не годятся: сегмент депо→станция стоит концами в двух клетках, а
#: на деле проходит через четыре, и «клетка занята линией» пришлось бы
#: решать на глаз. Шаг — метр: скруглённый угол заходит в угловую клетку
#: на пару метров, и при шаге в 5 м такая клетка терялась — кусок линии в
#: ней есть, а в списке её нет, и длина кусков не сходилась с длиной трассы.
LINE_SAMPLE = 1.0


def line_cells(pts, step: float = LINE_SAMPLE):
    """Клетки, по которым идёт ломаная, в порядке следования и без повторов."""
    out = []
    for (a, b) in zip(pts, pts[1:]):
        d = math.hypot(b[0] - a[0], b[1] - a[1])
        n = max(1, int(d / step + 0.5))
        for k in range(n + 1):
            t = k / n
            (i, j) = cell_of(a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t)
            if CELL_MIN <= i <= CELL_MAX and CELL_MIN <= j <= CELL_MAX:
                if not out or out[-1] != (i, j):
                    out.append((i, j))
    return out


def _clip_t(a, b, rect):
    """Liang-Barsky: доля сегмента, лежащая внутри прямоугольника клеток."""
    (x0, x1, z0, z1) = rect
    (dx, dz) = (b[0] - a[0], b[1] - a[1])
    (t0, t1) = (0.0, 1.0)
    for (p, q) in ((-dx, a[0] - x0), (dx, x1 - a[0]),
                   (-dz, a[1] - z0), (dz, z1 - a[1])):
        if p == 0.0:
            if q < 0.0:
                return None
        else:
            r = q / p
            if p < 0.0:
                if r > t1:
                    return None
                if r > t0:
                    t0 = r
            elif r < t0:
                return None
            elif r < t1:
                t1 = r
    if t1 < t0:
        return None
    return (t0, t1)


def _lerp(a, b, t):
    return (a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t)


def line_spans(pts, i: int, j: int):
    """Куски ломаной внутри клетки: список полилиний не короче двух точек.

    Куски режутся ровно по рёбрам решётки, поэтому соседняя клетка получает
    тот же конец: обе стороны держат одну точку, и рельс на стыке не может
    разойтись «на глаз» — это проверяет инвариант «стыки линии».
    """
    rect = cell_bounds(i, j)
    spans = []
    cur = []
    for (a, b) in zip(pts, pts[1:]):
        cut = _clip_t(a, b, rect)
        if cut is None:
            if len(cur) >= 2:
                spans.append(cur)
            cur = []
            continue
        (pa, pb) = (_lerp(a, b, cut[0]), _lerp(a, b, cut[1]))
        if cur:
            gap = math.hypot(pa[0] - cur[-1][0], pa[1] - cur[-1][1])
            if gap > 1e-6:
                if len(cur) >= 2:
                    spans.append(cur)
                cur = [pa]
        else:
            cur = [pa]
        if math.hypot(pb[0] - cur[-1][0], pb[1] - cur[-1][1]) > 1e-9:
            cur.append(pb)
    if len(cur) >= 2:
        spans.append(cur)
    return spans


def content_cells():
    """Клетки карты, где что-то стоит: узел, якорь или кусок линии.

    Остальные — пустошь: общая заготовка террейна, а не авторская сцена. Отсюда
    честное число: 121 клетка — это не 121 сцена в сборке. Линия учитывается
    образцами (`line_cells`), а не концами сегментов: иначе клетка, через
    которую путь проходит насквозь, считалась бы пустой, и наполнение её
    обошла бы стороной.
    """
    out = set()

    def add(x: float, z: float) -> None:
        (i, j) = cell_of(x, z)
        if CELL_MIN <= i <= CELL_MAX and CELL_MIN <= j <= CELL_MAX:
            out.add("%d:%d" % (i, j))

    for n in NODES:
        add(n["x"], n["z"])
    for a in ANCHORS:
        add(a["x"], a["z"])
    for r in RUINS:
        add(r["x"], r["z"])
    for pts in (RAIL_LINE,) + tuple(ROAD_LINES):
        for (i, j) in line_cells(pts):
            out.add("%d:%d" % (i, j))
    return out


def cells():
    """Все клетки карты: (i, j, x, z, есть ли в ней контент)."""
    cc = content_cells()
    out = []
    for i in range(CELL_MIN, CELL_MAX + 1):
        for j in range(CELL_MIN, CELL_MAX + 1):
            (x, z) = cell_center(i, j)
            out.append({"i": i, "j": j, "x": x, "z": z,
                        "content": "%d:%d" % (i, j) in cc})
    return out


def resident_cells(x: float, z: float, radius: int = 1):
    """Клетки, живущие в памяти при радиусе загрузки `radius` (окрестность Мура).

    У края карты окрестность обрезается границей: в угловой клетке живёт 4, а не
    9. Это и есть причина, по которой «121» не переводится в 121 сцену.
    """
    (ci, cj) = cell_of(x, z)
    out = []
    for i in range(ci - radius, ci + radius + 1):
        for j in range(cj - radius, cj + radius + 1):
            if CELL_MIN <= i <= CELL_MAX and CELL_MIN <= j <= CELL_MAX:
                out.append((i, j))
    return out


def resident_tris(radius: int = 1) -> int:
    """Треугольников террейна в памяти при радиусе `radius` в полной окрестности."""
    side = 2 * radius + 1
    return side * side * cell_tris()


#: Квадрат авторской земли депо и его «не генерировать клетку под ним» убраны:
#: с тех пор как депо стало обычным чанком клетки (−2,−2), исключений в сетке
#: больше нет. История решения — ADR 0036, п. 2.


def cell_items(i: int, j: int):
    """Что стоит в клетке: узлы, руины, якоря и куски линий, её занятые.

    Хозяин ищется через `cell_of`, а не «попала ли точка в границы»: границы
    клеток общие, и угловая точка (`far_s` стоит ровно в углу) по инклюзивным
    границам принадлежала бы сразу четырём клеткам. `cell_of` даёт один ответ на
    точку, и тот же ответ повторит рантайм на C# — иначе владение разъедется
    молча, и объект оживёт в клетке, которую никто не генерировал.
    """
    def mine(x, z):
        return cell_of(x, z) == (i, j)

    out = {"nodes": [n["k"] for n in NODES if mine(n["x"], n["z"])],
           "ruins": [r["k"] for r in RUINS if mine(r["x"], r["z"])],
           "anchors": [a["k"] for a in ANCHORS if mine(a["x"], a["z"])],
           "lines": []}
    for (name, pts) in [("rail", RAIL_LINE)] + [("road %d" % k, p)
                                           for k, p in enumerate(ROAD_LINES)]:
        if (i, j) in line_cells(pts):
            out["lines"].append(name)
    return out


# ---------------------------------------------------------------- расстояния

def leg(a: tuple[float, float], b: tuple[float, float]) -> float:
    return math.hypot(b[0] - a[0], b[1] - a[1])


def depot_to_station() -> float:
    return leg(DEPOT, (0.0, 0.0))


# ---------------------------------------------------------------- инварианты

def ang_delta(a: float, b: float) -> float:
    """Меньшая разность двух азимутов в градусах, всегда от 0 до 180."""
    return abs((a - b + 180.0) % 360.0 - 180.0)


def _grid_dist(v: float) -> float:
    """Расстояние до ближайшей ЛИНИИ сетки клеток (они на +/- 300 mod 600)."""
    w = abs(v) % BLK
    return abs(w - BLK * 0.5)


def invariants():
    """Проверяемые утверждения о раскладке: (имя, ok, разбор).

    Проверка здесь важнее кода: в наброске шага 0 магистраль уходила из чаши под
    азимутом 24 градуса, то есть сквозь сплошной вал гребня. Числами это видно
    сразу, а на плане сверху — нет.
    """
    out = []

    ok = cell_of(*DEPOT) == DEPOT_CELL and cell_of(0.0, 0.0) == (0, 0)
    ncells = len(range(CELL_MIN, CELL_MAX + 1))
    out.append(("депо в (-2,-2), станция в (0,0)", ok,
                "клетка депо %s, сторон сетки %d, клеток %d" % (
                    cell_of(*DEPOT), ncells, ncells * ncells)))

    d = depot_to_station()
    seg = fog_distance(0.01)
    (walk, run, ride) = travel(d)
    out.append(("станция за кадром: силуэт, а не меш", d > FAR_CLIP,
                "%.0f м = %.1f отрезков тумана по %.0f м; пешком %.0f мин, "
                "бегом %.0f мин, на транспорте %.0f с" % (
                    d, d / seg, seg, walk, run, ride)))

    off = min(min(_grid_dist(p["x"]), _grid_dist(p["z"]))
              for p in list(NODES) + list(ANCHORS))
    out.append(("узлы и якоря не стоят на границах клеток", off >= 40.0,
                "ближайшее к линии сетки %.0f м" % off))

    # Связность тёплого каркаса: к каждому обжитому узлу надо уметь дойти, не
    # выходя из тепла. Проверяется по линиям, а не «на глаз по плану»: узел может
    # стоять в тёплом прямоугольнике, но между ним и депо — ни одной тёплой нити.
    # Магистраль в списке нет намеренно: путь холоден, и связывать им тепло —
    # значит молча вернуть то, чего в каноне нет.
    lines = [("дорога %d" % i, p) for i, p in enumerate(ROADS)]

    def touches(pts, rect):
        for i in range(len(pts) - 1):
            (ax, az), (bx, bz) = pts[i], pts[i + 1]
            steps = max(2, int(math.hypot(bx - ax, bz - az) / 5.0))
            for s in range(steps + 1):
                t = s / steps
                if _rect_dist(ax + (bx - ax) * t, az + (bz - az) * t, rect) <= 0.0:
                    return True
        return False

    reach = {}
    for n in NODES:
        if not n["rect"]:
            continue
        hit = [name for (name, pts) in lines if touches(pts, n["rect"])]
        reach[n["k"]] = hit
    shared = {}
    for a in reach:
        for b in reach:
            if a < b:
                inter = set(reach[a]) & set(reach[b])
                if inter:
                    shared[(a, b)] = sorted(inter)[0]
    depot = "depot"
    linked = {depot}
    frontier_ = [depot]
    while frontier_:
        cur = frontier_.pop()
        for (a, b), _line in shared.items():
            nxt = b if a == cur else (a if b == cur else None)
            if nxt and nxt not in linked:
                linked.add(nxt)
                frontier_.append(nxt)
    orphans = [k for k in reach if k not in linked]
    out.append(("к каждому тёплому узлу можно дойти в тепле", not orphans,
                "связано %d из %d, без нитей: %s" % (
                    len(linked), len(reach), ", ".join(orphans) or "нет")))

    # Путь холоден. Ось магистрали вне дворов обязана быть вне тепла: если тут
    # станет тепло, значит рельсовая линия легла в чужую тёплую нить (или кто-то
    # вернул `WARM_RAIL_HALF`), и по миру можно будет «греться» на балласте.
    def in_pad(x: float, z: float) -> bool:
        return any(_rect_dist(x, z, n["rect"]) <= PAD_SKIRT
                   for n in NODES if n["rect"])

    warm_rail = [(s, x, z) for (s, x, z) in line_samples(RAIL_LINE)
                 if is_warm(x, z) and not in_pad(x, z)]
    out.append(("магистраль холодна: её ось вне дворов не даёт тепла",
                not warm_rail,
                "точек оси в тепле вне дворов: %d%s" % (
                    len(warm_rail),
                    "" if not warm_rail else ", первая (%.0f,%.0f)" % (
                        warm_rail[0][1], warm_rail[0][2]))))

    # Нити разведены: нигде вне дворов ось дороги не должна подходить к оси
    # рельса ближе плеча. Совпадение осей — это не «рядом идут», а одна канава,
    # в которой полотно лежит под шпалами и столы двух линий спорят за отметку.
    tight = []
    gaps = []
    for ln in TRANSPORT[1:]:
        for (s, x, z) in ln["samples"]:
            if in_pad(x, z):
                continue
            (d, _sr, _dir) = project_to_line(x, z, RAIL_LINE)
            gaps.append((d, ln["k"], x, z))
            if d < RAIL_SHOULDER:
                tight.append((d, ln["k"], x, z))
    tight.sort()
    gaps.sort()
    out.append(("нити разведены: дорога не идёт в путевой выемке", not tight,
                "мин. плечо %.0f м у %s (%.0f,%.0f), норма %.0f м · точек ближе "
                "нормы: %d" % (gaps[0][0], gaps[0][1], gaps[0][2], gaps[0][3],
                                RAIL_SHOULDER, len(tight))))

    # Магистраль кончается во дворе станции: её северная точка — тупик, дальше
    # пути нет. Это не вечный инвариант, а страховка от молчаливого «продолжим
    # по оси дороги»: куда вести линию дальше, решается слоем E и позже.
    st = node("station")
    end = RAIL[-1]
    zs = [z for (_s, _x, z) in line_samples(RAIL_LINE)]
    inside = (st["rect"][0] <= end[0] <= st["rect"][1]
              and st["rect"][2] <= end[1] <= st["rect"][3])
    out.append(("магистраль обрывается во дворе станции",
                inside and abs(max(zs) - end[1]) < 1e-6
                and max(zs) <= st["rect"][3] + 1e-6,
                "тупик (%.0f,%.0f) внутри двора: %s · севернее тупика %.0f м"
                % (end[0], end[1], inside, max(zs) - end[1])))

    # Два инварианта про вал и чашу отсюда ушли вместе с самой чашей: «вал не
    # оставляет каньона на плите» и «чашу депо трогает только транспортный
    # коридор» охраняли границу уровня, которой в мире больше нет.

    # Пол двора меряется там, где двору ничего не перечит. Хозяйская линия
    # проходит через узел по своему уклону, и двор держится её отметки — это не
    # плоский блин, а отсыпанная площадка в уровне пути: наклонён вдоль линии и
    # горизонтален поперёк. Чужой коридор (дорога сквозь двор) точечно режет
    # двор до своей постели, и такие точки из замера выбрасываются. Остальные
    # обязаны сойтись с `pad_level` на два сантиметра: на этом полу стоят
    # платформы, ворота и навес, и 2 см здесь — это то, на чём робот качается.
    off_grade_floor = []
    cut = 0
    for n in NODES:
        if not n["rect"] or n["k"] in PAD_SKIP:
            continue
        host = PAD_HOST.get(n["k"])
        (x0, x1, z0, z1) = n["rect"]
        worst = 0.0
        for t in range(9):
            for k in range(9):
                (px, pz) = (x0 + (x1 - x0) * t / 8.0, z0 + (z1 - z0) * k / 8.0)
                want = pad_level(n, px, pz)
                f = transport_floor(px, pz)
                if f is not None and f["mask"] > 1e-3:
                    if host is not None and f["k"] == host[0]["k"]:
                        # Хозяйский коридор во дворе — это его же постель: пол
                        # двора опущен в уровень дна ровно на глубину выемки.
                        want -= CUT_DEPTH[host[0]["kind"]]
                        continue
                    cut += 1
                    continue        # чужой коридор во дворе — здесь хозяин он
                worst = max(worst, abs(world_height(px, pz) - want))
        if worst > 0.02:
            off_grade_floor.append("%s %.3f" % (n["k"], worst))
    out.append(("тёплые дворы лежат в уровне своей хозяйской линии (допуск 2 см)",
                not off_grade_floor,
                "точек под чужим коридором %d; пол двора разошёлся со столом: %s" % (
                    cut, ", ".join(off_grade_floor) or "нет")))

    # Съезд с плиты на площадку меряется шагом, а не верой в формулу: профиль
    # smootherstep даёт в полтора-два раза круче, чем «перепад на юбку», и именно
    # это круче всего на узлах, вставших на склоне. Плюс юбки не должны сливаться:
    # две площадки впритирку — это уже одна площадка, а не два узла.
    grade = 0.0
    steepest = ("", 0.0)
    for (n, _level, skirt) in _PADS:
        (x0, x1, z0, z1) = n["rect"]
        (cx, cz) = ((x0 + x1) / 2.0, (z0 + z1) / 2.0)
        for (sx, sz, px, pz) in ((1, 0, x1, cz), (-1, 0, x0, cz),
                                 (0, 1, cx, z1), (0, -1, cx, z0)):
            prev = world_height(px, pz)
            (plx, plz) = (px, pz)
            steps = int((skirt + 20.0) / 5.0)
            for k in range(1, steps + 1):
                (qx, qz) = (px + sx * k * 5.0, pz + sz * k * 5.0)
                f = transport_floor(qx, qz)
                if f is not None and f["mask"] > 1e-3:
                    continue        # стенка коридора — это не съезд двора
                h = world_height(qx, qz)
                # Делить надо на расстояние между уцелевшими пробами, а не на
                # шаг сетки: после пропуска коридора соседние меряемые точки
                # стоят в десятках метров друг от друга, и делить их разницу на
                # пять метров значит изобрести уклон, которого на земле нет.
                run = math.hypot(qx - plx, qz - plz) or 1.0
                if abs(h - prev) / run > grade:
                    grade = abs(h - prev) / run
                    steepest = (n["k"], skirt)
                prev = h
                (plx, plz) = (qx, qz)
    near = []
    for a in _PADS:
        for b in _PADS:
            if a[0]["k"] < b[0]["k"] and leg((a[0]["x"], a[0]["z"]),
                                             (b[0]["x"], b[0]["z"])) < a[2] + b[2] + 40.0:
                near.append("%s+%s" % (a[0]["k"], b[0]["k"]))
    out.append(("съезды к площадкам пологи, юбки не сливаются",
                grade <= 0.25 and not near,
                "круче всего %.2f у %s (юбка %.0f м, цель <= 0.25), "
                "вплотную: %s" % (grade, steepest[0], steepest[1],
                                   ", ".join(near) or "нет")))

    warm_in_crack = [n["k"] for (n, _y, _s) in _PADS if in_crack(n["x"], n["z"])]
    warm_lines = []
    for (name, pts) in [("линия", RAIL)] + [("дорога %d" % i, p)
                                           for i, p in enumerate(ROADS)]:
        if any(in_crack(x, z) for (x, z) in pts):
            warm_lines.append(name)
    out.append(("разлом не режет тёплый каркас",
                not warm_in_crack and not warm_lines,
                "площадок в корыте %d, линий в корыте %d" % (
                    len(warm_in_crack), len(warm_lines))))

    cs = cells()
    out.append(("чанки: число, контент, residency",
                len(cs) == ncells * ncells,
                "клеток %d, с контентом %d, живёт при радиусе 1 — %d, "
                "террейна %d трис/клетка и %d трис в памяти" % (
                    len(cs), sum(1 for c in cs if c["content"]),
                    len(resident_cells(*DEPOT, 1)), cell_tris(), resident_tris(1))))

    # Клетка как контейнер. Проверяется не «красиво ли разбито», а три вещи, без
    # которых следующий шаг врёт молча: у каждого объекта есть ровно одна клетка-
    # хозяин; ни одна клетка не получает землю дважды (квадрат авторской земли
    # депо и генератор клетки); и границы этого квадрата кратны шагу решётки —
    # иначе дырку в клетке под квадратом пришлось бы резать дробными квадами, и
    # на её крае был бы видимый шов.
    owners = {}
    for c in cs:
        items = cell_items(c["i"], c["j"])
        for (kind, keys) in (("узел", items["nodes"]), ("руина", items["ruins"]),
                             ("якорь", items["anchors"])):
            for key in keys:
                owners.setdefault((kind, key), set()).add((c["i"], c["j"]))
    expected = ([("узел", n["k"]) for n in NODES] + [("руина", r["k"]) for r in RUINS]
                + [("якорь", a["k"]) for a in ANCHORS])
    homeless = ["%s %s" % k for k in expected if k not in owners]
    # Ключи классов пересекаются (станция — и узел, и якорь с одним именем),
    # поэтому «двух хозяев» значит две РАЗНЫЕ клетки у одной записи.
    # Клетка как контейнер. Раньше сюда входил ещё один пункт — квадрат авторской
    # земли депо и его «не генерировать клетку под ним». С тех пор как депо стало
    # обычным чанком, исключения кончились: все 121 клетка генерируются одинаково,
    # и двух слоёв снега в одной точке больше нет по построению, а не по оговорке.
    doubled = ["%s %s -> %s" % (k[0], k[1], sorted(owners[k]))
               for k in owners if len(owners[k]) > 1]
    out.append(("клетки: у каждого объекта есть хозяин, у каждой клетки есть земля",
                not homeless and not doubled,
                "объектов %d, без клетки: %s, с двумя: %s; клеток генерируется "
                "%d из %d, исключений нет" % (
                    len(expected), ", ".join(homeless) or "нет",
                    ", ".join(doubled) or "нет", len(cs), ncells * ncells)))

    # Линии режутся по клеткам, и это то место, где чанки обязаны сойтись числом,
    # а не «на глаз по превью». Стык считается отдельно от генератора: точка
    # перехода ищется половинным делением по самой трассе, а потом проверяется,
    # что оба куска (у каждой из двух клеток) заканчиваются ровно в ней и что
    # она лежит на линии решётки. Плюс длина: сумма кусков обязана давать длину
    # трассы — иначе где-то либо зазор, либо нахлёст, который на 6 км не видно.
    joints = 0
    off_grid = []
    open_joints = []
    length_gap = []
    termini = []
    for ln in TRANSPORT:
        pts = ln["pts"]
        for (p, ca, cb) in line_crossings(pts):
            # Стык на самом конце ломаной — это не стык двух чанков, а обрыв
            # линии. Требовать от него куска соседней клетки нельзя; зато можно
            # потребовать, чтобы он стоял ровно на линии решётки: тогда следующий
            # чанк продолжит трассу без шва, а не начнёт её в тридцати метрах
            # от конца рельса.
            last = min(leg(p, pts[0]), leg(p, pts[-1]))
            if last < 1e-6:
                termini.append("%s на границе %d:%d" % (ln["k"], ca[0], ca[1]))
                if _grid_dist(p[0]) > 1e-6 and _grid_dist(p[1]) > 1e-6:
                    off_grid.append("%s конец (%.0f;%.0f)" % (ln["k"], p[0], p[1]))
                continue
            joints += 1
            if _grid_dist(p[0]) > 1e-6 and _grid_dist(p[1]) > 1e-6:
                off_grid.append("%s (%.0f;%.0f)" % (ln["k"], p[0], p[1]))
            for c in (ca, cb):
                ends = []
                for sp in line_spans(pts, c[0], c[1]):
                    ends += [sp[0], sp[-1]]
                if not any(math.hypot(p[0] - e[0], p[1] - e[1]) < 1e-6
                           for e in ends):
                    open_joints.append("%s в %d:%d" % (ln["k"], c[0], c[1]))
        total = 0.0
        for (i, j) in line_cells(pts):
            for sp in line_spans(pts, i, j):
                total += sum(leg(a, b) for (a, b) in zip(sp, sp[1:]))
        if abs(total - ln["len"]) > 0.05:
            length_gap.append("%s: куски %.1f против %.1f" % (ln["k"], total, ln["len"]))
    out.append(("линия: куски клеток сходятся на рёбрах решётки",
                not off_grid and not open_joints and not length_gap,
                "линий %d, стыков %d; не на решётке: %s; без куска клетки: %s; "
                "длина кусков не сходится: %s; обрывов на границе клетки: %s" % (
                    len(TRANSPORT), joints, ", ".join(off_grid) or "нет",
                    ", ".join(open_joints) or "нет",
                    ", ".join(length_gap) or "нет",
                    ", ".join(termini) or "нет")))

    # Продольный профиль стола: уклон и то, насколько он уходит от плиты. Это
    # не эстетика — 19-метровый уход есть ровно там, где рельсовая линия
    # пересекает долгую волну макрельефа, и без предела уклона путь превратился
    # бы в каньон со стенами, которые никто не заказывал.
    over_grade = []
    over_depth = []
    gmax_seen = {}
    for ln in TRANSPORT:
        tb = ln["table"]
        ds = tb[1][0] - tb[0][0]
        g = max(abs(tb[i + 1][1] - tb[i][1]) / ds for i in range(len(tb) - 1))
        dev = max(abs(plate_height(*point_at_distance(ln["pts"], s)) - y)
                  for (s, y) in tb)
        gmax_seen[ln["kind"]] = max(gmax_seen.get(ln["kind"], 0.0), g)
        if g > ln["grade"][1] + 1e-3:
            over_grade.append("%s %.1f%%" % (ln["k"], g * 100.0))
        if dev > CUT_DEV_MAX:
            over_depth.append("%s %.1f м" % (ln["k"], dev))
    out.append(("стол: уклон линии и глубина выемки в пределах",
                not over_grade and not over_depth,
                "уклон: рельсовая %.2f%% (норма %.1f%%), дороги %.2f%% (норма "
                "%.1f%%); уход от плиты максимум %.1f м (норма %.1f м); "
                "превышений: %s" % (
                    gmax_seen["rail"] * 100.0, RAIL_GRADE[1] * 100.0,
                    gmax_seen["road"] * 100.0, ROAD_GRADE[1] * 100.0,
                    max(abs(plate_height(*point_at_distance(ln["pts"], s)) - y)
                        for ln in TRANSPORT for (s, y) in ln["table"]),
                    CUT_DEV_MAX,
                    ", ".join(over_grade + over_depth) or "нет")))

    # «В чаше депо только срезанный пенёк» убран вместе с чашей: якорь у депо
    # и остался пнём на человеческий размер, но держать его теперь нечем —
    # кольца, внутри которого он был бы «в чаше», в мире больше нет.

    # Руины — класс контента вместо гигантских башен. Проверка держит их в
    # объявленном диапазоне, не даёт встать в тёплый каркас (руина в тепле — это
    # уже постройка) и следит, что «достижимая» руина действительно достижима за
    # запас остывания: 90 с пешком — это ~120 м от края тепла, на транспорте
    # ~540 м туда-обратно. `RUIN_REACH` — верхняя граница этого смысла.
    bad_ruins = []
    unreachable = []
    for r in RUINS:
        if not 15.0 <= r["h"] <= 60.0:
            bad_ruins.append("%s h=%.0f" % (r["k"], r["h"]))
        if is_warm(r["x"], r["z"]):
            bad_ruins.append("%s стоит в тепле" % r["k"])
        d = warm_distance(r["x"], r["z"])
        if r["kind"] == "reach" and d > RUIN_REACH:
            unreachable.append("%s (%.0f м)" % (r["k"], d))
    n_reach = sum(1 for r in RUINS
                  if r["kind"] == "reach" and warm_distance(r["x"], r["z"]) <= RUIN_REACH)
    out.append(("руины 15-60 м, вне тепла и в пределах запаса",
                not bad_ruins and not unreachable,
                "всего %d, достижимо %d; дефекты: %s; далеко: %s" % (
                    len(RUINS), n_reach, ", ".join(bad_ruins) or "нет",
                    ", ".join(unreachable) or "нет")))

    thin = [a["k"] for a in ANCHORS if a["h"] < 12.0 or a["w"] < 12.0]
    out.append(("наследие крупнее человеческих размеров", not thin,
                "тоньше 12 м: %s" % (", ".join(thin) or "нет")))

    # Дальний слой. Смысл проверки не в том, что карточки посчитаны (формула
    # одна, она не может разойтись сама с собой), а в трёх вещах, которые
    # правкой якорей ломаются молча: слой обязан остаться внутри дали и целиком
    # в тумане, силуэты не должны сливаться в стену по азимуту, и каждый якорь
    # обязан быть либо читаемым, либо явно списанным в географию — иначе
    # следующий агент рисует меш, которого в кадре не видно.
    cards = far_layer()
    drawn = [c for c in cards if c["draw"]]
    hidden = [c["k"] for c in cards if not c["draw"]]
    want = sorted(a["k"] for a in ANCHORS if a["kind"] != "stump")
    got = sorted(c["k"] for c in cards)
    far_edge = max(FAR_CLIP - FAR_CARD_DISTANCE, 0.0)
    tall = [c["k"] for c in drawn if c["deg"] > FAR_TOP_MAX_DEG]
    gaps = []
    for (i, c) in enumerate(drawn):
        for o in drawn[i + 1:]:
            half = angular_width(c["w"] * 0.5, FAR_CARD_DISTANCE) + \
                angular_width(o["w"] * 0.5, FAR_CARD_DISTANCE)
            gaps.append((ang_delta(c["bearing"], o["bearing"]) - half,
                         "%s+%s" % (c["k"], o["k"])))
    (gap, pair) = min(gaps) if gaps else (99.0, "нет пар")
    (lo, lo_k) = min((c["dark"], c["k"]) for c in drawn)
    top = max(c["deg"] for c in drawn)
    ok_far = (want == got and far_edge >= 20.0 and drawn
              and fog_t(FAR_CARD_DISTANCE) <= 0.01
              and gap >= 1.0 and lo >= SKY_CONTRAST_MIN and not tall)
    out.append(("дальний слой: карточки внутри дали, читаемы и не сливаются",
                ok_far,
                "карточек %d из %d якорей, не читаются и остаются на бумаге: %s; "
                "запас до `farClip` %.0f м, туман оставляет %.2f %% цвета, зазор "
                "по азимуту %.1f° (%s), контраст худшего %.2f (%s) при норме %.2f, "
                "макушка %.1f° (норма %.0f°): %s" % (
                    len(drawn), len(want), ", ".join(hidden) or "нет", far_edge,
                    fog_t(FAR_CARD_DISTANCE) * 100.0, gap, pair, lo, lo_k,
                    SKY_CONTRAST_MIN, top, FAR_TOP_MAX_DEG,
                    ", ".join(tall) or "нет")))

    # Аномалия обязана оставаться чистым куском неба. Диск живёт в фиксированном
    # направлении, а «Откос», направление взгляда и силуэты якорей двигаются, —
    # без этой пробы тело может утонуть в силуэте и перестать читаться, и никто
    # этого по плану сверху не увидит. Считаем только азимут: он консервативнее
    # вертикали (сила тела вниз с площадки не видна), а зазор берём от края
    # силуэта до края диска, а не между центрами.
    clr = 99.0
    tight = ""
    for a in ANCHORS:
        dx = a["x"] - SKY_VIEW["x"]
        dz = a["z"] - SKY_VIEW["z"]
        dist = math.hypot(dx, dz)
        if dist < 1.0:
            continue
        b = math.degrees(math.atan2(dx, dz)) % 360.0
        half = math.degrees(math.atan2(a["w"] * 0.5, dist))
        gap = ang_delta(b, ANOMALY["bearing"]) - half - ANOMALY["radius"]
        if gap < clr:
            (clr, tight) = (gap, a["k"])
    out.append(("аномалия не перекрывает силуэты якорей с площадки «Откоса»",
                clr >= 3.0,
                "ближайший %s, угловой зазор %.1f° (норма 3°); диск %.1f° на "
                "азимуте %.0f°, высоте %.0f°" % (
                    tight, clr, ANOMALY["radius"], ANOMALY["bearing"],
                    ANOMALY["elev"])))
    return out


def report() -> str:
    """Однострочный отчёт по инвариантам — для `check_world.py` и для глаз."""
    return "\n".join("%s %s — %s" % ("OK  " if ok else "FAIL", name, detail)
                     for (name, ok, detail) in invariants())


