SPRINT_SPEED = 6.5
RIDE_SPEED = 12.0


def travel(d: float) -> tuple[float, float, float]:
    """(минут пешком, минут бегом, секунд на транспорте) для расстояния."""
    return (d / WALK_SPEED / 60.0, d / SPRINT_SPEED / 60.0, d / RIDE_SPEED)


