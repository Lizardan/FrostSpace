def smooth01(edge0: float, edge1: float, value: float) -> float:
    """Сглаживание тем же smootherstep, что внутри `frontier_layout`.

    Приватный хелпер чужого модуля не зовётся (в проекте так не делают), но поля
    высот обязаны смешиваться одинаково: иначе на стыке чаши и плиты появился бы
    излом, который никто не заказывал.
    """
    if edge1 <= edge0:
        return 1.0 if value >= edge1 else 0.0
    t = min(max((value - edge0) / (edge1 - edge0), 0.0), 1.0)
    return t * t * (3.0 - 2.0 * t)


def macro_height(x: float, z: float) -> float:
    """Сумма долгих волн плиты в мировой точке, метры."""
    h = 0.0
    for (amp, period, bearing, phase) in MACRO_WAVES:
        b = math.radians(bearing)
        s = (x * math.sin(b) + z * math.cos(b)) / period * 2.0 * math.pi
        h += amp * math.sin(s + phase)
    return h


def crack_drop(x: float, z: float) -> float:
    """Насколько плита НИЖЕ нормы в разломе: корыто минус вал по краю."""
    d = FL.dist_to_polyline(x, z, CRACK["pts"])
    q = d / CRACK["half"]
    trench = CRACK["depth"] * max(0.0, 1.0 - q * q)
    lip = CRACK["lip"] * math.exp(-(((d - CRACK["half"] * 1.15) /
                                     (CRACK["half"] * 0.45)) ** 2))
    return trench - lip


def wall_fill(lx: float, lz: float) -> float:
    """Сколько высоты вала возвращается плите за стеной.

    Прорыв гребня в `frontier_layout` не ограничен радиусом: он вычитает вал по
    всему азимуту коридора, и без доливки дорога от депо до станции идёт по
    каньону глубиной 8.5 м через всю плиту. Внутри `RIDGE_FILL[0]` доливка ноль —
    принятый кадр прибытия остаётся полем сцены, и это отдельный инвариант.
    """
    r = math.hypot(lx, lz)
    w = smooth01(RIDGE_FILL[0], RIDGE_FILL[1], r)
    if w <= 0.0:
        return 0.0
    full = FL.RIDGE_H * smooth01(FL.EDGE_R, FL.RIDGE_R, r)
    return w * (full - FL.ridge_height(lx, lz))


def plate_height(x: float, z: float) -> float:
    """Плита мира до выравнивания площадок: чаша сцены + макрельеф - разлом.

    Порядок слоёв важен и он не очевидный. `FL.ground_height` уже прорезал под
    путём коридор с плоским дном, а макрельеф — это форма дальней плиты. Если
    добавить макрельеф поверх готовой выемки, дно коридора поедет вверх вместе с
    плитой: «дно на одной отметке на всех 340 м» перестаёт быть правдой ровно
    там, где линия уходит за 300 м, и состав висит над рельефом или тонет в нём.
    Поэтому выемка накладывается ещё раз — уже после макрельефа. Внутри 300 м
    гейт равен нулю, и вторая application ничего не меняет: инвариант «чаша не
    тронута» от этого шага не двигается ни на микрометр.
    """
    lx, lz = to_frontier(x, z)
    r = math.hypot(lx, lz)
    h = FL.ground_height(lx, lz)
    k = smooth01(MACRO_GATE[0], MACRO_GATE[1], r)
    if k > 0.0:
        h += k * macro_height(x, z)
        m = FL.corridor_mask(lx, lz)
        if m > 0.0:
            h += (FL.TRACK_FLOOR_Y - h) * m
    h += wall_fill(lx, lz)
    h += FL.drift_sum(x, z, ANCHOR_DRIFTS)
    h -= crack_drop(x, z)
    return h


def _pads():
    """(узел, отметка, юбка) — считается один раз при импорте.

    Во-первых, звать `plate_height` на каждую точку каждой клетки нельзя:
    генератор террейна получил бы квадратичное время. Во-вторых, юбка площадки
    растёт до тех пор, пока съезд с плиты на площадку не станет пологим
    (`PAD_GRADE`): у узла на склоне перепад в 13 м на сорокаметровой юбке — это
    стена, в которую робот упирается носом, а не площадь.
    """
    out = []
    for n in NODES:
        if not n["rect"] or n["k"] in PAD_SKIP:
            continue
        level = plate_height(n["x"], n["z"])
        (x0, x1, z0, z1) = n["rect"]
        (cx, cz) = ((x0 + x1) * 0.5, (z0 + z1) * 0.5)
        skirt = PAD_SKIRT
        for _ in range(8):
            edge = [(x0 - skirt, z0 - skirt), (x1 + skirt, z0 - skirt),
                    (x0 - skirt, z1 + skirt), (x1 + skirt, z1 + skirt),
                    (x0 - skirt, cz), (x1 + skirt, cz),
                    (cx, z0 - skirt), (cx, z1 + skirt)]
            drop = max(abs(plate_height(ex, ez) - level) for (ex, ez) in edge)
            if drop <= skirt * PAD_GRADE or skirt >= PAD_SKIRT_MAX:
                break
            skirt = min(PAD_SKIRT_MAX, max(skirt * 1.5, drop / PAD_GRADE))
        out.append((n, level, skirt))
    return out


_PADS = _pads()

#: Отметка каждой тёплой площадки: берётся из плиты один раз и больше не
#: меняется, поэтому у пэда есть число, на котором он лежит.
PAD_LEVEL = {n["k"]: y for (n, y, _s) in _PADS}


def pad_skirt(k: str) -> float:
    """Фактическая юбка площадки узла: её меряет `check_world.py`."""
    for (n, _y, s) in _PADS:
        if n["k"] == k:
            return s
    return 0.0


def world_height(x: float, z: float) -> float:
    """Высота снега в мировой точке: плита, у которой тёплые узлы срезаны вровень.

    Площадка обязана быть плоской по той же причине, что и двор депо: на 6.6 км
    волны дают под полом узла десятки сантиметров, и робот, стоящий на плите,
    либо проваливается в неё, либо висит над ней. Внутри границ узла — ровно
    `PAD_LEVEL`, снаружи за юбкой — ровно плита.

    Порядок здесь важен и он ровно тот, к которому пришло депо: сначала плита,
    потом коридор транспорта, потом площадки узлов. Коридор до площадок, потому
    что дорога приходит к узлу и должна коснуться его пола, а не перерезать
    уже плоскую площадь. Площадки после коридора, потому что двор узла — хозяин
    своей земли: путь, входящий в площадку, кончается на её полу, а не прорезает
    его обратно до своей отметки.
    """
    h = transport_cut(x, z, plate_height(x, z))
    for (n, level, skirt) in _PADS:
        d = _rect_dist(x, z, n["rect"])
        if d >= skirt:
            continue
        h += (level - h) * (1.0 - smooth01(0.0, skirt, d))
    return h


def pad_blend(x: float, z: float) -> float:
    """Доля, которой площадка узла хозяин в точке: 0 — чистая плита или коридор.

    Отдельная функция нужна не генератору, а проверке: коридор проходит через
    тёплые узлы, и внутри их площадки пол узла перекрывает стол намеренно
    (двор обязан быть плоским). Мерить «выемка совпала со столом» надо там, где
    площадки нет, иначе проверка падала бы на собственном порядке слоёв.
    """
    best = 0.0
    for (n, _level, skirt) in _PADS:
        d = _rect_dist(x, z, n["rect"])
        if d >= skirt:
            continue
        best = max(best, 1.0 - smooth01(0.0, skirt, d))
    return best


def in_crack(x: float, z: float) -> bool:
    """Точка в корыте разлома (не в валу): сюда не должна заходить тёплая линия."""
    return FL.dist_to_polyline(x, z, CRACK["pts"]) < CRACK["half"] * 0.9


# ---------------------------------------------------------------- чанки

#: Шаг, которым ломаная превращается в список клеток. Концы сегментов для
#: этого не годятся: сегмент депо→станция стоит концами в двух клетках, а
#: на деле проходит через четыре, и «клетка занята линией» пришлось бы
#: решать на глаз. Шаг — метр: скруглённый угол заходит в угловую клетку
#: на пару метров, и при шаге в 5 м такая клетка терялась — кусок линии в
#: ней есть, а в списке её нет, и длина кусков не сходилась с длиной трассы.
LINE_SAMPLE = 1.0


def line_cells(pts, step: float = LINE_SAMPLE):
    """Клетки, по которым идёт ломаная, в порядке следования и без повторов."""
    out = []
    for (a, b) in zip(pts, pts[1:]):
        d = math.hypot(b[0] - a[0], b[1] - a[1])
        n = max(1, int(d / step + 0.5))
        for k in range(n + 1):
            t = k / n
            (i, j) = cell_of(a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t)
            if CELL_MIN <= i <= CELL_MAX and CELL_MIN <= j <= CELL_MAX:
                if not out or out[-1] != (i, j):
                    out.append((i, j))
    return out


def _clip_t(a, b, rect):
    """Liang-Barsky: доля сегмента, лежащая внутри прямоугольника клеток."""
    (x0, x1, z0, z1) = rect
    (dx, dz) = (b[0] - a[0], b[1] - a[1])
    (t0, t1) = (0.0, 1.0)
    for (p, q) in ((-dx, a[0] - x0), (dx, x1 - a[0]),
                   (-dz, a[1] - z0), (dz, z1 - a[1])):
        if p == 0.0:
            if q < 0.0:
                return None
        else:
            r = q / p
            if p < 0.0:
                if r > t1:
                    return None
                if r > t0:
                    t0 = r
            elif r < t0:
                return None
            elif r < t1:
                t1 = r
    if t1 < t0:
        return None
    return (t0, t1)


def _lerp(a, b, t):
    return (a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t)


def line_spans(pts, i: int, j: int):
    """Куски ломаной внутри клетки: список полилиний не короче двух точек.

    Куски режутся ровно по рёбрам решётки, поэтому соседняя клетка получает
    тот же конец: обе стороны держат одну точку, и рельс на стыке не может
    разойтись «на глаз» — это проверяет инвариант «стыки линии».
    """
    rect = cell_bounds(i, j)
    spans = []
    cur = []
    for (a, b) in zip(pts, pts[1:]):
        cut = _clip_t(a, b, rect)
        if cut is None:
            if len(cur) >= 2:
                spans.append(cur)
            cur = []
            continue
        (pa, pb) = (_lerp(a, b, cut[0]), _lerp(a, b, cut[1]))
        if cur:
            gap = math.hypot(pa[0] - cur[-1][0], pa[1] - cur[-1][1])
            if gap > 1e-6:
                if len(cur) >= 2:
                    spans.append(cur)
                cur = [pa]
        else:
            cur = [pa]
        if math.hypot(pb[0] - cur[-1][0], pb[1] - cur[-1][1]) > 1e-9:
            cur.append(pb)
    if len(cur) >= 2:
        spans.append(cur)
    return spans


def content_cells():
    """Клетки карты, где что-то стоит: узел, якорь или кусок линии.

    Остальные — пустошь: общая заготовка террейна, а не авторская сцена. Отсюда
    честное число: 121 клетка — это не 121 сцена в сборке. Линия учитывается
    образцами (`line_cells`), а не концами сегментов: иначе клетка, через
    которую путь проходит насквозь, считалась бы пустой, и наполнение её
    обошла бы стороной.
    """
    out = set()

    def add(x: float, z: float) -> None:
        (i, j) = cell_of(x, z)
        if CELL_MIN <= i <= CELL_MAX and CELL_MIN <= j <= CELL_MAX:
            out.add("%d:%d" % (i, j))

    for n in NODES:
        add(n["x"], n["z"])
    for a in ANCHORS:
        add(a["x"], a["z"])
    for r in RUINS:
        add(r["x"], r["z"])
    for pts in (RAIL_LINE,) + tuple(ROAD_LINES):
        for (i, j) in line_cells(pts):
            out.add("%d:%d" % (i, j))
    return out


def cells():
    """Все клетки карты: (i, j, x, z, есть ли в ней контент)."""
    cc = content_cells()
    out = []
    for i in range(CELL_MIN, CELL_MAX + 1):
        for j in range(CELL_MIN, CELL_MAX + 1):
            (x, z) = cell_center(i, j)
            out.append({"i": i, "j": j, "x": x, "z": z,
                        "content": "%d:%d" % (i, j) in cc})
    return out


def resident_cells(x: float, z: float, radius: int = 1):
    """Клетки, живущие в памяти при радиусе загрузки `radius` (окрестность Мура).

    У края карты окрестность обрезается границей: в угловой клетке живёт 4, а не
    9. Это и есть причина, по которой «121» не переводится в 121 сцену.
    """
    (ci, cj) = cell_of(x, z)
    out = []
    for i in range(ci - radius, ci + radius + 1):
        for j in range(cj - radius, cj + radius + 1):
            if CELL_MIN <= i <= CELL_MAX and CELL_MIN <= j <= CELL_MAX:
                out.append((i, j))
    return out


def resident_tris(radius: int = 1) -> int:
    """Треугольников террейна в памяти при радиусе `radius` в полной окрестности."""
    side = 2 * radius + 1
    return side * side * cell_tris()


#: Квадрат авторской земли депо и его «не генерировать клетку под ним» убраны:
#: с тех пор как депо стало обычным чанком клетки (−2,−2), исключений в сетке
#: больше нет. История решения — ADR 0036, п. 2.


def cell_items(i: int, j: int):
    """Что стоит в клетке: узлы, руины, якоря и куски линий, её занятые.

    Хозяин ищется через `cell_of`, а не «попала ли точка в границы»: границы
    клеток общие, и угловая точка (`far_s` стоит ровно в углу) по инклюзивным
    границам принадлежала бы сразу четырём клеткам. `cell_of` даёт один ответ на
    точку, и тот же ответ повторит рантайм на C# — иначе владение разъедется
    молча, и объект оживёт в клетке, которую никто не генерировал.
    """
    def mine(x, z):
        return cell_of(x, z) == (i, j)

    out = {"nodes": [n["k"] for n in NODES if mine(n["x"], n["z"])],
           "ruins": [r["k"] for r in RUINS if mine(r["x"], r["z"])],
           "anchors": [a["k"] for a in ANCHORS if mine(a["x"], a["z"])],
           "lines": []}
    for (name, pts) in [("rail", RAIL_LINE)] + [("road %d" % k, p)
                                           for k, p in enumerate(ROAD_LINES)]:
        if (i, j) in line_cells(pts):
            out["lines"].append(name)
    return out


