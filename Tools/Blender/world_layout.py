#: Тот же туман и та же дальность, что в принятой `Frontier` (STYLE.md раздел
#: «Туман дали в Frontier»): 99 % контраста теряется на 358 м, а `farClip`
#: обрывает геометрию на 400 м. Значит всё наследие дальше 400 м — это
#: **дальний слой** (силуэты), а не меш, и мир обязан это честно говорить.
FOG_DENSITY = 0.006
FAR_CLIP = 400.0

#: Небо. Почти чёрное, с редкими особенно яркими звёздами — это канон
#: (`WORLD.md`: «Небо почти чёрное, но остались отдельные особо яркие звёзды»,
#: «звёзды видны всегда»). Полёта в космос в игре нет: мы на планете.
#:
#: Облачного потолка в мире НЕТ, и это не экономия, а требование владельца: небо
#: и темнота обязаны быть видны и на дороге, и на открытой местности. Значит
#: вершины якорей не прячутся за слой — тело читается целиком, а масштаб продают
#: силуэт, дистанция, туман и human-реперы (STYLE.md, правило 2).

#: Вертикальный раствор камеры прибытия — тот же `ARRIVAL_FOV` из сцены.
CAM_FOV = FL.ARRIVAL_FOV


def fog_t(d: float) -> float:
    """Доля видимости в тумане: движковая формула Exp^2, `exp(-(d*D)^2)`."""
    return math.exp(-((d * FOG_DENSITY) ** 2))


def fog_distance(t: float) -> float:
    """Расстояние, на котором остаётся доля `t`: обратная функция к `fog_t`."""
    return math.sqrt(-math.log(t)) / FOG_DENSITY


def elevation_angle(eye_y: float, top_y: float, d: float) -> float:
    """Угол до вершины тела с высоты глаза, градусы."""
    return math.degrees(math.atan2(top_y - eye_y, max(d, 1e-6)))


def angular_width(half_w: float, d: float) -> float:
    """Половина угловой ширины тела, градусы: сколько кадра съедает фасад."""
    return math.degrees(math.atan2(half_w, max(d, 1e-6)))


# ---------------------------------------------------------------- движение

#: Скорости взяты из кода, а не из воображения: `_walkSpeed = 1.2` и
#: `_sprintSpeed = 6.5` в `RobotLocomotion.cs:37-38`, множитель R15-курьера 1.15
#: (`Content/Data/Characters/R15_Courier.asset`), `_maxSpeed = 12` у ховербайка
#: (`Hoverbike.cs:41`). Числа стоят рядом с расстояниями специально: 2.2 км
#: дороги — это 26 минут пешком и 3 минуты на транспорте, а не «минута», как
#: записано в RD-04. Расхождение видно сразу и оно поправляется владельцем.
WALK_SPEED = 1.2 * 1.15
SPRINT_SPEED = 6.5
RIDE_SPEED = 12.0


def travel(d: float) -> tuple[float, float, float]:
    """(минут пешком, минут бегом, секунд на транспорте) для расстояния."""
    return (d / WALK_SPEED / 60.0, d / SPRINT_SPEED / 60.0, d / RIDE_SPEED)


# ---------------------------------------------------------------- сетка мира

#: Сторона чанка = клетка сетки = 600 м. Причина — `farClip`, она описана в
#: докстринге модуля.
BLK = 600.0

#: Карта — по пять блоков во все стороны от станции (правка владельца
#: 2026-11-01): клетки от -5 до +5 по обеим осям, всего 121.
CELL_MIN = -5
CELL_MAX = 5

#: Габарит карты в мировых метрах: (x0, x1, z0, z1).
HALF_MAP = (CELL_MAX + 0.5) * BLK
BB = (-HALF_MAP, HALF_MAP, -HALF_MAP, HALF_MAP)

#: Депо — клетка (-2, -2): два блока западнее и два южнее станции (правка
#: владельца 2026-11-01 после замера дороги: 2163 м дали 180 с на транспорте,
#: что вдвое дольше обещанного RD-04 перегона; сдвиг по диагонали даёт 1697 м).
DEPOT_CELL = (-2, -2)
DEPOT = (DEPOT_CELL[0] * BLK, DEPOT_CELL[1] * BLK)


def to_frontier(x: float, z: float) -> tuple[float, float]:
    """Мировая точка -> оси сцены `Frontier` (её ноль = двор депо)."""
    return (x - DEPOT[0], z - DEPOT[1])


def to_world(x: float, z: float) -> tuple[float, float]:
    """Оси сцены `Frontier` -> мировая точка."""
    return (x + DEPOT[0], z + DEPOT[1])


#: Азимут горловины: принятый коридор дороги сквозь вал в осях сцены.
THROAT_DEG = FL.ROAD_BEARING_DEG

#: Азимут станции от депо. С депо в клетке (-2,-2) он равен 45° и попадает
#: ВНУТРЬ принятого прорыва вала (50 +/- 11°) — то есть дорога к станции идёт
#: через горловину почти прямо, без лишнего разворота.
STATION_DEG = FL.bearing_deg(*to_frontier(0.0, 0.0))


def polar(r: float, bearing_deg: float, base=None) -> tuple[float, float]:
    """Точка по дальности и азимуту от базы (по умолчанию — от депо).

    Нужен именно вычисляемый адрес, а не ручные числа: депо передвинули третий
    раз за вечер, и каждый раз ручная геометрия вокруг него расходилась с
    принятым кадром. Азимут — от +Z на восток, как `bearing_deg`.
    """
    (bx, bz) = DEPOT if base is None else base
    b = math.radians(bearing_deg)
    return (bx + r * math.sin(b), bz + r * math.cos(b))


def cell_of(x: float, z: float) -> tuple[int, int]:
    """Клетка точки: ближайший центр, а ровно на границе — клетка с бо́льшим индексом.

    Правило записано через `floor`, а не через `round`, намеренно: `round` в
    Python округляет половину к чётному (round(-1.5) = -2), а его же аналог в C# —
    от нуля. Шесть точек раскладки стоят ровно на границе клетки (`x ≡ ±300` по
    модулю 600: «Откос», «Пролёт», «Плита ангара» и другие), и на них два языка
    дали бы разные клетки — то есть миникарта и раскладка разошлись бы молча.
    `floor(v/BLK + 0.5)` даёт один и тот же ответ в обоих, и его же повторяет
    `WorldGrid.CellOf`.
    """
    return (math.floor(x / BLK + 0.5), math.floor(z / BLK + 0.5))


def cell_center(i: int, j: int) -> tuple[float, float]:
    return (i * BLK, j * BLK)


def cell_bounds(i: int, j: int) -> tuple[float, float, float, float]:
    """Габарит клетки (x0, x1, z0, z1): границы на +/- BLK/2 от центра."""
    h = BLK * 0.5
    return (i * BLK - h, i * BLK + h, j * BLK - h, j * BLK + h)


def in_bounds(x: float, z: float) -> bool:
    return BB[0] <= x <= BB[1] and BB[2] <= z <= BB[3]


#: Шаг решётки террейна одного чанка: 600/15 = 40 делений на сторону, то есть
#: 3200 треугольников на клетку и ~387 тыс. на весь мир. Шаг выбран не «чтобы
#: было красиво», а поперёк главной геометрии: коридор пути с косогорами шире 20 м
#: требует хотя бы три узла на поперечное сечение, иначе в яму попадает один узел,
#: поверхность соединяет его с соседями прямыми палками, и разрез превращается в
#: пологу яму в 60 м, где борта тела пути тонут. 15 м — вдвое чаще, при этом
#: решётка остаётся равномерной по всей карте: шов чанков держится на том, что
#: общая сторона двух соседей — один и тот же набор точек, и никакие вставки
#: локальной детализации этот шов не срывают.
#:
#: Бюджет: 387 тыс. трис террейна на карту, 28 800 в памяти при радиусе 1 —
#: ADR 0029 п.4 (1.5 млн трис в кадре) выдерживается с запасом в 50 раз.
TERRAIN_STEP = 15.0


def cell_tris() -> int:
    """Треугольников террейна в одной клетке — по той же сетке, что и меш."""
    n = int(round(BLK / TERRAIN_STEP))
    return 2 * n * n


