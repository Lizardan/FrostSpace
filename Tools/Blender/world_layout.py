def _flat(lines):
    """Ломаные одним плоским списком [x, z, x, z, ...] плюс число точек каждой.

    Форма для `JsonUtility`: массивы массивов он не читает, а рантайме (миникарта
    по ADR 0036) нужны именно ломаные. Человеческий вид линий остаётся в SVG,
    которые рисует этот же модуль.
    """
    pts, counts = [], []
    for ln in lines:
        counts.append(len(ln))
        for (x, z) in ln:
            pts.extend((x, z))
    return (pts, counts)


