#: Дальность карточек, метры. Число держат три ограничения сразу, и все три —
#: из этого модуля:
#:
#: * внутри `FAR_CLIP` с запасом: камера орбитирует игрока на ±3 м, наблюдатель
#:   поднимается на гребень (+8.5 м), правка тумана возможна — значит не дальше
#:   380 м, иначе часть силуэта просто отсекается;
#: * тело обязано утонуть в тумане, иначе карточка начнёт показывать свой
#:   материал и свет, а не контур: `fog_t(380) = 0.0055` — 0.5 % цвета, то есть
#:   ровно «контур цвета мглы» из ADR 0036 п.6;
#: * ближе ~300 м силуэт получает параллакс, который глаз читает как «стена в
#:   ста метрах», и он же лезет в кадр гребню и лесу.
#:
#: Это НЕ расстояние до якоря. Якорь стоит на 849-4033 м и никогда не будет
#: мешом этой сцены; карточка — обман оптики на 380 м, и живёт она в слое,
#: который следует за наблюдателем (`FarLayer.cs`), а не в географии.
FAR_CARD_DISTANCE = 380.0

#: Доля пути неба от цвета мглы к чёрному зениту. Профиль — тот же, что в
#: `SkyNightStars.shader`: `smoothstep(0.03, 0.28, sin(элевация))`, где 0.03 и
#: 0.28 — синусы 2° и 16° (`STYLE.md` §«Небо»). Порог 0.30 — не «на глаз»:
#: силуэт цвета мглы против неба на этой высоте даёт отношение яркостей 1.4,
#: и это нижняя граница, при которой большой мягкий контур ещё различим. При
#: 0.12 (самый удачный из «дальних») — 1.13, то есть тело на 13 % светлее неба,
#: которое и так его цвет: это не силуэт, а ровное поле.
SKY_CONTRAST_MIN = 0.30

#: Верхняя граница макушки, градусы. Потемнение неба чем выше, тем лучше, а вот
#: угол — мера: тело, чья вершина поднимается выше 30°, занимает треть кадра и
#: перестаёт быть далёким массивом. Именно поэтому якоря 320 м, а не 900 м.
FAR_TOP_MAX_DEG = 30.0


def sky_darkness(elev_deg: float) -> float:
    """Насколько небо над горизонтом уже потемнело на высоте `elev_deg`, доля."""
    s = math.sin(math.radians(elev_deg))
    t = max(0.0, min(1.0, (s - 0.03) / (0.28 - 0.03)))
    return t * t * (3.0 - 2.0 * t)


def far_layer():
    """Карточки дальнего слоя, посчитанные из якорей.

    Размер берётся не из красоты, а из угла: глаз на этой дали читает только
    угловой размер, поэтому карточка занимает ровно столько же, сколько
    настоящий якорь со своей дистанции — `h = D·h_якоря/d`. Сохранить метры
    означало бы получить макушку в 40° выше горизонта, сохранить метры ширины —
    стену вместо башни.

    Позиция — в осях сцены `Frontier` (её ноль = двор депо), потому что слой
    ставится именно там. Ручных чисел здесь нет намеренно: депо двигали трижды,
    и каждый раз всё, записанное «на глаз от депо», расходилось с кадром.
    Округление до сантиметра — здесь, а не в билдере и не в JSON, чтобы и меш,
    и манифест, и сцена читали одно и то же число.

    Флаг `draw` — ответ на вопрос «а зачем?». Якорь, чья макушка не выходит из
    полосы мглы, карточки не получает: тело светлее неба на 3-13 % в кадре
    просто отсутствует, и рисовать его — значит платить мешами за ноль. Такие
    якоря остаются географией карты и миникарты, и инвариант печатает их списком,
    чтобы это решение было видно, а не молча подразумевалось.
    """
    out = []
    for a in ANCHORS:
        # Пенёк — настоящая геометрия в 228 м: он и внутри дали, и внутри тумана,
        # карточка ему не нужна (и была бы ближе него).
        if a["kind"] == "stump":
            continue
        (fx, fz) = to_frontier(a["x"], a["z"])
        d = math.hypot(fx, fz)
        b = FL.bearing_deg(fx, fz) % 360.0
        (cx, cz) = polar(FAR_CARD_DISTANCE, b, base=(0.0, 0.0))
        scale = FAR_CARD_DISTANCE / d
        deg = math.degrees(math.atan2(a["h"], d))
        out.append({
            "k": a["k"], "n": a["n"], "kind": a["kind"], "bearing": round(b, 1),
            "real": round(d, 1),
            "w": round(a["w"] * scale, 2), "h": round(a["h"] * scale, 2),
            "deg": round(deg, 2),
            "dark": round(sky_darkness(deg), 3),
            "draw": sky_darkness(deg) >= SKY_CONTRAST_MIN,
            "x": round(cx, 2), "z": round(cz, 2),
        })
    return out


