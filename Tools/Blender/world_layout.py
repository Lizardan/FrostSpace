def anchor(k: str) -> dict:
    for a in ANCHORS:
        if a["k"] == k:
            return a
    raise KeyError(k)


#: Ширина тела на доле высоты `frac`: к верху фасад уже на четверть. Сужение
#: обязательно: 320 м при постоянной ширине 260 м читаются как труба, а со
#: сужением тело становится постройкой, которую можно опознать с площадки.
def tier_width(frac: float, w: float = 260.0) -> float:
    return w * (1.0 - 0.25 * frac)


#: Оборванные коммуникации между якорями: (от, доля высоты, куда, доля). Пролёт
#: с 78 % главного якоря идёт на 250 м — выше всех окрестных заносов и деревьев,
#: поэтому виден как натянутая нить, даже когда сам якорь уже тонет в тумане.
SPANS = (
    ("station", 0.78, "far_n", 1.00),
    ("station", 0.78, "far_w", 1.00),
    ("station", 0.55, "far_e", 1.00),
)


def span_points():
    """Концы пролётов в мировых координатах: ((x0, y0, z0), (x1, y1, z1))."""
    out = []
    for (a, fa, b, fb) in SPANS:
        (ax, az, ah) = (anchor(a)["x"], anchor(a)["z"], anchor(a)["h"])
        (bx, bz, bh) = (anchor(b)["x"], anchor(b)["z"], anchor(b)["h"])
        out.append(((ax, ah * fa, az), (bx, bh * fb, bz)))
    return out


