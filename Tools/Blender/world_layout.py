def smooth01(edge0: float, edge1: float, value: float) -> float:
    """Сглаживание тем же smootherstep, что внутри `frontier_layout`.

    Приватный хелпер чужого модуля не зовётся (в проекте так не делают), но поля
    высот обязаны смешиваться одинаково: иначе на стыке чаши и плиты появился бы
    излом, который никто не заказывал.
    """
    if edge1 <= edge0:
        return 1.0 if value >= edge1 else 0.0
    t = min(max((value - edge0) / (edge1 - edge0), 0.0), 1.0)
    return t * t * (3.0 - 2.0 * t)


def macro_height(x: float, z: float) -> float:
    """Сумма долгих волн плиты в мировой точке, метры."""
    h = 0.0
    for (amp, period, bearing, phase) in MACRO_WAVES:
        b = math.radians(bearing)
        s = (x * math.sin(b) + z * math.cos(b)) / period * 2.0 * math.pi
        h += amp * math.sin(s + phase)
    return h


def crack_drop(x: float, z: float) -> float:
    """Насколько плита НИЖЕ нормы в разломе: корыто минус вал по краю."""
    d = FL.dist_to_polyline(x, z, CRACK["pts"])
    q = d / CRACK["half"]
    trench = CRACK["depth"] * max(0.0, 1.0 - q * q)
    lip = CRACK["lip"] * math.exp(-(((d - CRACK["half"] * 1.15) /
                                     (CRACK["half"] * 0.45)) ** 2))
    return trench - lip


def plate_height(x: float, z: float) -> float:
    """Плита мира: долгие волны, заносы у якорей и корыто разлома.

    Прежняя формула начиналась с `FL.ground_height` — чаши депо с валом-стеной
    на 140–260 м и двумя прорывами. Чаша была границей уровня: депо читалось
    отдельной локацией, обнесённой снегом. С тех пор как депо стало обычным
    чанком карты, обносить один узел стеной миру незачем — горизонт закрывают
    туман, заносы якорей и дальний слой, а не кольцо.

    Гейт, который выключал волны в 300 м от депо, ушёл вместе с чашей: площадка
    узла плоская сама по себе (`world_height` срезает её вровень), и защищать её
    отдельным правилом не нужно. Порядок внутри одной функции прежний и он не
    очевидный: заносы добавляются к волне, а разлом вычитается последним —
    корыто режет и волну, и занос, потому что это трещина в плите, а не ещё один
    холм на ней.
    """
    return (PLATE_BASE + macro_height(x, z)
            + FL.drift_sum(x, z, ANCHOR_DRIFTS) - crack_drop(x, z))


