"""Меши наследия: то, что осталось от Пояса на земле.

Класс контента выбрал владелец после холста шага 0: никаких 900-метровых башен
(«перемудр»), вместо них — **руины 15-60 м**, к которым можно подойти, и якоря
дальним силуэтом. Числа раскладки (где стоит руина, её высота) берутся из
`world_layout.py`, а не повторяются здесь: меш и карта не могут разойтись.

Оси — Blender (x, y, z), z вверх, метры; основание меша на z = 0 и слегка
утоплено, как того требует `STYLE.md` (деталь на полу опускается ниже уровня).
Перевод в Unity делает постпроцессор и зеркало X из `export_static` (ADR 0007):
Unity = (-x, z, -y), то есть длинная ось по Blender-Y есть ось Unity-Z.

Сборка — существующими примитивами (`LevelBuilder.box/_rot/_tube/_ico`), палитра
только ключами из `level_lib.MATERIALS`. Булевых операций нет: «дверь» — это
рама и тёмная врезка перед гранью, а не вырез.
"""

from __future__ import annotations

import math

import level_lib  # noqa: E402
import world_layout as W  # noqa: E402

# ---------------------------------------------------------------- «Откос»

#: Уклон плиты. 32° — ниже typical slope limit контроллера персонажа, то есть
#: по верхней грани действительно можно подняться: «Откос» выбран точкой
#: «открытого неба» именно потому, что на него можно влезть ногами.
TILT = 32.0

PLATE_LEN = 96.0        # вдоль Blender-Y
PLATE_W = 58.0          # вдоль Blender-X
PLATE_T = 4.2           # толщина плиты
PLATE_Z = 27.0          # центр плиты по высоте: нижний торец уходит в снег

#: Площадки: горизонтальные обломки, лёгшие на плиту. У каждой под низом —
#: призма-опора, иначе на 32° склоне плита торчит из-под края обломка на
#: полтора метра и обломок висит в воздухе («ничего не парит», STYLE.md 5).
PLATFORMS = ((-23.6, 14.7, 18.0, 6.0, 3.9), (21.1, 42.7, 16.0, 5.0, 4.0))

#: Перила. 1,1 м — человеческий репер из `SCALE_REPERS`: без них плита в 58 м
#: читается горой, с ними — сооружением, которое кто-то огородил.
RAIL_H = 1.1
RAIL_POST = 0.09
RAIL_STEP = 1.75

#: Дверь. 2,1 м — второй репер; тёмная врезка с рамой и деревянной заглушкой:
#: дерево поставили роботы, камень и металл — ушедшие.
DOOR_W, DOOR_H = 1.0, 2.1


def _slope_y(s: float) -> float:
    """Blender-Y точки верхней грани плиты на расстоянии s от её центра."""
    return s * math.cos(math.radians(TILT))


def _slope_z(s: float) -> float:
    """Высота верхней грани плиты на расстоянии s."""
    return PLATE_Z + s * math.sin(math.radians(TILT)) + PLATE_T * 0.5 * math.cos(
        math.radians(TILT))


def build_slide(materials):
    """«Откос» — опрокинутая плита Пояса, 58 м, с подъёмом и человеческими реперами.

    Состав читается сверху вниз как история: инженерная плита с рёбрами снизу
    (была несущей), на ней обломки-площадки, на верхней площадке — перила и
    одна тёплая лампа (это сделали здесь), у подошвы — дверь с деревянной
    заглушкой. Ни одного «декоративного» элемента без назначения.
    """
    b = level_lib.LevelBuilder(materials)
    tilt = (TILT, 0.0, 0.0)

    # Тело: сама плита.
    b.box_rot((0.0, 0.0, PLATE_Z), (PLATE_W, PLATE_LEN, PLATE_T), tilt,
              "Level_Stone", bevel=0.06)

    # Рёбра снизу: то, что доказывает инженерную природу плиты. Видны в
    # пролёте между снегом и верхним краем.
    for s in (-14.0, -4.0, 6.0, 16.0, 26.0):
        z = PLATE_Z + s * math.sin(math.radians(TILT)) - PLATE_T * 0.5 * math.cos(
            math.radians(TILT)) - 0.55
        b.box_rot((0.0, _slope_y(s), z), (PLATE_W - 6.0, 1.1, 1.3), tilt,
                  "Level_Stone", bevel=0.04)

    # Обломки-площадки и призмы под них.
    for (y, z, px, py, wedge_h) in PLATFORMS:
        b.box((0.0, y, z - wedge_h * 0.5), (px * 0.92, py, wedge_h),
              "Level_Stone", bevel=0.05)
        b.box((0.0, y, z), (px, py, 1.4), "Level_Stone", bevel=0.08)
        b.box((0.0, y, z + 0.76), (px - 1.2, py - 1.2, 0.14), "Level_Snow",
              bevel=0.05)

    top_y, top_z = PLATFORMS[1][0], PLATFORMS[1][1] + 0.7
    deck = top_z + 0.7                      # верхняя площадка, по ней ходят

    # Перила по наветренному краю верхней площадки: 9 стоек и поручень.
    rail_y = top_y - PLATFORMS[1][3] * 0.5 + 0.45
    n_post = int((PLATFORMS[1][2] - 2.0) / RAIL_STEP) + 1
    for i in range(n_post):
        x = -(PLATFORMS[1][2] - 2.0) * 0.5 + i * RAIL_STEP
        b.box((x, rail_y, deck + RAIL_H * 0.5), (RAIL_POST, RAIL_POST, RAIL_H),
              "Level_Metal", bevel=0.012)
    rail_len = (n_post - 1) * RAIL_STEP + 0.24
    b.box((0.0, rail_y, deck + RAIL_H), (rail_len, 0.10, 0.10), "Level_Metal",
          bevel=0.02)
    b.box((0.0, rail_y, deck + RAIL_H + 0.075), (rail_len - 0.4, 0.16, 0.07),
          "Level_Snow", bevel=0.015)

    # Фонарь: единственная тёплая точка на ассет (STYLE.md: акцент — редкость).
    lamp = (5.2, top_y + 1.1)
    b.tube([(lamp[0], lamp[1], deck), (lamp[0], lamp[1], deck + 4.05),
            (lamp[0] - 0.55, lamp[1], deck + 4.5)],
           [(0.12, 0.12), (0.09, 0.09), (0.07, 0.07)], "Level_Metal", n=6)
    b.box((lamp[0] - 0.62, lamp[1], deck + 4.36), (0.30, 0.26, 0.34),
          "Level_Window", bevel=0.03)
    b.box((lamp[0] - 0.62, lamp[1], deck + 4.60), (0.42, 0.36, 0.10),
          "Level_Rust", bevel=0.02)

    # Дверь у подошвы: рама, тёмный проём и деревянная заглушка наполовину.
    # Сборка вынесена НАРужу по нормали торца, а не просто по -Y: торец плиты
    # наклонён, и деталь, лежащая точно в его плоскости, либо тонет в плите,
    # либо мерцает соучастием граней (STYLE.md, правило 7).
    d_s = -PLATE_LEN * 0.5
    n_y, n_z = -math.cos(math.radians(TILT)), -math.sin(math.radians(TILT))
    d_y = _slope_y(d_s) + n_y * 0.22
    d_z = _slope_z(d_s) - PLATE_T * 0.5 + n_z * 0.22
    b.box_rot((6.0, d_y, d_z + DOOR_H * 0.5), (DOOR_W + 0.5, 0.34, DOOR_H + 0.5),
              tilt, "Level_Metal", bevel=0.03)
    b.box_rot((6.0, d_y - 0.10, d_z + DOOR_H * 0.5),
              (DOOR_W, 0.30, DOOR_H), tilt, "Level_Rust", bevel=0.02)
    b.box_rot((6.0 - DOOR_W * 0.27, d_y - 0.26, d_z + DOOR_H * 0.5),
              (DOOR_W * 0.46, 0.08, DOOR_H - 0.12), tilt, "Level_Wood",
              bevel=0.02)

    # Лестница на наклонной грани: второй инженерный признак после рёбер и
    # единственное, что объясняет, как сюда вообще забрались без перил.
    lad_x = -14.0
    for i in range(9):
        s = -34.0 + i * 1.9
        z = _slope_z(s) + 0.10
        b.tube([(lad_x - 0.32, _slope_y(s), z), (lad_x + 0.32, _slope_y(s), z)],
               [(0.05, 0.05), (0.05, 0.05)], "Level_Metal", n=5)
    for sx in (-0.32, 0.32):
        b.tube([(lad_x + sx, _slope_y(-34.0), _slope_z(-34.0) + 0.1),
                (lad_x + sx, _slope_y(-17.8), _slope_z(-17.8) + 0.1)],
               [(0.055, 0.055), (0.055, 0.055)], "Level_Metal", n=5)

    # Сломанный край наверху: арматура и оторванный кусок, который и даёт
    # объявленные 58 м.
    lip_s = PLATE_LEN * 0.5 - 2.0
    b.box_rot((0.0, _slope_y(lip_s) + 1.6, _slope_z(lip_s) + 2.2),
              (PLATE_W * 0.72, 5.0, 1.6), (62.0, 0.0, 0.0), "Level_Stone",
              bevel=0.06)
    # Снежная шапка на оторванном куске: лежит ВРЕЗАННОЙ в верхнюю грань, иначе
    # её верхний край лезет выше объявленных 58 м и раскладка перестаёт врать.
    b.box_rot((0.0, _slope_y(lip_s) + 2.6, _slope_z(lip_s) + 3.5),
              (PLATE_W * 0.66, 3.4, 0.5), (62.0, 0.0, 0.0), "Level_Snow",
              bevel=0.10)
    for i in range(6):
        x = -20.0 + i * 8.0
        y = _slope_y(PLATE_LEN * 0.5) + 0.4
        z = _slope_z(PLATE_LEN * 0.5) - 1.2
        b.tube([(x, y - 0.6, z), (x, y + 0.9, z + 1.5), (x + 0.4, y + 1.5, z + 2.2)],
               [(0.07, 0.07)] * 3, "Level_Rust", n=5)

    # Опора, на которой держится поднятый край. Раньше здесь лежала «осыпь» из
    # четырёх блоков — и на превью она висела в воздухе: плита на 32° поднимает
    # нижнюю грань на 45 м, и никакой хлам её не подпирает. Теперь это надломлен-
    # ный пилон Пояса: он и физически честен, и читается как наследие, а не как
    # осыпь. Считается от нормали: нижняя грань плиты на y есть
    # PLATE_Z + y·tg(TILT) − (PLATE_T/2)·cos(TILT).
    def underside(y: float) -> float:
        return PLATE_Z + y * math.tan(math.radians(TILT)) - PLATE_T * 0.5 * math.cos(
            math.radians(TILT))

    pyl_y = 33.0
    top_need = underside(pyl_y)
    z0 = 0.0
    for (h, size, lean) in ((15.0, 11.0, 2.5), (14.0, 9.6, -3.0), (12.0, 8.4, 2.0)):
        b.box_rot((lean * 0.9, pyl_y + lean * 0.4, z0 + h * 0.5),
                  (size, size, h + 1.2), (lean, lean * 0.6, lean * 2.0),
                  "Level_Stone", bevel=0.10)
        b.box_rot((lean * 0.9, pyl_y + lean * 0.4, z0 + h + 0.35),
                  (size - 1.6, size - 1.6, 0.7), (lean, lean * 0.6, lean * 2.0),
                  "Level_Snow", bevel=0.12)
        b.box_rot((lean * 0.9, pyl_y - size * 0.5 + 0.2, z0 + h * 0.5),
                  (0.9, 0.5, h * 0.7), (0.0, 0.0, lean * 2.0), "Level_Rust",
                  bevel=0.04)
        z0 += h
    # Пята: верхний блок доводится ровно до нижней грани плиты с заходом на
    # 0.8 м, чтобы не было ни зазора, ни шипа, проткнувшего площадку сверху.
    cap_h = max(2.0, top_need + 0.8 - z0)
    b.box_rot((1.0, pyl_y, z0 + cap_h * 0.5), (7.2, 7.2, cap_h),
              (0.5, -1.0, 4.0), "Level_Stone", bevel=0.08)

    # Обломки у подошвы пилонов — то, что осыпалось, а не то, что держит.
    for i, (oy, oz, sx, sy, rot) in enumerate((
            (24.0, 2.2, 9.0, 6.0, (18.0, 6.0, 8.0)),
            (40.0, 2.6, 8.0, 5.0, (-14.0, 9.0, 4.0)),
            (30.0, 1.6, 6.0, 4.0, (26.0, -7.0, 12.0)))):
        b.box_rot((-14.0 + i * 13.0, oy, oz), (sx, sy, 3.2), rot, "Level_Stone",
                  bevel=0.10)
        b.box_rot((-14.0 + i * 13.0, oy - 0.5, oz + 1.8), (sx - 2.0, sy - 1.4, 0.5),
                  rot, "Level_Snow", bevel=0.10)

    # Ящик у двери: след быта, а не наследия.
    b.box((3.2, d_y - 1.9, 0.45), (0.9, 0.9, 0.9), "Level_WoodDark", bevel=0.03)
    b.box((3.2, d_y - 1.9, 0.94), (0.78, 0.78, 0.12), "Level_Snow", bevel=0.03)

    # Заносы у подошвы: граница «плита легла в снег», а не «меши коснулись».
    for (px, py, sc) in ((-16.0, -44.0, 1.0), (9.0, -47.0, 0.8),
                         (24.0, -40.0, 0.6)):
        b.ico((px, py, 0.2), 4.2 * sc, "Level_SnowDeep", subdivisions=1,
              scale=(1.6, 1.1, 0.42), jitter=0.22, seeds=px + py)

    # Снежные полосы по склону. Девяностометровая тёмная грань без снега
    # читается как асфальт, а не как брошенное наследие: STYLE.md правило 4
    # требует, чтобы снег был геометрией. Полосы лежат ВРЕЗАНЫМИ в грань: с
    # первого прогона они были по 0.4 м и на скользящем угле не читались
    # совсем — видимой остаётся только та грань, что выступает на 0.6 м.
    for (sx, w, ln) in ((-19.0, 7.0, 62.0), (14.0, 5.0, 50.0), (24.0, 4.0, 40.0)):
        b.box_rot((sx, _slope_y(2.0), _slope_z(2.0) + 0.25), (w, ln, 1.2), tilt,
                  "Level_Snow", bevel=0.14)

    # Ржавые перевязки поперёк склона: второй читаемый на расстоянии ритм,
    # кроме снежного. Это шов секций, а не decoration: плита набиралась кусками.
    for s in (-26.0, 4.0, 30.0):
        b.box_rot((0.0, _slope_y(s), _slope_z(s) + 0.15),
                  (PLATE_W - 1.0, 1.3, 0.9), tilt, "Level_Rust", bevel=0.06)

    return b.build("Heritage_Slide")


# ---------------------------------------------------------------- «Опора-3»

#: Решётчатый столб коммуникаций. 34 м — в десять с лишним раз выше робота, и
#: репером здесь работает лестница: ступени в 0.5 м известны глазу, и по ним
#: видно, что башня не дерево и не гора.
PYLON_H = 34.0
PYLON_BASE = 7.0
PYLON_TOP = 2.6
LEG_R = 0.45              # 90 см в диаметре: на 34-метровой опоре тоньше — жилисто
BELT = 0.24               #: пояс обвязки: 24 см — видно с 200 м, не сыпь


def build_pylon(materials):
    """«Опора-3»: столб, на котором висел пролёт, теперь надломлен и оборван."""
    b = level_lib.LevelBuilder(materials)
    h0, h1 = PYLON_BASE * 0.5, PYLON_TOP * 0.5

    # Фундамент: плита шире башни, нижняя грань утоплена в снег.
    b.box((0.0, 0.0, 1.05), (PYLON_BASE + 3.4, PYLON_BASE + 3.4, 2.4),
          "Level_Stone", bevel=0.08)
    b.box((0.0, 0.0, 2.35), (PYLON_BASE + 2.2, PYLON_BASE + 2.2, 0.5),
          "Level_Snow", bevel=0.12)

    # Ноги: четыре трубы, сходящиеся кверху.
    for (sx, sy) in ((1, 1), (1, -1), (-1, 1), (-1, -1)):
        b.tube([(sx * h0, sy * h0, 1.4),
                (sx * (h0 * 0.52 + h1 * 0.48), sy * (h0 * 0.52 + h1 * 0.48),
                 PYLON_H * 0.52),
                (sx * h1, sy * h1, PYLON_H - 1.6)],
               [(LEG_R, LEG_R)] * 3, "Level_Metal", n=6)

    # Пояса обвязки: пять ярусов, каждый уже предыдущего. Это и есть «повтор
    # модуля», которым читается высота (STYLE.md: повтор = гигантское).
    for i in range(5):
        z = 5.0 + i * 5.4
        h = h0 + (h1 - h0) * (z / PYLON_H)
        for (sx, sy, cx, cy) in ((2 * h, BELT, 0.0, -h), (2 * h, BELT, 0.0, h),
                                 (BELT, 2 * h, -h, 0.0), (BELT, 2 * h, h, 0.0)):
            b.box((cx, cy, z), (sx, sy, BELT), "Level_Rust", bevel=0.02)

    # Лестница на южной грани: human-репер.
    for i in range(11):
        z = 3.4 + i * 2.4
        h = h0 + (h1 - h0) * (z / PYLON_H)
        b.tube([(-0.34, -h - 0.16, z), (0.34, -h - 0.16, z)],
               [(0.07, 0.07), (0.07, 0.07)], "Level_Metal", n=5)
    for sx in (-0.34, 0.34):
        b.tube([(sx, -h0 - 0.16, 3.0), (sx, -h1 - 0.16, PYLON_H - 3.2)],
               [(0.075, 0.075), (0.075, 0.075)], "Level_Metal", n=5)

    # Кронштейн пролёта: то, за что держала линия, и её обрывок.
    arm_z = PYLON_H - 3.4
    b.box((3.6, 0.0, arm_z), (7.6, 0.5, 0.5), "Level_Metal", bevel=0.05)
    b.box((3.6, 0.0, arm_z + 0.42), (7.0, 0.62, 0.22), "Level_Snow", bevel=0.06)
    for sx in (1.4, 5.8):
        b.tube([(sx, 0.0, arm_z - 0.25), (sx, 0.0, arm_z - 1.1)],
               [(0.19, 0.19), (0.15, 0.15)], "Level_Stone", n=6)

    # Надлом: верхний огрызок согнут, кабель оборван и висит.
    b.tube([(0.0, 0.0, PYLON_H - 2.0), (0.5, 0.3, PYLON_H - 0.6),
            (1.3, 0.9, PYLON_H + 0.2)],
           [(0.26, 0.26), (0.22, 0.22), (0.14, 0.14)], "Level_Rust", n=6)
    b.tube([(6.3, 0.0, arm_z - 1.1), (9.0, -1.4, arm_z - 6.0),
            (10.2, -3.0, arm_z - 12.5)],
           [(0.07, 0.07)] * 3, "Level_Metal", n=5)

    # Снег у подошвы: граница «опора стоит в сугробе», а не «касалась плоскости».
    for (px, py, sc) in ((-5.2, 4.4, 0.9), (5.6, -4.0, 0.75), (0.5, 6.2, 0.6)):
        b.ico((px, py, 0.25), 3.4 * sc, "Level_SnowDeep", subdivisions=1,
              scale=(1.5, 1.2, 0.4), jitter=0.24, seeds=px + py)

    return b.build("Heritage_Pylon")


