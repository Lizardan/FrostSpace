"""Дизайн ховербайка FrostSpace: статическая геометрия уровня.

Композиция — как у спортивного байка, поставленного на подушку: крупный
передний обтекатель с козырьком и фарой, за ним бак, низкое седло в «талии» и
тяжёлая корма с двумя дюзами. По бокам талии идут низкие выносные поплавки —
они дают машине ширину и читаются как опоры подушки, а не как второй корпус.

Оси и палитра — как в `level_lib.py`: вверх +Z, нос смотрит в Blender −Y. После
`export_static` это Unity +Z, то есть `transform.forward` байка; бок остаётся боком.

Корпус поднят над землёй на `CLEARANCE` — подушка под днищем рисуется в Unity
отдельным шейдером, а не геометрией. Правило «ничего не парит» относится к
креплению деталей: каждая деталь пересекается с корпусом, поплавком или посажена
на стойку, ничего не висит в воздухе отдельно от машины.

Все массы крупные (от 0.05 м), фаска 0.012–0.05, снег — часть геометрии.
"""

from __future__ import annotations

import level_lib

#: Низ корпуса над землёй, м. Подушка светится в этом зазоре.
CLEARANCE = 0.46

#: Верх седла, м. С этой высотой должен совпадать `Seat` в префабе Unity.
SEAT_TOP = 0.88

#: Середина седла по оси Y (Blender): в Unity это z = −SEAT_Y.
SEAT_Y = 0.35

#: Рукоятки: Blender (x, y, z) → Unity (x, z, −y).
GRIP_X = 0.33
GRIP_Y = -0.44
GRIP_Z = 1.05

#: Задние подножки: ступни уходят за седло, как на спортивном мотоцикле.
#: Корма сужена до 0.28, поэтому ступня стоит вплотную к борту, а не на отлёте.
FOOT_X = 0.24
FOOT_Y = 0.55
FOOT_Z = 0.62

#: Ось выносных поплавков.
POD_X = 0.46


def _side_box(b, side, center, size, mat, bevel=0.02, rot=None):
    """Коробка на борту: side = −1 левый, +1 правый."""
    x, y, z = center
    if rot is None:
        b.box((side * x, y, z), size, mat, bevel=bevel)
    else:
        b.box_rot((side * x, y, z), size, rot, mat, bevel=bevel)


def _plate(b, x, outline, thickness, mat):
    """Пластина в плоскости YZ, выдавленная по X: плавники и косынки."""
    half = thickness * 0.5
    count = len(outline)
    verts = [(x - half, y, z) for y, z in outline]
    verts += [(x + half, y, z) for y, z in outline]
    faces = [tuple(range(count)), tuple(range(count, count * 2))[::-1]]
    for i in range(count):
        j = (i + 1) % count
        faces.append((i, j, count + j, count + i))
    b.add(verts, faces, mat)


def _fairing(b):
    """Передний обтекатель: лофт-клин, верхний капот, козырёк и клюв с фарой."""
    stations = (
        (-1.02, 0.80, 0.12, 0.10),
        (-0.92, 0.82, 0.20, 0.16),
        (-0.72, 0.84, 0.26, 0.22),
        (-0.52, 0.86, 0.25, 0.21),
        (-0.42, 0.86, 0.20, 0.17),
    )
    b.tube([(0.0, y, z) for y, z, _w, _h in stations],
           [(w, h) for _y, _z, w, h in stations],
           "Level_Metal", n=8, ref=(0.0, 0.0, 1.0), fan_caps=True)

    # Верхний капот и козырёк.
    b.box_rot((0.0, -0.62, 1.02), (0.42, 0.38, 0.12), (-16.0, 0.0, 0.0),
              "Level_Metal", bevel=0.028)
    b.box_rot((0.0, -0.72, 1.17), (0.34, 0.03, 0.26), (-40.0, 0.0, 0.0),
              "Level_Ice", bevel=0.008)
    b.box_rot((0.0, -0.62, 1.05), (0.18, 0.08, 0.03), (-30.0, 0.0, 0.0),
              "Level_Stone", bevel=0.008)

    # Тёмные щёки обтекателя с оранжевой маркировкой.
    for side in (-1.0, 1.0):
        _side_box(b, side, (0.245, -0.72, 0.82), (0.04, 0.38, 0.22),
                  "Level_Stone", bevel=0.014)
        _side_box(b, side, (0.252, -0.72, 0.91), (0.03, 0.20, 0.03),
                  "Level_Orange", bevel=0.006)
        _side_box(b, side, (0.252, -0.82, 0.72), (0.03, 0.12, 0.04),
                  "Level_Metal", bevel=0.008)

    # Нос-клюв продолжает обтекатель без ступеньки: фара на самом кончике.
    beak = (
        (-1.24, 0.74, 0.04, 0.03),
        (-1.16, 0.75, 0.09, 0.06),
        (-1.08, 0.77, 0.14, 0.09),
        (-0.98, 0.79, 0.17, 0.12),
    )
    b.tube([(0.0, y, z) for y, z, _w, _h in beak],
           [(w, h) for _y, _z, w, h in beak],
           "Level_Metal", n=8, ref=(0.0, 0.0, 1.0), fan_caps=True)
    b.box_rot((0.0, -1.23, 0.745), (0.10, 0.03, 0.05), (6.0, 0.0, 0.0),
              "Level_Window", bevel=0.008)
    b.box_rot((0.0, -1.12, 0.815), (0.11, 0.16, 0.025), (6.0, 0.0, 0.0),
              "Level_Snow", bevel=0.008)

    # Снег на верхнем капоте.
    b.box_rot((0.0, -0.60, 1.085), (0.30, 0.24, 0.025), (-16.0, 0.0, 0.0),
              "Level_Snow", bevel=0.008)


def _outrigger(b, side):
    """Низкий выносной поплавок: ширина машины и опора подушки."""
    stations = (
        (-0.26, 0.56, 0.04, 0.04),
        (-0.12, 0.56, 0.10, 0.08),
        (0.22, 0.57, 0.11, 0.09),
        (0.50, 0.58, 0.08, 0.06),
        (0.60, 0.59, 0.04, 0.04),
    )
    b.tube([(side * POD_X, y, z) for y, z, _w, _h in stations],
           [(w, h) for _y, _z, w, h in stations],
           "Level_Metal", n=8, ref=(0.0, 0.0, 1.0), fan_caps=True)

    # Стойки к корпусу.
    _side_box(b, side, (0.31, -0.06, 0.57), (0.26, 0.10, 0.06),
              "Level_Metal", bevel=0.012)
    _side_box(b, side, (0.31, 0.40, 0.58), (0.26, 0.10, 0.06),
              "Level_Metal", bevel=0.012)

    # Снег на поплавке и задний маркер.
    _side_box(b, side, (POD_X, 0.16, 0.645), (0.12, 0.24, 0.025),
              "Level_Snow", bevel=0.008)
    _side_box(b, side, (POD_X, 0.52, 0.59), (0.05, 0.03, 0.04),
              "Level_Window", bevel=0.006)


def _engine(b):
    """Корма: лофт-блок, решётки, плавник и две дюзы."""
    stations = (
        (0.52, 0.74, 0.14, 0.12),
        (0.64, 0.76, 0.22, 0.19),
        (0.86, 0.76, 0.24, 0.20),
        (1.02, 0.76, 0.20, 0.18),
        (1.10, 0.76, 0.14, 0.12),
    )
    b.tube([(0.0, y, z) for y, z, _w, _h in stations],
           [(w, h) for _y, _z, w, h in stations],
           "Level_Metal", n=8, ref=(0.0, 0.0, 1.0), fan_caps=True)

    # Боковые решётки: тёмный зев и ржавая окантовка.
    for side in (-1.0, 1.0):
        _side_box(b, side, (0.225, 0.84, 0.76), (0.04, 0.28, 0.16),
                  "Level_Stone", bevel=0.008)
        _side_box(b, side, (0.24, 0.84, 0.76), (0.02, 0.18, 0.10),
                  "Level_Rust", bevel=0.006)

    # Плавник: стреловидная металлическая пластина с оранжевым кончиком.
    _plate(b, 0.0, ((0.90, 0.93), (1.12, 0.93), (1.18, 1.07),
                    (1.05, 1.07)), 0.05, "Level_Metal")
    _plate(b, 0.0, ((1.13, 1.02), (1.17, 1.03), (1.19, 1.08),
                    (1.15, 1.08)), 0.06, "Level_Orange")
    b.box((0.0, 1.10, 0.84), (0.18, 0.03, 0.05), "Level_Window",
          bevel=0.008)
    b.box_rot((0.0, 0.82, 0.955), (0.26, 0.28, 0.025), (0.0, 0.0, 0.0),
              "Level_Snow", bevel=0.008)

    # Две дюзы: стакан и светящееся сопло.
    for side in (-1.0, 1.0):
        b.tube([(side * 0.14, 1.06, 0.74), (side * 0.14, 1.18, 0.74)],
               [(0.11, 0.11)] * 2, "Level_Metal", n=8)
        b.tube([(side * 0.14, 1.19, 0.74), (side * 0.14, 1.22, 0.74)],
               [(0.08, 0.08)] * 2, "Level_Window", n=8,
               caps=(False, True))


def build_hoverbike(materials: dict, name: str = "Hoverbike"):
    """Собрать один меш ховербайка: обтекатель, седло, корма, поплавки."""
    b = level_lib.LevelBuilder(materials)

    # -- центральный корпус и киль --------------------------------------
    # Корма уже талии: между седлом и подножками борт поджат, иначе
    # сведённые внутрь ступни входили бы в корпус.
    b.box((0.0, -0.14, 0.62), (0.36, 1.16, 0.32), "Level_Metal",
          bevel=0.04)
    b.box((0.0, 0.54, 0.62), (0.28, 0.36, 0.32), "Level_Metal",
          bevel=0.04)
    b.box((0.0, 0.0, 0.475), (0.24, 1.16, 0.05), "Level_Stone",
          bevel=0.012)
    # Тёмная вставка по борту разбивает плоскую боковину.
    for side in (-1.0, 1.0):
        _side_box(b, side, (0.18, -0.05, 0.58), (0.02, 0.82, 0.09),
                  "Level_Stone", bevel=0.006)
    # Кольца-emitter'ы подушки крепятся к днищу.
    for y in (-0.36, 0.40):
        b.band((0.0, y), 0.14, CLEARANCE - 0.005, CLEARANCE + 0.04,
               "Level_Metal", n=10, thickness=0.03)

    # -- передний обтекатель --------------------------------------------
    _fairing(b)

    # -- выносные поплавки ----------------------------------------------
    for side in (-1.0, 1.0):
        _outrigger(b, side)

    # -- бак -------------------------------------------------------------
    b.box_rot((0.0, -0.22, 0.90), (0.40, 0.40, 0.20), (-4.0, 0.0, 0.0),
              "Level_Metal", bevel=0.03)
    b.box((0.0, -0.22, 1.005), (0.12, 0.26, 0.02), "Level_Orange",
          bevel=0.006)
    for side in (-1.0, 1.0):
        _side_box(b, side, (0.20, -0.22, 0.88), (0.04, 0.26, 0.16),
                  "Level_Stone", bevel=0.014)
        _side_box(b, side, (0.205, -0.22, 0.96), (0.03, 0.16, 0.03),
                  "Level_Metal", bevel=0.006)

    # -- седло -----------------------------------------------------------
    b.box((0.0, 0.33, 0.80), (0.32, 0.52, 0.08), "Level_Stone",
          bevel=0.02)
    b.box((0.0, 0.33, SEAT_TOP - 0.025), (0.30, 0.44, 0.05),
          "Level_WoodDark", bevel=0.02)
    b.box((0.0, 0.57, 0.90), (0.30, 0.06, 0.08), "Level_Rust",
          bevel=0.012)
    b.box((0.0, 0.57, 0.945), (0.24, 0.04, 0.02), "Level_Snow",
          bevel=0.006)
    for side in (-1.0, 1.0):
        _side_box(b, side, (0.16, 0.33, 0.84), (0.03, 0.36, 0.06),
                  "Level_Metal", bevel=0.008)

    # -- корма -----------------------------------------------------------
    _engine(b)

    # -- рама по борту: тонкие трубы, как у мотоцикла --------------------
    for side in (-1.0, 1.0):
        b.tube([(side * 0.19, -0.46, 0.70), (side * 0.19, 0.10, 0.70),
                (side * 0.14, 0.58, 0.72)],
               [(0.026, 0.026)] * 3, "Level_Metal", n=6)
        b.tube([(side * 0.19, -0.30, 0.55), (side * 0.19, 0.20, 0.55),
                (side * 0.14, 0.52, 0.56)],
               [(0.022, 0.022)] * 3, "Level_Metal", n=6)

    # -- руль ------------------------------------------------------------
    b.box((0.0, -0.46, 1.02), (0.10, 0.10, 0.16), "Level_Metal",
          bevel=0.018)
    b.tube([(-0.39, GRIP_Y - 0.03, GRIP_Z - 0.01),
            (0.0, GRIP_Y + 0.02, GRIP_Z + 0.01),
            (0.39, GRIP_Y - 0.03, GRIP_Z - 0.01)],
           [(0.026, 0.026)] * 3, "Level_Metal", n=8)
    for side in (-1.0, 1.0):
        _side_box(b, side, (GRIP_X, GRIP_Y - 0.03, GRIP_Z),
                  (0.12, 0.06, 0.06), "Level_WoodDark", bevel=0.014)
        _side_box(b, side, (GRIP_X + 0.04, GRIP_Y - 0.10, GRIP_Z - 0.02),
                  (0.08, 0.04, 0.02), "Level_Orange", bevel=0.006)

    # -- задние подножки -------------------------------------------------
    for side in (-1.0, 1.0):
        _side_box(b, side, (0.19, FOOT_Y, 0.595), (0.10, 0.10, 0.05),
                  "Level_Metal", bevel=0.01)
        _side_box(b, side, (FOOT_X, FOOT_Y, FOOT_Z - 0.02),
                  (0.12, 0.18, 0.04), "Level_Metal", bevel=0.01)
        _side_box(b, side, (FOOT_X + 0.05, FOOT_Y, 0.63), (0.05, 0.10, 0.10),
                  "Level_Rust", bevel=0.01)

    return b.build(name)
