"""Дизайн ховербайка FrostSpace: статическая геометрия уровня.

Вариант B — сравнивается с макетом из примитивов (`Hoverbike_A_Model.prefab`,
собирается `Assets/_Project/Editor/HoverbikeMockBuilder.cs`).

Оси и палитра — как в `level_lib.py`: вверх +Z, нос смотрит в Blender −Y. После
`export_static` это Unity +Z, то есть `transform.forward` байка; бок остаётся боком.

Корпус поднят над землёй на `CLEARANCE` — подушка под днищем рисуется в Unity
отдельным шейдером, а не геометрией. Правило «ничего не парит» относится к
креплению деталей: каждая деталь пересекается с корпусом или посажена на стойку,
ничего не висит в воздухе отдельно от машины.

Все массы крупные (от 0.04 м), фаска 0.012–0.02, снег — часть геометрии.
"""

from __future__ import annotations

import level_lib

#: Низ корпуса над землёй, м. Подушка светится в этом зазоре.
CLEARANCE = 0.53

#: Полувысота главного корпуса, м: середина корпуса = CLEARANCE + HULL_H.
HULL_H = 0.15


def build_hoverbike(materials: dict, name: str = "Hoverbike"):
    """Собрать один меш ховербайка: корпус, борта, руль, выхлоп, подножка, снег."""
    b = level_lib.LevelBuilder(materials)

    cz = CLEARANCE + HULL_H          # середина корпуса по высоте
    deck_z = CLEARANCE + HULL_H * 2  # верх корпуса — на нём седло

    # -- корпус ---------------------------------------------------------
    # Одна крупная масса и два сужающихся блока: силуэт читается с игрового
    # кадра, где байк занимает сотню пикселей.
    b.box((0.0, 0.0, cz), (0.72, 2.20, 0.30), "Level_Metal", bevel=0.02)
    b.box_rot((0.0, -1.14, cz + 0.08), (0.54, 0.85, 0.24), (-10.0, 0.0, 0.0),
              "Level_Metal", bevel=0.02)
    b.box_rot((0.0, 1.14, cz + 0.06), (0.46, 0.55, 0.20), (8.0, 0.0, 0.0),
              "Level_Rust", bevel=0.018)

    # -- седло и консоль ------------------------------------------------
    b.box((0.0, 0.30, deck_z + 0.04), (0.60, 1.05, 0.10), "Level_WoodDark",
          bevel=0.015)
    b.box_rot((0.0, -0.68, deck_z + 0.09), (0.44, 0.16, 0.20),
              (-20.0, 0.0, 0.0), "Level_Rust", bevel=0.015)
    # Тёплый свет только через Level_Window — как окна дома и лампа меню.
    b.box_rot((0.0, -0.66, deck_z + 0.17), (0.20, 0.03, 0.09),
              (-20.0, 0.0, 0.0), "Level_Window", bevel=0.008)
    b.box((0.0, -1.56, cz + 0.16), (0.24, 0.06, 0.12), "Level_Window",
          bevel=0.008)

    # -- борта ----------------------------------------------------------
    for side in (-1.0, 1.0):
        b.box((side * 0.44, 0.05, cz - 0.02), (0.16, 0.85, 0.26),
              "Level_Rust", bevel=0.015)
        # Панель врезана в под: половина внутри, половина снаружи — это
        # хайтек-деталь уровня, а не наклейка.
        b.box((side * 0.365, -0.30, cz), (0.05, 0.40, 0.16), "Level_Stone",
              bevel=0.01)

    # -- руль, выхлоп, подножка ------------------------------------------
    b.tube([(-0.34, -0.56, cz + 0.30), (0.0, -0.52, cz + 0.30),
            (0.34, -0.56, cz + 0.30)],
           [(0.028, 0.028)] * 3, "Level_Metal", n=8)
    for side in (-1.0, 1.0):
        b.box((side * 0.20, -0.56, cz + 0.24), (0.06, 0.06, 0.16),
              "Level_Metal", bevel=0.012)

    b.tube([(0.33, 0.62, cz - 0.04), (0.33, 1.22, cz - 0.04)],
           [(0.065, 0.065)] * 2, "Level_Rust", n=8)
    b.box_rot((0.28, 0.10, CLEARANCE - 0.08), (0.06, 0.06, 0.26),
              (0.0, 10.0, 0.0), "Level_Metal", bevel=0.012)

    # -- снег ------------------------------------------------------------
    # Снег лежит на выступающих плоскостях: седло, нос, корма.
    b.box((0.0, 0.55, deck_z + 0.10), (0.52, 0.66, 0.05), "Level_Snow",
          bevel=0.012)
    b.box_rot((0.0, -1.22, cz + 0.21), (0.42, 0.48, 0.045),
              (-10.0, 0.0, 0.0), "Level_Snow", bevel=0.012)
    b.box_rot((0.0, 1.18, cz + 0.18), (0.40, 0.42, 0.04), (8.0, 0.0, 0.0),
              "Level_Snow", bevel=0.012)

    return b.build(name)
