def _wall(b):
    """Капитальная стена периметра: цоколь, тело, обвязка, снег, зубы и фонари.

    Пол двора падает вдоль пути на 11,09 м (южный край −11,25, северный −22,34),
    поэтому каждая станция стены стоит на своей отметке: одна плоскость на 230 м
    дала бы то «парящую» секцию, то секцию, уехавшую юбкой в грунт. Проверка
    `_sweep` падает, если нижняя грань не уходит ниже рельефа, — и падает с
    именем элемента.

    Зуб не лежит на обвязке одной гранью: его основание утоплено в неё на 10 см,
    снежная шапка на макушке шире зуба на 5 см, поэтому ни одна горизонтальная
    грань не совпадает с соседней (порог `check_frontier` — 6 см при пятне
    20×20 см).
    """
    wall = W.DEPOT_WALL
    plinth_h = wall["plinth"]
    body_top = wall["plinth"] + wall["body"]
    coping_top = body_top + WALL_COPING_TOP
    merlon_top = coping_top + wall["merlon_h"]

    plinth = [(-WALL_PLINTH_W * 0.5, -BURY), (WALL_PLINTH_W * 0.5, -BURY),
              (WALL_PLINTH_W * 0.5, plinth_h), (-WALL_PLINTH_W * 0.5, plinth_h)]
    body = [(-WALL_BODY_W * 0.5, plinth_h - 0.05), (WALL_BODY_W * 0.5, plinth_h - 0.05),
            (WALL_BODY_W * 0.5, body_top), (-WALL_BODY_W * 0.5, body_top)]
    coping = [(-WALL_COPING_W * 0.5, body_top - 0.10),
              (WALL_COPING_W * 0.5, body_top - 0.10),
              (WALL_COPING_W * 0.5, coping_top),
              (-WALL_COPING_W * 0.5, coping_top)]
    snow = [(-WALL_COPING_W * 0.5 + 0.02, coping_top - 0.08),
            (WALL_COPING_W * 0.5 - 0.02, coping_top - 0.08),
            (WALL_COPING_W * 0.5 - 0.02, coping_top + WALL_SNOW),
            (-WALL_COPING_W * 0.5 + 0.02, coping_top + WALL_SNOW)]

    for side in _wall_sides():
        for (a, bnd) in _wall_runs(side):
            ss = _span(a, bnd, WALL_STATION)
            pts = [_wall_point(side, s) for s in ss]
            lvl = [yard(px, pz) for (px, pz) in pts]
            _sweep(b, pts, plinth, "Level_Stone", lvl, "цоколь стены")
            _sweep(b, pts, body, "Level_Metal", lvl, "тело стены",
                   buried=False)
            _sweep(b, pts, coping, "Level_Stone", lvl, "обвязка стены",
                   buried=False)
            _sweep(b, pts, snow, "Level_Snow", lvl, "снег на обвязке",
                   buried=False)

            # Зубья: шаг от начала отрезка, у края проёма зуба нет — там тумба.
            k = 0
            while True:
                s = a + wall["step"] * (k + 0.5)
                if s > bnd - wall["step"] * 0.5:
                    break
                k += 1
                if any(abs(s - edge) < 1.4 for edge in _gap_edges(side)):
                    continue
                (lx, lz) = _wall_point(side, s)
                g = yard(lx, lz)
                merlon_h = wall["merlon_h"] + 0.15
                size = (WALL_COPING_W, wall["merlon"], merlon_h) \
                    if side["axis"] == "z" else \
                    (wall["merlon"], WALL_COPING_W, merlon_h)
                _box(b, lx, lz, g + body_top - 0.05 + merlon_h * 0.5, size,
                     "Level_Metal", bevel=0.0)
                cap = (WALL_COPING_W + 0.10, wall["merlon"] + 0.10, 0.14) \
                    if side["axis"] == "z" else \
                    (wall["merlon"] + 0.10, WALL_COPING_W + 0.10, 0.14)
                _box(b, lx, lz, g + merlon_top + 0.06, cap, "Level_Snow",
                     bevel=0.0)

            # Тумбы на краях проёмов и фонари по лицовой стороне.
            for edge in _gap_edges(side):
                if a - 0.1 <= edge <= bnd + 0.1:
                    _wall_pier(b, side, edge, coping_top + 0.20)
            ls = _span(a, bnd, wall["lamp_span"])
            for s in ls:
                (lx, lz) = _wall_point(side, s)
                _wall_lamp(b, side, s, yard(lx, lz), WALL_BODY_W * 0.5 + 0.30)


def _gap_edges(side):
    """Края проёмов стороны: там стоят тумбы, и зубу рядом с ними не место."""
    out = []
    for (a, b) in side["gaps"]:
        out.extend((a, b))
    return out


def _gate_arch(b):
    """Ворота на дорогу: прорез в стене с консолями, замковым камнем и фонарным рядом.

    Тело стены прерывается на 16 м (`DEPOT_GATE["span"]`), а роль обвязки над
    проёмом берёт перемычка, поднятая до 4,20 м: без неё прорез читался бы дырой
    в заборе, а не створом в капитальной стене. Зубья над перемычкой ставят
    ворота башней — макушка 5,65 м против 4,20 м у стены. Три консоли с каждой
    стороны сужают проём к верху: это арка на языке проекта, лоупольно и плитами,
    без единой детали тоньше 6 см.

    Восточная стена идёт вдоль пути, а пол двора падает вдоль пути же, поэтому
    два устоя ворот стоят на разных отметках (разница по 8,8 м в обе стороны —
    0,83 м). Отметку держит верхняя: перемычка одна, и опирается она на оба устоя,
    а не зависает над нижним.
    """
    wall = W.DEPOT_WALL
    (gx, gz) = _gate_center()
    span = W.DEPOT_GATE["span"]
    thick = wall["thickness"] + 0.40
    spring = 4.20                        # низ перемычки над полом двора
    jamb_top = spring + 0.30             # устои выступают над перемычкой
    js = span * 0.5 + 0.80               # плечо устоя от осевой проёма
    g_hi = max(yard(gx, gz - js), yard(gx, gz + js))
    bridge_top = g_hi + spring + 0.90

    for side in (-1.0, 1.0):
        lz = gz + side * js
        g = yard(gx, lz)
        _box(b, gx, lz, (g - BURY + g_hi + jamb_top) * 0.5,
             (thick, 1.60, g_hi + jamb_top - g + BURY), "Level_Stone",
             bevel=0.04)
        _box(b, gx, lz, g_hi + jamb_top + 0.06, (thick + 0.20, 1.80, 0.16),
             "Level_Snow", bevel=0.04)
        # Устои со стороны двора: гладкий торец стены читается необшитым, а
        # руст из блоков с швом в 2 см даёт масштаб человека. Блок выступает
        # из грани на 22 см: заподлицо он читался бы дырой, а не нашивкой.
        for k in range(4):
            _box(b, gx - thick * 0.5 - 0.11, lz, g + 0.70 + k * 1.05,
                 (0.22, 1.30, 0.86), "Level_Stone", bevel=0.02)

    _box(b, gx, gz, g_hi + spring + 0.45, (thick, span + 3.20, 0.90),
         "Level_Stone", bevel=0.03)
    _box(b, gx, gz, bridge_top + 0.10, (thick + 0.24, span + 3.60, 0.24),
         "Level_Snow", bevel=0.04)
    # Замковый камень: единственный цветной акцент на проёме. Он выступает из
    # грани стены на 15 см и выше перемычки на 15 см — заподлицо камень читался
    # бы просто пятном на бетоне.
    _box(b, gx - 0.15, gz, g_hi + spring + 0.325, (thick + 0.30, 1.80, 0.85),
         "Level_Orange", bevel=0.02)

    # Консоли: по три с каждой стороны, верхняя выступает в проём сильнее
    # нижней. Ступень набрана массивными блоками с нахлёстом 20 см: тонкие
    # плитки на 46 см читались не сводом, а обвалом.
    for side in (-1.0, 1.0):
        for k in range(3):
            reach = 3.00 - k * 1.00
            _box(b, gx, gz + side * (span * 0.5 - reach * 0.5),
                 g_hi + spring + 0.10 - k * 0.62,
                 (thick - 0.10, reach, 0.84), "Level_Stone", bevel=0.02)

    # Фонарный ряд под перемычкой со стороны двора: свет падает на осевую
    # дороги и ведёт человека от вагона к воротам. Кронштейн входит в перемычку,
    # плафон висит под ним, а не лежит на её нижней грани.
    for k in (-1, 0, 1):
        lz = gz + k * 4.60
        _box(b, gx - thick * 0.5 - 0.05, lz, g_hi + spring - 0.20,
             (0.10, 0.10, 0.34), "Level_Metal", bevel=0.0)
        _box(b, gx - thick * 0.5 - 0.28, lz, g_hi + spring - 0.50,
             (0.26, 0.26, 0.32), "Level_Window", bevel=0.02)
        _box(b, gx - thick * 0.5 - 0.28, lz, g_hi + spring - 0.30,
             (0.36, 0.36, 0.10), "Level_Rust", bevel=0.0)

    # Зубья над перемычкой: ворота выше стены ровно на один зуб.
    merlon_h = wall["merlon_h"] + 0.15
    for k in range(4):
        lz = gz - span * 0.5 + wall["step"] * (k + 0.5)
        _box(b, gx, lz, bridge_top - 0.05 + merlon_h * 0.5,
             (WALL_COPING_W, wall["merlon"], merlon_h), "Level_Metal",
             bevel=0.02)
        _box(b, gx, lz, bridge_top - 0.05 + merlon_h + 0.06,
             (WALL_COPING_W + 0.10, wall["merlon"] + 0.10, 0.14),
             "Level_Snow", bevel=0.03)


def _rail_masts(b):
    """Путевые разрывы: по паре мачтовых столбов с юга и с севера.

    Владелец просил «просто два столба» на выезде поезда; линия сквозная, и
    поезд приезжает с юга, поэтому симметричная пара стоит и на входе. Столб
    держит фонарь на кронштейне и оранжевую плашку — ночевой ориентир горловины,
    а не перемычку: перемычка снова сделала бы из разрыва ворота.
    """
    rail_x = W.DEPOT_MAIN_X - W.DEPOT[0]
    half = W.DEPOT_RAIL_GAP * 0.5
    for lz in (local(W.DEPOT_YARD)[2], local(W.DEPOT_YARD)[3]):
        for side in (-1.0, 1.0):
            lx = rail_x + side * (half + 0.90)
            g = yard(lx, lz)
            _leg(b, lx, lz, g + 0.55, (0.90, 0.90), "Level_Stone", bevel=0.03)
            _tube(b, [(lx, lz, g + 0.40), (lx, lz, g + W.DEPOT_MAST_H),
                      (lx, lz, g + W.DEPOT_MAST_H + 0.45)],
                  [(0.21, 0.21), (0.155, 0.155), (0.12, 0.12)],
                  "Level_Metal", n=6)
            inward = 1.0 if lz < 0 else -1.0
            _box(b, lx, lz + inward * 0.46, g + W.DEPOT_MAST_H - 0.10,
                 (0.10, 0.92, 0.10), "Level_Rust", bevel=0.0)
            _box(b, lx, lz + inward * 0.86, g + W.DEPOT_MAST_H - 0.34,
                 (0.30, 0.30, 0.36), "Level_Window", bevel=0.02)
            _box(b, lx, lz - inward * 0.30, g + 3.10,
                 (0.10, 1.10, 0.46), "Level_Orange", bevel=0.0)
            _box(b, lx, lz, g + W.DEPOT_MAST_H + 0.51, (0.34, 0.34, 0.12),
                 "Level_Snow", bevel=0.03)


def _mast(b, lx, lz):
    """Сигнальная мачта у горловины: основание, мачта, траверса с линзой.

    Стоит южнее съезда бокового пути: прибывающий поезд идёт с юга, и мачта —
    первое, что он видит во дворе, а не последний кадр уезжающего вида.
    """
    g = yard(lx, lz)
    _leg(b, lx, lz, g + 0.70, (1.10, 1.10), "Level_Rust", bevel=0.03)
    _box(b, lx, lz, g + 0.78, (0.72, 0.72, 0.14), "Level_Snow", bevel=0.03)
    _tube(b, [(lx, lz, g + 0.60), (lx, lz, g + 3.60), (lx, lz, g + 7.10)],
          [(0.19, 0.19), (0.145, 0.145), (0.11, 0.11)], "Level_Metal", n=6)
    for hz in (2.30, 3.85, 5.30):
        _box(b, lx, lz, g + hz, (0.62, 0.10, 0.09), "Level_Rust", bevel=0.0)
    _box(b, lx + 0.42, lz, g + 6.30, (1.15, 0.12, 0.12), "Level_Metal",
         bevel=0.02)
    _tube(b, [(lx + 0.86, lz, g + 6.30), (lx + 0.86, lz, g + 6.72)],
          [(0.17, 0.17), (0.17, 0.17)], "Level_Window", n=8)
    _box(b, lx + 0.86, lz, g + 6.90, (0.40, 0.34, 0.12), "Level_Snow",
         bevel=0.03)
    _box(b, lx, lz, g + 7.16, (0.30, 0.30, 0.12), "Level_Snow", bevel=0.03)


def _cross_x(pts, x: float):
    """Точка, где ломаная пересекает прямую x = const: (x, z) в мире."""
    for (a, b) in zip(pts, pts[1:]):
        (ax, az) = a
        (bx, bz) = b
        if (ax - x) * (bx - x) > 0.0:
            continue
        if abs(bx - ax) < 1e-9:
            return (x, max(az, bz))
        t = (x - ax) / (bx - ax)
        return (x, az + (bz - az) * t)
    raise RuntimeError("линия не пересекает x = %.1f" % x)


def _dir_at(pts, at):
    """Направление ломаной в точке `at`: единичный вектор (x, z) в мире."""
    best = None
    for (a, b) in zip(pts, pts[1:]):
        ln = math.hypot(b[0] - a[0], b[1] - a[1])
        if ln <= 1e-6:
            continue
        t = max(0.0, min(1.0, ((at[0] - a[0]) * (b[0] - a[0]) +
                               (at[1] - a[1]) * (b[1] - a[1])) / (ln * ln)))
        p = (a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t)
        d = math.hypot(p[0] - at[0], p[1] - at[1])
        if best is None or d < best[0]:
            best = (d, ((b[0] - a[0]) / ln, (b[1] - a[1]) / ln))
    return best[1]


