#: обрыва не видно, и рельсы не упёрты в гребень (см. RAIL_GAP_BEARING_DEG).
TRACK_MAIN_SOUTH = -320.0

TRACK_MAIN = [
    (TRACK_X, TRACK_MAIN_SOUTH),
    (TRACK_X, -60.0),
    (TRACK_X, 2.0),
    (TRACK_X, NOSE_Z + 1.0),
    (TRACK_X, 21.0),
]

#: Стрелка на север: путь от носа уходит на запад к буферному упору.
TRACK_STUB = [
    (TRACK_X, 21.0),
    (TRACK_X - 4.5, 22.5),
    (TRACK_X - 10.0, 21.0),
    (TRACK_X - 15.0, 17.0),
    (TRACK_X - 18.5, 12.5),
]

#: Буферный упор: куда упирается ветка. За ним — стена заноса.
BUFFER_STOP = (TRACK_X - 18.5, 12.5)

#: Стена заноса, в которую упирается линия: (x, z, rx, rz, h) — та же форма
#: записи, что у `DRIFTS`, поэтому она участвует в высоте и в материале на
#: общих основаниях.
#:
#: Два числа выбраны не «на глаз», а из кадра прибытия.
#: Подъём: гребень вагона (y = 4.76 на 23.5 м от точки P0) виден с камеры
#: под 7.2°, значит стена обязана быть выше ~9 м, чтобы из стартового кадра
#: она читалась поверх крыши, а не пряталась за составом.
#: Дистанция: центр на 9.2 м севернее ближайшей точки стрелки, то есть
#: плоское дно коридора (`CORRIDOR_FLAT` = 4.3) её не достанет и не прорежет
#: стену пополам. Хвост гауссианы в z = 14.3 (нос состава) — 4 см,
#: поэтому «под депо плоско» продолжает выполняться.
TERMINUS_DRIFT = (TRACK_X - 12.0, 30.0, 17.0, 5.5, 10.5)


# ---------------------------------------------------------------- рельеф

#: Радиусы схемы высоты — та же структура, что у `level_parts.build_terrain`.
FLAT_R = 46.0        # до этого радиуса волны не выходят из нуля
WAVE_R = 96.0        # здесь волны на полной амплитуде
EDGE_R = 140.0       # начало гребня-стены
RIDGE_R = 260.0      # конец подъёма гребня
RIDGE_H = 8.5        # высота гребня, м

#: Амплитуды двух октав. Крупнее, чем у 90-метрового `SnowTerrain`: на 600 м
#: мира прежняя амплитуда 0.22 м читалась бы как натянутый лист.
WAVE_A1 = 0.55
WAVE_A2 = 0.25
WAVE_F1 = 0.0155
WAVE_F2 = 0.0330

#: Прорыв гребня — коридор дороги. Азимут от депо к воротам (12, 10):
#: atan2(12, 10) ≈ 50°. Половина угла раскрывается так, чтобы на 140 м
#: ширина прорыва была ~54 м: дорога уходит в белое, край читается краем
#: (ADR 0030), невидимых стен нет.
ROAD_BEARING_DEG = 50.0
ROAD_GAP_HALF_DEG = 11.0


def bearing_deg(x: float, z: float) -> float:
    """Азимут точки от начала координат, 0 = +Z (север), по часовой."""
    return math.degrees(math.atan2(x, z))


#: Второй проход — по оси пути. Без него линия, набранная до z = -320,
#: упёрлась бы в 8.5-метровую стену: состав уходит «за горизонт», а рельсы
#: нет. Ось считается от фактического конца `TRACK_MAIN`, а не «примерно на
#: юг», чтобы выемка в рельефе и проход в гребне лежали на одной прямой.
RAIL_GAP_BEARING_DEG = bearing_deg(TRACK_X, TRACK_MAIN_SOUTH)
RAIL_GAP_HALF_DEG = 12.0

RIDGE_GAPS = (
    (ROAD_BEARING_DEG, ROAD_GAP_HALF_DEG),
    (RAIL_GAP_BEARING_DEG, RAIL_GAP_HALF_DEG),
)


def ridge_height(x: float, z: float) -> float:
    """Гребень-стена от EDGE_R до RIDGE_R, с прорывами под дорогу и путь."""
    r = math.hypot(x, z)
    h = RIDGE_H * _smooth(EDGE_R, RIDGE_R, r)
    b = bearing_deg(x, z)
    for (bearing, half) in RIDGE_GAPS:
        gap = abs(_ang_delta(b, bearing))
        if gap < half * 2.0:
            h *= _smooth(0.0, half * 2.0, gap)
    return h


def corridor_mask(x: float, z: float) -> float:
    """Доля выемки в точке: 1 на плоском дне, 0 за откосом.

    Дно держится на одной отметке `TRACK_FLOOR_Y`, а не режет рельеф на
    фиксированную глубину: путь набран прямым на 340 м, и если дно пойдёт
    по волнам, балластная плита то повиснет в воздухе над прогибом, то
    утонет в гребне. Откос между ними — это и есть стенка выемки.
    """
    d = min(dist_to_polyline(x, z, TRACK_MAIN),
            dist_to_polyline(x, z, TRACK_STUB))
    return 1.0 - _smooth(CORRIDOR_FLAT, CORRIDOR_HALF, d)


def ground_height(x: float, z: float, drifts=None) -> float:
    """Полная высота снега в точке раскладки (Unity).

    Заносы по умолчанию берутся из `all_drifts()`: и генератор, и проверка
    обязаны мерить одно и то же поле, иначе `check_frontier.py` будет
    сверять меш с рельефом, которого никто не строил.
    """
    if drifts is None:
        drifts = all_drifts()
    r = max(abs(x), abs(z))
    w = _smooth(FLAT_R, WAVE_R, r)
    h = PAD_Y
    h += WAVE_A1 * w * _noise(x * WAVE_F1, z * WAVE_F1, 11.0)
    h += WAVE_A2 * w * _noise(x * WAVE_F2 + 5.0, z * WAVE_F2, 14.0)
    h += ridge_height(x, z)
    h += drift_sum(x, z, drifts)
    k = corridor_mask(x, z)
    if k > 0.0:
        h += (TRACK_FLOOR_Y - h) * k
    return h


