#: начало сцены». Правится вместе с `DefaultPath()`: расхождение между этими
#: двумя местами означает, что кадр смонтирован один, а рисуется другой.
ARRIVAL_EYE = (2.2, 1.80, -9.0)
ARRIVAL_AIM = (-1.5, 1.30, -1.60)
ARRIVAL_FOV = 44.0


