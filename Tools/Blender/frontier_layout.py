"""Раскладка открытого края депо: один источник истины.

Координаты — **Unity** (x, z), метры. `to_blender` переводит точку в оси Blender
(Unity-юг -Z = Blender +Y), как в `level_layout.py`; `export_static` при выгрузке
зеркалит по X, поэтому обратное превращение уже учтено и в мешах, и здесь.

Здесь только числа и чистые функции (без `bpy`): их читают `build_frontier_ground.py`
(выемка под путь, полоса леса), `build_frontier_track.py` (оси рельсов, терминус),
`build_frontier_grove.py` (куда ставить кластеры) и `check_frontier.py` (геометрические
инварианты). Раскладка сцены отсюда не генерируется — это нарушение ADR 0005.

Все размеры пути взяты из фактического авторинга вагона, а не из документации:
`build_train.py:837-856` — колёса на x = ±2.95, ось z = -0.65, радиус 0.35, то есть
низ колеса ровно на y = 0 при корне вагона y = 1. Значит головка рельса обязана быть
на y = 0, а разнос рельсов — 5.90 м.
"""

from __future__ import annotations

import math

# ---------------------------------------------------------------- оси

def to_blender(x: float, z: float) -> tuple[float, float]:
    """Позиция раскладки (Unity x, z) -> плоскость Blender (x, y)."""
    return (x, -z)


# ---------------------------------------------------------------- уровень отсчёта

#: Отметка плоской площадки депо. Не 0: низ `DepotPlatform` ровно на y = 0
#: (верх на y = 0.60, грань x = -4.00 — замер bounds в сцене), и на одной
#: высоте с ней получились бы совпадающие плоскости (STYLE.md, «никаких
#: копланарных граней»), которые мерцают и которые не ловит `coplanar_pairs`:
#: он проверяет грани внутри одного меша, а не между объектами.
PAD_Y = 0.02

#: Зона, где рельеф гарантированно плоский: застроенная площадка депо —
#: платформа, навес, состав, ворота и горловина проёма. Границы взяты с
#: запасом от фактических bounds (`DepotPlatform` x ∈ [-4.00, 15.00],
#: кузов вагона x ∈ [-12.09, -3.20], `DepotGate` z до 14.74), а не от
#: «примерно четверть карты»: внутри неё ни волны, ни заносы не дают
#: ни сантиметра, поэтому у стоящих на ней объектов нет зазора под полом.
#: Севернее z = 15 начинается стена терминуса — она уже нарочно вне зоны.
DEPOT_PAD = (-14.0, 17.0, -11.0, 15.0)


