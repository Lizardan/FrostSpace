def _smooth(edge0: float, edge1: float, value: float) -> float:
    if edge1 <= edge0:
        return 1.0 if value >= edge1 else 0.0
    t = min(max((value - edge0) / (edge1 - edge0), 0.0), 1.0)
    return t * t * (3.0 - 2.0 * t)


def _ang_delta(a: float, b: float) -> float:
    d = (a - b + 180.0) % 360.0 - 180.0
    return d


def _noise(x: float, y: float, seed: float) -> float:
    """Тот же детерминированный шум, что `level_lib.noise2d` (без импорта bpy)."""
    def v(i: float, j: float) -> float:
        s = math.sin(i * 127.1 + j * 311.7 + seed * 74.7) * 43758.5453
        return s - math.floor(s)

    xi, yi = math.floor(x), math.floor(y)
    xf, yf = x - xi, y - yi
    u = xf * xf * (3.0 - 2.0 * xf)
    w = yf * yf * (3.0 - 2.0 * yf)
    a = v(xi, yi)
    b = v(xi + 1, yi)
    c = v(xi, yi + 1)
    d = v(xi + 1, yi + 1)
    return 2.0 * ((a * (1 - u) + b * u) * (1 - w) +
                  (c * (1 - u) + d * u) * w) - 1.0
