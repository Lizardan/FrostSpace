CORRIDOR_FLAT = 4.3
CORRIDOR_HALF = 6.0
CORRIDOR_CUT = 0.62                    # на сколько метров ниже площадки

#: Дно коридора — отметка, а не перепад: путь набран прямым и уровень
#: под ним обязан быть прямым, иначе на волнах балласт повиснет в воздухе.
TRACK_FLOOR_Y = PAD_Y - CORRIDOR_CUT

#: Нос состава в покое (замер bounds `TrainBody`: z ∈ [-14.64, +14.30]).
NOSE_Z = 14.30
TAIL_Z = -14.64

#: Южный конец главной линии. Состав в начале прибытия стартует из
#: z = -2 + _trainStartOffset.z, то есть корень на z = -46 и хвост на
