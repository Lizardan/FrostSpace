#: Параметр неровномерной сетки террейна: `x = H·(a·t + (1-a)·t·|t|)`, t ∈ [-1, 1].
#: У депо шаг ~0.94 м (там, где рельеф читается вблизи), у края ~12 м: 192
#: деления на сторону дают 37 249 вершин и 73 728 трис вместо 460 тыс. трис
#: равномерной сетки того же качества в центре.
GROUND_SIZE = 1200.0
GROUND_N = 192
GROUND_FOCUS = 0.15

#: Коллайдер-прокси: та же неровномерная ось, прореженная через `COLLIDER_DIV`.
#: 73 тыс. трис в `MeshCollider` на WebGL — это cook-время и память физики
#: впустую, и внутри `DEPOT_PAD` обе сетки дают ровно `PAD_Y`, так что пешком
#: разницы нет. Равномерную сетку под это подгонять нельзя: шаг 18.75 м
#: просто не попадает в 8.6-метровое дно выемки, и робот ходил бы по невидимой
#: плите над прорезанным коридором. Прореживание сохраняет сгущение у депо:
#: ~1.9 м на площадке и ~23 м у края, 97×97 узлов = 18 432 трис.
COLLIDER_DIV = 2

#: Допуск «плоско под депо»: хвосты гауссиан заносов (q < 7) дают на границе
#: зоны миллиметры, а ловить надо сантиметры.
PAD_FLAT_TOL = 0.02


def grid_axis(n: int, half: float, focus: float) -> list[float]:
    """Неровномерная ось: густо у нуля, редко к краям."""
    out = []
    for i in range(n + 1):
        t = -1.0 + 2.0 * i / n
        out.append(half * (focus * t + (1.0 - focus) * t * abs(t)))
    return out


