def in_track_cut(x: float, z: float) -> bool:
    """Точка стоит в выемке пути: дно или откос.

    Для одиночных пропов это отдельная проверка, а не часть `in_keep_out`:
    фильтр рассыпания бережёт деревья от коридора автоматически, а столб,
    указатель или мачту кладёт человек — и им надо держать коридор в поле
    зрения, а не получить `False` «по умолчанию».
    """
    return corridor_mask(x, z) > 0.0


def in_road_corridor(x: float, z: float) -> bool:
    """Коридор дороги от ворот к прорыву гребня.

    Лес, вставший поперёк азимута 50°, убивает единственную подсказку
    направления: из депо должно быть видно, куда ехать (`RD-06`).
    """
    r = math.hypot(x, z)
    if r < 18.0 or r > RIDGE_R:
        return False
    return abs(_ang_delta(bearing_deg(x, z), ROAD_BEARING_DEG)) < ROAD_GAP_HALF_DEG


def in_keep_out(x: float, z: float) -> bool:
    if in_road_corridor(x, z):
        return True
    for (cx, cz, r) in KEEP_OUT_CIRCLES:
        if (x - cx) ** 2 + (z - cz) ** 2 < r * r:
            return True
    for (x0, x1, z0, z1) in KEEP_OUT_RECTS:
        if x0 <= x <= x1 and z0 <= z <= z1:
            return True
    return False


