def all_drifts():
    """Все заносы поля высот: равнинные плюс стена терминуса."""
    return list(DRIFTS) + [TERMINUS_DRIFT]


def drift_sum(x: float, z: float, drifts) -> float:
    """Сумма гауссовых заносов в точке Unity — та же форма, что `drift_height`."""
    h = 0.0
    for (dx, dz, rx, rz, dz_h) in drifts:
        q = ((x - dx) / rx) ** 2 + ((z - dz) / rz) ** 2
        if q < 7.0:
            h += dz_h * math.exp(-q)
    return h


def collider_height(x: float, z: float) -> float:
    """Поверхность, по которой ходит игрок: снег, но не глубже головки рельса.

    Прокси-коллайдер строится по `ground_height`, и если оставить как есть,
    внизу выемки (~-0.60) робот шагал бы сквозь шпалы и рельсы: их верх
    на -0.20 и 0.00. Поднимаем пол коридора до головки — идти по шпале, а
    не внутри неё, и переход на площадку (верх 0.60) остаётся тем же шагом,
    что и был до термина.
    """
    h = ground_height(x, z)
    if corridor_mask(x, z) >= 1.0:
        return max(h, RAIL_HEAD_Y)
    return h


def drift_contribution(x: float, z: float) -> float:
    """Вклад заносов и гребня в высоту грани — по нему выбирается материал.

    Повторяет приём `level_parts.build_terrain`: гребни получают «глубокий
    снег», подошвы — обычный. Гребень добавлен к заносам намеренно: без него
    стена издалека выходит одного тона и сливается с равниной.
    """
    return drift_sum(x, z, all_drifts()) + ridge_height(x, z)


