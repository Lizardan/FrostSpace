def dist_to_polyline(x: float, z: float, pts) -> float:
    """Расстояние от точки до ломаной в плоскости Unity (x, z)."""
    best = float("inf")
    for i in range(len(pts) - 1):
        ax, az = pts[i]
        bx, bz = pts[i + 1]
        vx, vz = bx - ax, bz - az
        len2 = vx * vx + vz * vz
        if len2 <= 1e-9:
            best = min(best, math.hypot(x - ax, z - az))
            continue
        t = max(0.0, min(1.0, ((x - ax) * vx + (z - az) * vz) / len2))
        best = min(best, math.hypot(x - (ax + vx * t), z - (az + vz * t)))
    return best


def rail_center_z():
    """Диапазон z, занятый путём: из него считается южный и северный конец."""
    zs = [p[1] for p in TRACK_MAIN] + [p[1] for p in TRACK_STUB]
