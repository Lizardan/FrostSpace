def _cockpit_console(b):
    """Пульт: шкафы, наклонная столешница, экраны, кнопки, штурвал, рычаги."""
    # Шкафы: низ утоплен в пол, между ними ниша для колен. Задняя кромка
    # пульта — 14,40, до корпуса R11 остаётся ~0,35 м.
    for sx in (-1, 1):
        b.box((sx * 1.175, -14.90, 0.45), (1.25, 1.00, 0.94),
              "Level_Metal", bevel=0.02)
        b.box((sx * 1.175, -14.42, 0.50), (1.10, 0.10, 0.60),
              "Level_Rust", bevel=0.01)

    # Столешница наклонена к водителю: передняя кромка выше задней.
    b.box_rot((0.0, -14.90, 0.98), (3.80, 1.20, 0.14),
              (-7.0, 0.0, 0.0), "Level_WoodDark", bevel=0.02)

    # Задняя полка под кнопки: своя плита, чтобы кнопки не легли в плоскость
    # наклонной столешницы.
    b.box((0.0, -14.65, 1.00), (3.20, 0.30, 0.08), "Level_Rust",
          bevel=0.01)
    for row, y in enumerate((-14.58, -14.70)):
        for i in range(7):
            x = -0.90 + i * 0.30
            mat = "Level_Window" if (i + row) % 3 == 0 else "Level_Orange"
            b.box((x, y, 1.065), (0.14, 0.12, 0.06), mat, bevel=0.0)

    # Два экрана: рамка и светящееся лицо. Лицо смещено к водителю на 3 см,
    # поэтому его плоскость не совпадает с передней гранью рамки.
    for x in (-0.55, 0.55):
        b.box_rot((x, -15.30, 1.24), (0.80, 0.08, 0.56),
                  (58.0, 0.0, 0.0), "Level_Rust", bevel=0.01)
        b.box_rot((x, -15.25, 1.24), (0.68, 0.04, 0.44),
                  (58.0, 0.0, 0.0), "Level_Window", bevel=0.0)

    # Педали в нише: низ ниже пола, верх читается как наклонная площадка.
    for sx in (-1, 1):
        b.box_rot((sx * 0.25, -14.85, 0.05), (0.20, 0.28, 0.06),
                  (18.0, 0.0, 0.0), "Level_Metal", bevel=0.0)
        b.box_rot((sx * 0.25, -14.78, 0.09), (0.14, 0.16, 0.04),
                  (18.0, 0.0, 0.0), "Level_Rust", bevel=0.0)

    # Штурвал: обод в наклонной плоскости, три спицы и ступица. Нормаль
    # (0; 0,42; 0,91) — как у наклонной панели перед водителем.
    cx, cy, cz = -1.30, -15.00, 1.38
    ny, nz = 0.42, 0.91
    vy, vz = nz, -ny
    ring = []
    for i in range(13):
        a = math.tau * i / 12.0
        ring.append((cx + math.cos(a) * 0.30,
                     cy + math.sin(a) * vy * 0.30,
                     cz + math.sin(a) * vz * 0.30))
    b.tube(ring, [(0.035, 0.035)] * 13, "Level_Metal", n=6,
           caps=(False, False))
    for i in range(3):
        a = math.tau * i / 3.0
        b.tube([(cx, cy, cz),
                (cx + math.cos(a) * 0.30,
                 cy + math.sin(a) * vy * 0.30,
                 cz + math.sin(a) * vz * 0.30)],
               [(0.028, 0.028)] * 2, "Level_Rust", n=6)
    b.tube([(cx, cy - ny * 0.05, cz - nz * 0.05),
            (cx, cy + ny * 0.07, cz + nz * 0.07)],
           [(0.09, 0.09)] * 2, "Level_Metal", n=8)
    b.tube([(cx, -15.36, 1.02), (cx, -15.04, 1.36)],
           [(0.05, 0.05)] * 2, "Level_Metal", n=6)

    # Рычаги справа: пьедестал врезан в правый шкаф, тяги уходят вверх.
    b.box((1.05, -14.24, 0.55), (0.54, 0.54, 1.10), "Level_Metal",
          bevel=0.02)
    b.box_rot((1.05, -14.24, 1.12), (0.60, 0.56, 0.08),
              (8.0, 0.0, 0.0), "Level_Rust", bevel=0.01)
    for x, top in ((0.90, 1.58), (1.20, 1.52)):
        b.tube([(x, -14.28, 1.14), (x, -14.33, top)],
               [(0.035, 0.035)] * 2, "Level_Metal", n=6)
        b.box((x, -14.33, top + 0.05), (0.12, 0.12, 0.14),
              "Level_Orange" if x < 1.0 else "Level_Rust", bevel=0.01)


