def _nose(b):
    """Полая кабина за торцевой дверью: трапеция в плане и наклонное стекло.

    Дверь вагона ведёт в кабину — поэтому нос не спорит с торцевой дверью
    за один и тот же торец. Задняя кромка кабины уходит в толщу стены на
    10 см, совпадающих плоскостей нет.
    """
    back = NOSE_BACK
    tip = NOSE_TIP
    hb = CAB_HALF_BACK
    hf = CAB_HALF_FRONT
    floor = 0.012
    wall_top = CAB_ROOF_LOW

    # Боковые стенки: трапеция в плане, толщина внутрь.
    for sx in (-1, 1):
        quad = ((sx * hb, back, floor), (sx * hb, back, wall_top),
                (sx * hf, tip, wall_top), (sx * hf, tip, floor))
        _plate(b, quad, (-sx * CAB_WALL, 0.0, 0.0), "Level_Metal")

    # Пол кабины: ступенька 12 мм над полом вагона, порог её не замечает.
    _plate(b, ((-hb, back - 0.05, floor), (hb, back - 0.05, floor),
               (hf, tip + 0.02, floor), (-hf, tip + 0.02, floor)),
           (0.0, 0.0, -0.172), "Level_WoodDark")

    # Крыша кабины: низ внахлёст с крышей вагона, верх выше снега.
    _plate(b, ((-hb, back, CAB_ROOF_LOW), (hb, back, CAB_ROOF_LOW),
               (hf, tip, CAB_ROOF_LOW), (-hf, tip, CAB_ROOF_LOW)),
           (0.0, 0.0, CAB_ROOF_HIGH - CAB_ROOF_LOW), "Level_Stone")

    # Снег на кабине: чуть меньше крыши и утоплен в неё на 2 см — иначе его
    # нижняя грань ложится в плоскость крыши и мерцает.
    _plate(b, ((-hb + 0.10, back - 0.05, CAB_ROOF_HIGH - 0.02),
               (hb - 0.10, back - 0.05, CAB_ROOF_HIGH - 0.02),
               (hf - 0.10, tip + 0.05, CAB_ROOF_HIGH - 0.02),
               (-hf + 0.10, tip + 0.05, CAB_ROOF_HIGH - 0.02)),
           (0.0, 0.0, 0.06), "Level_Snow")

    # Нижняя лобовая панель: от пола до низа стекла, наклонена назад.
    _plate(b, ((-hf, tip, floor), (hf, tip, floor),
               (hf, tip + 0.15, 1.45), (-hf, tip + 0.15, 1.45)),
           (0.0, 0.15, 0.0), "Level_Metal")

    # Лобовое стекло: трапеция во всю ширину лба — иначе по бокам остаются
    # тёмные проёмы, и кабина читается пустой коробкой. Верх на y = tip+1.02:
    # при глубине 4,2 м полуширина внутренней стенки 2,60, внешней 2,76;
    # кромка 2,66 уходит в толщу стенки, не ложась на её плоскость.
    _plate(b, ((-2.45, tip + 0.02, 1.45), (2.45, tip + 0.02, 1.45),
               (2.66, tip + 1.02, 3.58), (-2.66, tip + 1.02, 3.58)),
           (0.0, 0.075, 0.0), "Level_SnowDeep")

    # Стойки рамы по краям стекла: верх врезан в стенку, а не висит снаружи.
    for sx in (-1, 1):
        b.tube([(sx * 2.42, tip + 0.03, 1.48), (sx * 2.70, tip + 1.04, 3.56)],
               [(0.05, 0.05)] * 2, "Level_Rust", n=6)

    # Дворники: лежат на плоскости стекла, иначе на наклонной плите парят.
    def glass_y(z):
        return tip + 0.02 + (z - 1.45) * (1.0 / 2.13)

    for sx in (-1, 1):
        b.tube([(sx * 1.20, glass_y(1.52) - 0.005, 1.52),
                (sx * 0.55, glass_y(1.95) - 0.005, 1.95)],
               [(0.03, 0.03)] * 2, "Level_Rust", n=6)

    # Боковые окна кабины: без них нос сбоку читается как глухой блок.
    # Стенка сплошная (16 см), поэтому окно ставится на обе поверхности:
    # внешнее видно снаружи, внутреннее — из кабины. Два окна на борт.
    for sx in (-1, 1):
        nx, ny = _cabin_normal(sx)
        for t in (0.30, 0.58):
            cx, cy = _cabin_point(sx, t)
            for depth in (0.012, -0.152):
                b.box_rot((cx + nx * depth, cy + ny * depth, 2.30),
                          (0.02, 0.92, 1.00), (0.0, 0.0, _cabin_angle(sx)),
                          "Level_SnowDeep", bevel=0.01)

    # Плафон кабины: свет в носу, иначе водитель стоит в темноте. Корпус на
    # сантиметр входит в крышу, полоса — в корпус. Стоит над R11 (z = 13,6),
    # чтобы сценовой CabinLight освещал пульт.
    b.box((0.0, CAB_OPERATOR_Y, 3.36), (0.60, 0.90, 0.10), "Level_Metal",
          bevel=0.01)
    b.box((0.0, CAB_OPERATOR_Y, 3.295), (0.40, 0.70, 0.04), "Level_Window",
          bevel=0.0)

    # Горизонтальные рёбра лобовой панели: решётка вместо плоского щита.
    for z in (0.35, 0.75, 1.15):
        b.box((0.0, tip + 0.02, z), (4.36, 0.06, 0.07), "Level_Rust",
              bevel=0.0)

    # Фары: большая по центру и две малые по краям.
    for x, radius in ((0.0, 0.24), (-1.55, 0.13), (1.55, 0.13)):
        b.tube([(x, tip + 0.02, 1.12), (x, tip - 0.14, 1.12)],
               [(radius, radius)] * 2, "Level_Metal", n=12)
        b.tube([(x, tip - 0.13, 1.12), (x, tip - 0.19, 1.12)],
               [(radius * 0.8, radius * 0.8)] * 2, "Level_Window", n=12)

    # Буферы на углах кабины.
    for sx in (-1, 1):
        b.tube([(sx * 1.75, tip + 0.04, 0.95),
                (sx * 1.75, tip - 0.20, 0.95)],
               [(0.17, 0.17)] * 2, "Level_Metal", n=10)

    # Отвал: низ не ниже −1,2 м, иначе сборка не пройдёт проверку.
    b.box_rot((0.0, tip + 0.28, -0.72), (5.0, 0.50, 0.34), (0.55, 0.0, 0.0),
              "Level_Rust", bevel=0.02)
    for sx in (-1, 1):
        b.box_rot((sx * 2.35, tip + 0.30, -0.58), (0.5, 0.4, 0.5),
                  (0.55, 0.0, 0.0), "Level_Metal", bevel=0.02)
    b.box((0.0, tip + 0.10, -0.98), (4.8, 0.16, 0.14), "Level_Orange",
          bevel=0.0)

    # Поручни кабины: не парят, врезаются в стенку у носа.
    for sx in (-1, 1):
        b.tube([(sx * 2.16, tip + 0.10, 0.35), (sx * 2.16, tip + 0.10, 2.70)],
               [(0.045, 0.045)] * 2, "Level_Metal", n=6)
        for z in (0.35, 2.70):
            b.box((sx * 2.12, tip + 0.10, z), (0.14, 0.14, 0.10),
                  "Level_Metal", bevel=0.01)

    # Предупреждающая полоса на борту кабины: лежит в плоскости стенки,
    # иначе висит в воздухе на сужающемся борту.
    for sx in (-1, 1):
        b.box_rot((sx * 2.727, tip + 0.55, 0.95), (0.06, 0.62, 0.18),
                  (0.0, 0.0, _cabin_angle(sx)),
                  "Level_Orange", bevel=0.0)


