import level_lib  # noqa: E402

OUT = os.path.abspath(os.path.join(HERE, "..", "..", "Assets", "_Project",
                                   "Content", "Models", "Train"))

HALF_W = 4.0          # половина ширины вагона, м
HALF_L = 12.0         # половина длины, м
WALL = 0.2            # толщина стены
HEIGHT = 3.2          # высота интерьера
DOOR_W = 3.2          # ширина дверного проёма в торце
DOOR_H = 2.6          # высота проёма
SIDE_DOOR_Y = -1.0    # центр бокового проёма по длине (Unity z = +1.0)
SIDE_DOOR_W = 2.6     # ширина бокового проёма, м
SIDE_DOOR_H = 2.6     # высота бокового проёма, м

# Нахлёст оболочки: пол и крыша шире корпуса, торцы врезаются в них. Без
# этого фаски соседних деталей ложатся в одну плоскость и мерцают.
SKIN = 0.02
BODY_W = HALF_W * 2.0 + SKIN * 2.0
BODY_L = HALF_L * 2.0 + SKIN * 2.0

# Нос-кабина за торцевой дверью: полая, сужается к переду.
NOSE_BACK = -11.90    # задняя кромка входит в толщу торцевой стены
NOSE_TIP = -16.10     # передняя точка корпуса кабины (глубина 4,20 м)
CAB_HALF_BACK = 3.40  # полуширина у торца вагона
CAB_HALF_FRONT = 2.55 # полуширина у носа
CAB_WALL = 0.16       # толщина стенки кабины
CAB_ROOF_LOW = 3.40   # низ крыши кабины: внахлёст с крышей вагона (3.20…3.44)
CAB_ROOF_HIGH = 3.72  # верх крыши кабины: выше снега на крыше (3.56)

# R11 в сцене — на Unity z = 13.6 (Blender y = -13.6); он остаётся стоять
# у пульта, поэтому плафон и посадочное место привязаны к этой линии.
CAB_OPERATOR_Y = -13.60


# ------------------------------------------------------------------ вагон

def _segments(gap):
    """Отрезки вдоль длины, исключающие проём (Blender Y)."""
    if gap is None:
        return [(-HALF_L, HALF_L)]
    lo, hi = gap
    return [(-HALF_L, lo), (hi, HALF_L)]


def _wall_boxes(b, x, z, height, thickness, material, gap, bevel=0.02):
    """Коробки борта по отрезкам: проём вырезает панель, а не закрывает её."""
    for y0, y1 in _segments(gap):
        if y1 - y0 <= 0.01:
            continue
        b.box((x, (y0 + y1) * 0.5, z), (thickness, y1 - y0, height),
              material, bevel=bevel)


def _in_gap(y, gap, margin=0.0):
    if gap is None:
        return False
    return gap[0] - margin <= y <= gap[1] + margin


def _cabin_angle(sx):
    """Угол поворота детали в плоскости наклонной стенки кабины.

    Ось Y детали должна лечь вдоль стенки: направление стенки от торца к
    носу — (sx·(hf−hb), tip−back), а ось Y после поворота на θ — (−sinθ, cosθ).
    Отсюда θ = atan2(dy, dx) − 90°.
    """
    return math.degrees(math.atan2(
        NOSE_TIP - NOSE_BACK,
        sx * (CAB_HALF_FRONT - CAB_HALF_BACK))) - 90.0


def _cabin_half_width(t, inset=0.0):
    """Полуширина стенки кабины на доле глубины t (0 — торец, 1 — нос)."""
    return (CAB_HALF_BACK + (CAB_HALF_FRONT - CAB_HALF_BACK) * t) - inset


def _cabin_normal(sx):
    """Нормаль сужающейся стенки кабины наружу (для t = 0)."""
    dx = CAB_HALF_FRONT - CAB_HALF_BACK
    dy = NOSE_TIP - NOSE_BACK
    length = math.hypot(dx, dy)
    return (sx * (-dy) / length, dx / length)


def _cabin_point(sx, t, inset=0.0):
    """Точка на стенке кабины на доле t, сдвинутая внутрь по нормали."""
    nx, ny = _cabin_normal(sx)
    y = NOSE_BACK + (NOSE_TIP - NOSE_BACK) * t
    x = sx * _cabin_half_width(t)
    return (x - nx * inset, y - ny * inset)


def _plate(b, quad, offset, mat):
    """Плита по четырём точкам: внешняя грань и та же со сдвигом (толщина).

    Нужна там, где `box` не выражает форму: сужающийся нос, наклонное стекло.
    Оболочка замкнутая, поэтому `recalc_face_normals` при сборке выправит
    ориентацию граней.
    """
    pts = [level_lib.Vector(p) for p in quad]
    shift = level_lib.Vector(offset)
    verts = pts + [p + shift for p in pts]
    faces = [(0, 1, 2, 3), (7, 6, 5, 4), (0, 4, 5, 1),
             (1, 5, 6, 2), (2, 6, 7, 3), (3, 7, 4, 0)]
    b.add(verts, faces, mat)


def _side_door_frame(b, sx, gap):
    """Оранжевая рамка бокового проёма: видна и изнутри, и снаружи."""
    x = sx * (HALF_W - 0.02)
    for y in (gap[0] - 0.08, gap[1] + 0.08):
        b.box((x, y, SIDE_DOOR_H * 0.5), (0.18, 0.16, SIDE_DOOR_H),
              "Level_Orange", bevel=0.0)
    b.box((x, (gap[0] + gap[1]) * 0.5, SIDE_DOOR_H + 0.08),
          (0.18, gap[1] - gap[0] + 0.32, 0.16), "Level_Orange", bevel=0.0)
    # Порог врезается в пол: иначе его низ лежит в плоскости плиты.
    b.box((sx * (HALF_W - 0.28), (gap[0] + gap[1]) * 0.5, 0.03),
          (0.36, gap[1] - gap[0] + 0.2, 0.16), "Level_Rust", bevel=0.01)


def _wall(b, sx, side_door=False):
    """Борт: нижняя панель, окна между стойками, верхняя полоса и рёбра.

    У правого борта (Unity +X — сторона платформы) может быть боковой
    грузовой проём: панели, подоконник, стойка и рёбра вокруг него
    разрезаются, а не остаются поверх. Створки проёма — отдельные объекты.
    """
    x = sx * (HALF_W - WALL * 0.5)
    gap = None
    if side_door:
        gap = (SIDE_DOOR_Y - SIDE_DOOR_W * 0.5,
               SIDE_DOOR_Y + SIDE_DOOR_W * 0.5)

    # Нижняя панель — дерево: металл в интерьере отражает небо и седеет.
    _wall_boxes(b, x, 0.6, 1.2, WALL, "Level_Wood", gap)
    _wall_boxes(b, x, 2.85, 0.7, WALL, "Level_Stone", gap)

    # Подоконник и перемычка: тёмная ржавчина отделяет остекление.
    _wall_boxes(b, sx * (HALF_W - 0.16), 1.26, 0.12, 0.24,
                "Level_Rust", gap, bevel=0.01)
    _wall_boxes(b, sx * (HALF_W - 0.16), 2.44, 0.12, 0.24,
                "Level_Rust", gap, bevel=0.01)

    # Стойки между окнами: восемь пролётов по 3 м.
    for i in range(9):
        y = -HALF_L + 1.5 + i * 2.625
        if _in_gap(y, gap):
            continue
        b.box((x, y, 1.85), (0.24, 0.3, 1.3), "Level_Metal", bevel=0.015)
        # Оранжевая метка на стойке — ориентир в длинном вагоне. Врезается
        # в стойку на сантиметр: висящая в воздухе метка читается как баг.
        b.box((sx * (HALF_W - 0.24), y, 1.9), (0.06, 0.12, 0.5),
              "Level_Orange", bevel=0.0)

    # Рёбра жёсткости по нижней панели.
    for i in range(17):
        y = -HALF_L + 1.0 + i * 1.375
        if _in_gap(y, gap, 0.15):
            continue
        b.box((sx * (HALF_W - 0.16), y, 0.55), (0.12, 0.18, 1.0),
              "Level_Metal", bevel=0.01)

    # Иней у пола ближе к двери: вагон холодный, дверь открывают редко.
    for i in range(3):
        y = -HALF_L + 1.2 + i * 1.1
        if _in_gap(y, gap, 0.4):
            continue
        b.box((sx * (HALF_W - 0.45), y, 0.03), (0.55, 0.8, 0.16),
              "Level_Snow", bevel=0.02)

    if gap is not None:
        _side_door_frame(b, sx, gap)


def _far_end(b):
    """Глухая стена: панели, люк, щиток с индикаторами, вертикальные трубы."""
    y = HALF_L - WALL * 0.5
    # Шире корпуса и врезана в пол и крышу: фаски не совпадают с бортами.
    b.box((0.0, y, 1.6), (BODY_W, WALL, 3.24),
          "Level_Metal", bevel=0.02)

    for x in (-2.6, 0.0, 2.6):
        b.box((x, y - 0.08, 1.6), (0.3, 0.16, 2.9), "Level_Metal",
              bevel=0.015)

    # Люк в стене: тёмная панель в оранжевой рамке. Панель утоплена на 4 см,
    # иначе её задняя грань лежит в плоскости стены и мерцает.
    b.box((0.0, y - 0.20, 1.1), (1.6, 0.12, 1.8), "Level_WoodDark",
          bevel=0.02)
    b.box((0.0, y - 0.26, 2.02), (1.8, 0.08, 0.12), "Level_Orange", bevel=0.0)
    for sx in (-1, 1):
        b.box((sx * 0.84, y - 0.26, 1.1), (0.08, 0.08, 1.9),
              "Level_Orange", bevel=0.0)

    # Щиток: три индикатора, читаются как «система жива».
    b.box((1.9, y - 0.16, 2.15), (1.2, 0.1, 0.7), "Level_Metal", bevel=0.02)
    for i in range(3):
        b.box((1.55 + i * 0.3, y - 0.22, 2.15), (0.12, 0.04, 0.12),
              "Level_Window", bevel=0.0)

    for sx in (-3.1, -3.45):
        b.tube([(sx, y - 0.12, 0.1), (sx, y - 0.12, HEIGHT - 0.1)],
               [(0.07, 0.07)] * 2, "Level_Rust", n=6)


def _door_end(b):
    """Торец с проёмом: сегменты стены, перемычка, портал и рельс створок.

    Оранжевый портал выступает в салон (Unity 11,56…11,78), створки скользят
    за ним в плоскости стены (11,82…12,00): иначе при раздвиге створка
    прорезает косяк.
    """
    y = -HALF_L + WALL * 0.5
    side = (BODY_W - DOOR_W) * 0.5
    top = 3.22   # врезается в крышу: фаска не совпадает с её нижней гранью
    portal = y + 0.23   # −11,67 → Unity 11,56…11,78 при толщине 0,22

    for sx in (-1, 1):
        b.box((sx * (DOOR_W * 0.5 + side * 0.5), y, 1.6),
              (side, WALL, 3.24), "Level_Metal", bevel=0.02)
        # Вертикальные рёбра на глухих частях.
        b.box((sx * (DOOR_W * 0.5 + side * 0.5), y - 0.08, 1.6),
              (side * 0.5, 0.16, 2.9), "Level_Metal", bevel=0.015)

    # Перемычка над проёмом.
    b.box((0.0, y, DOOR_H + (top - DOOR_H) * 0.5),
          (DOOR_W, WALL, top - DOOR_H), "Level_Metal", bevel=0.02)

    # Оранжевый портал: выступает в салон и закрывает щель по краям створок.
    for sx in (-1, 1):
        b.box((sx * (DOOR_W * 0.5 + 0.06), portal, DOOR_H * 0.5),
              (0.12, 0.22, DOOR_H), "Level_Orange", bevel=0.0)
    b.box((0.0, portal, DOOR_H + 0.06), (DOOR_W + 0.24, 0.22, 0.12),
          "Level_Orange", bevel=0.0)

    # Рельс на две створки и порог — внутри вагона.
    b.box((0.0, portal + 0.02, DOOR_H + 0.22), (6.8, 0.40, 0.14),
          "Level_Rust", bevel=0.02)
    b.box((0.0, y + 0.2, 0.03), (DOOR_W, 0.5, 0.14), "Level_Rust",
          bevel=0.01)

    # Занос у двери: внутрь наметает.
    b.box((0.0, y + 1.1, 0.04), (DOOR_W - 0.4, 1.1, 0.16), "Level_Snow",
          bevel=0.03)


def _deck(b):
    """Настил по центру: доска, оранжевые кромки и поперечные швы."""
    # Настил врезается в плиту пола на 6 см: низ не лежит в её плоскости.
    b.box((0.0, 0.0, -0.005), (2.6, HALF_L * 2.0 - 0.8, 0.11),
          "Level_WoodDark", bevel=0.01)
    for sx in (-1, 1):
        b.box((sx * 1.30, 0.0, 0.025), (0.10, HALF_L * 2.0 - 0.8, 0.07),
              "Level_Orange", bevel=0.0)

    # Поперечные швы настила: крупные, чтобы не читались «сыпью». Верх шва
    # ниже кромки на 5 мм — совпадающие плоскости дают мерцание.
    for i in range(11):
        y = -HALF_L + 1.4 + i * 2.0
        b.box((0.0, y, 0.0475), (2.56, 0.08, 0.015), "Level_Rust", bevel=0.0)


def _ceiling_inside(b):
    """Внутренняя отделка потолка: рёбра, плафоны и трубы под плитой крыши."""
    for i in range(13):
        y = -HALF_L + i * 2.0
        b.box((0.0, y, HEIGHT - 0.02), (HALF_W * 2.0, 0.16, 0.14),
              "Level_Metal", bevel=0.01)

    # Плафоны: широкий кожух и утопленная тёплая полоса. Свет в вагоне — единственный.
    for y in (-6.0, 6.0):
        b.box((0.0, y, HEIGHT - 0.07), (1.3, 3.2, 0.18), "Level_Metal",
              bevel=0.02)
        b.box((0.0, y, HEIGHT - 0.14), (0.55, 2.5, 0.07), "Level_Window",
              bevel=0.0)

    # Трубы и хомуты.
    for sx in (-1, 1):
        b.tube([(sx * 3.5, -HALF_L + 0.4, HEIGHT - 0.18),
                (sx * 3.5, HALF_L - 0.4, HEIGHT - 0.18)],
               [(0.08, 0.08)] * 2, "Level_Rust", n=6, caps=(False, False))
        for i in range(6):
            y = -HALF_L + 2.0 + i * 4.0
            b.box((sx * 3.5, y, HEIGHT - 0.06), (0.16, 0.12, 0.24),
                  "Level_Metal", bevel=0.01)
    b.tube([(0.0, -HALF_L + 0.4, HEIGHT - 0.06),
            (0.0, HALF_L - 0.4, HEIGHT - 0.06)],
           [(0.05, 0.05)] * 2, "Level_Rust", n=6, caps=(False, False))


def _furniture(b):
    """Лавки, верстак, ящики и полка — чтобы вагон читался как рабочий."""
    for sx in (-1, 1):
        # Лавка: сиденье, спинка, ножки. Спинка врезается в сиденье.
        b.box((sx * 3.25, 6.4, 0.5), (0.6, 2.4, 0.1), "Level_Wood",
              bevel=0.02)
        b.box((sx * 3.5, 6.4, 0.83), (0.12, 2.4, 0.66), "Level_WoodDark",
              bevel=0.02)
        for dy in (-1.0, 1.0):
            b.box((sx * 3.25, 6.4 + dy, 0.24), (0.5, 0.12, 0.54),
                  "Level_Metal", bevel=0.01)

    # Верстак в дальнем конце: столешница, ножки, тиски, лампа.
    b.box((0.0, 10.5, 0.95), (2.4, 0.9, 0.12), "Level_Wood", bevel=0.02)
    for sx in (-1, 1):
        for dy in (-0.35, 0.35):
            b.box((sx * 1.0, 10.5 + dy, 0.43), (0.14, 0.14, 0.94),
                  "Level_Metal", bevel=0.01)
    b.box((0.7, 10.5, 1.11), (0.5, 0.4, 0.24), "Level_Rust", bevel=0.02)
    b.box((0.7, 10.5, 1.26), (0.24, 0.2, 0.12), "Level_Metal", bevel=0.01)
    b.box((-0.9, 10.5, 1.14), (0.12, 0.12, 0.3), "Level_Metal", bevel=0.01)
    b.box((-0.9, 10.5, 1.32), (0.5, 0.3, 0.1), "Level_Metal", bevel=0.02)
    b.box((-0.9, 10.5, 1.26), (0.4, 0.2, 0.04), "Level_Window", bevel=0.0)

    # Ящики по углам: низ утоплен в пол на 2 см.
    for x, y, size in ((3.1, -9.4, 0.9), (-3.0, 9.7, 0.8)):
        b.box((x, y, size * 0.5 - 0.02), (size, size, size), "Level_Wood",
              bevel=0.03)
        b.box((x, y, size * 0.55), (size + 0.04, 0.1, 0.12), "Level_Rust",
              bevel=0.0)
        b.box((x, y, size + 0.01), (size * 0.9, size * 0.9, 0.06),
              "Level_Snow", bevel=0.0)

    # Полка на дальнем борту.
    b.box((3.6, 9.6, 1.9), (0.35, 3.0, 0.1), "Level_WoodDark", bevel=0.01)
    for dy in (-1.2, 1.2):
        b.box((3.45, 9.6 + dy, 1.8), (0.2, 0.12, 0.3), "Level_Metal",
              bevel=0.01)


def _shell(b):
    """Оболочка вагона — ровно один раз: пол, борта, крыша, торцы."""
    # Плита пола: низ −0.30, верх 0.0. Шире корпуса на 2 см с каждой стороны,
    # чтобы её фаска не совпала с фаской борта.
    b.box((0.0, 0.0, -0.15), (BODY_W, BODY_L, 0.3),
          "Level_Stone", bevel=0.02)
    for sx in (-1, 1):
        _wall(b, sx, side_door=sx > 0)

    # Крыша: одна плита на всю длину, 3.20…3.44. Она же потолок интерьера —
    # второй плиты быть не должно.
    b.box((0.0, 0.0, 3.32), (BODY_W, BODY_L, 0.24),
          "Level_Stone", bevel=0.02)

    _far_end(b)
    _door_end(b)


def _interior(b):
    """Внутренние надстройки: настил, потолок, мебель."""
    _deck(b)
    _ceiling_inside(b)
    _furniture(b)


