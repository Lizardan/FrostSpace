def _build_side_leaf(materials, name, x, y_center):
    """Створка боковой двери отдельным объектом: сцена раздвигает её по Z."""
    d = level_lib.LevelBuilder(materials)
    d.box((0.0, 0.0, 0.0), (0.12, 1.30, SIDE_DOOR_H + 0.02),
          "Level_Metal", bevel=0.02)
    # Окно, полоса и рёбра с обеих сторон: экспорт зеркалит X, и деталь,
    # построенная только снаружи, после зеркала оказалась бы внутри створки.
    for sx in (-1, 1):
        d.box((sx * 0.07, 0.0, 0.65), (0.05, 0.62, 0.44), "Level_SnowDeep",
              bevel=0.01)
        d.box((sx * 0.07, 0.0, -0.92), (0.05, 0.72, 0.18), "Level_Orange",
              bevel=0.0)
        for dy in (-0.26, 0.26):
            d.box((sx * 0.07, dy, 0.0), (0.05, 0.06, 2.2), "Level_Rust",
                  bevel=0.0)
        # Ручка и петли.
        d.box((sx * 0.1, 0.42, -0.25), (0.06, 0.1, 0.5), "Level_Rust",
              bevel=0.01)
    leaf = d.build(name)
    leaf.location = (x, y_center, SIDE_DOOR_H * 0.5)
    return leaf


def _build_end_leaf(materials, name, x, y_center):
    """Створка торцевой двери: меш вокруг нуля, пивот — низ по центру.

    Створок две: одна на 3,10 м не убирается в стену — вылезает за борт.
    Полотно 1,58 м уезжает за косяк и остаётся в габарите.
    """
    d = level_lib.LevelBuilder(materials)
    # Низ утоплен под пол на 2 см, верх ниже перемычки на 5 см.
    d.box((0.0, 0.0, 1.265), (1.58, 0.12, 2.57), "Level_Metal", bevel=0.02)
    # Окно сквозь створку в ржавой рамке.
    d.box((0.0, 0.0, 2.0), (0.95, 0.16, 0.50), "Level_SnowDeep", bevel=0.01)
    for dz in (-1, 1):
        d.box((0.0, 0.0, 2.0 + dz * 0.29), (1.05, 0.16, 0.08),
              "Level_Rust", bevel=0.0)
    for dx in (-1, 1):
        d.box((dx * 0.50, 0.0, 2.0), (0.08, 0.16, 0.56), "Level_Rust",
              bevel=0.0)
    # Аварийная полоса и ручки с обеих сторон.
    d.box((0.0, 0.0, 0.35), (1.30, 0.16, 0.18), "Level_Orange", bevel=0.0)
    for dx in (-1, 1):
        d.tube([(dx * 0.55, 0.07, 1.0), (dx * 0.55, 0.07, 1.6)],
               [(0.03, 0.03)] * 2, "Level_Metal", n=6)
    leaf = d.build(name)
    leaf.location = (x, y_center, 0.0)
    return leaf


def build_car(materials):
    """Один вагон: оболочка, интерьер, кабина и раздвижные створки."""
    b = level_lib.LevelBuilder(materials)
    _shell(b)
    _interior(b)
    _nose(b)
    _cockpit(b)
    _rear_outside(b)
    _roof_outside(b)
    _side_outside(b)
    _bogies(b)
    body = b.build("TrainBody")

    # Торцевая дверь: две створки на разных дорожках. Blender X зеркалится
    # при экспорте, поэтому +0,76 даёт левую створку в Unity на −0,76.
    door_left = _build_end_leaf(materials, "TrainDoorL", 0.76, -11.88)
    door_right = _build_end_leaf(materials, "TrainDoorR", -0.76, -11.94)

    # Два рельса: створки разнесены по X на 7 см и перекрываются по Y на
    # 3 см — ни щели, ни совпадающих граней. Смещение центров — внутрь проёма:
    # наружу оно давало зазор 4 см, в который проходил луч.
    left = _build_side_leaf(materials, "TrainSideDoorL", -4.09,
                            SIDE_DOOR_Y - SIDE_DOOR_W * 0.25 + 0.02)
    right = _build_side_leaf(materials, "TrainSideDoorR", -4.16,
                             SIDE_DOOR_Y + SIDE_DOOR_W * 0.25 - 0.02)
    return [body, door_left, door_right, left, right]


