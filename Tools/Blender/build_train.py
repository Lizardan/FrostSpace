"""Собирает вагон и груз для среза «Поезд».

Запуск (штатно — через единый вход пайплайна):

    python Tools/Blender/build_all.py --asset train --check

Прямой запуск для точечной отладки:

    blender --background --factory-startup --python Tools/Blender/build_train.py

Выход в `Assets/_Project/Content/Models/Train/`:

    TrainCar.fbx       — один вагон: корпус `TrainBody` (оболочка + интерьер +
                         кабина 4,2 м с кокпитом), створки торцевой двери
                         `TrainDoorL`/`TrainDoorR` и раздвижные створки бокового
                         проёма `TrainSideDoorL`/`TrainSideDoorR` отдельными
                         объектами (их двигает сцена); интерьер 8 × 24 м,
                         высота 3.2 м, дверь в Blender −Y (после `export_static`
                         это Unity +Z, нос вагона); боковой грузовой проём на
                         Unity +X;
    Prop_Battery.fbx   — тяжёлый аккумулятор: корпус, ручки, полосы, индикатор;
    Prop_GravCart.fbx  — грави-тележка на четыре слота с ручкой и пультом.

Оболочка (пол, борта, крыша, торцы) строится **один раз**: интерьер и наружные
детали — только надстройки. Иначе две копии одной геометрии дают z-fighting,
из-за которого вагон «мерцает».

Оси и единицы — как у остальной статики (ADR 0002, 0007): метры, Z вверх,
дверь в −Y, `export_static` зеркалит X и компенсирует `bake_space_transform`.
Пивот пропов — низ по центру (z = 0): в сцене они ставятся на пол как есть.

Правило геометрии (docs/STYLE.md): никакая грань детали не лежит в плоскости
грани другой оболочки — накладка врезается минимум на 2 см, деталь на полу
опускается ниже уровня пола.

Палитра — `Level_*`; материалы подставит `LevelAssetPostprocessor` (папки
`Models/Level` и `Models/Train` используют один контракт палитры).
"""

