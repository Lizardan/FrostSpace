"""Меши дальнего слоя: силуэты якорей, отмеренные по углу, а не по метрам.

Запуск (штатно — из пайплайна, а не руками):

    blender --background --factory-startup --python Tools/Blender/build_far.py

Зачем отдельный класс контента, если якоря уже описаны в раскладке: якорь стоит
на 849-1697 м, а сцена обрывает геометрию на 400 м. На его месте рисовать нечего,
поэтому в кадре стоит **карточка** — тело на 380 м, размер которого повторяет
угловой размер настоящего якоря. Все числа карточки (ширина, высота, азимут,
«читать/не читать») считаются в `world_layout.far_layer()`, здесь только профиль:
чем ниже тело, тем оно шире, где ярус — там выступ.

Профиль берётся из тех же `STEPS`, `RINGS` и `tier_width`, что описывают настоящий
якорь: карточка обязана быть тем же телом, уменьшенным по углу, а не «башней из
воображения». Иначе силуэт станции и станция на миникарте — два разных объекта.

Габарит меша по X и Z обязан ровно равняться обещанным `w` и `h` — это не
косметика, а то, за чем слой существует: `w` из раскладки сошёл с угловой
ширины, и если профиль торчит за него (обходы стержня — ровно тот случай),
силуэт съедает азимут соседа и инвариант «не сливаются» врёт. Профиль поэтому
жимается множителем `_fit`, а сборка меряет оба габарита по мешу.

Оси — Blender (x, y, z), z вверх, метры; основание утоплено в снег, как требует
`STYLE.md`. Перевод в Unity делает `export_static` с зеркалом X (ADR 0007).
Материал один: туман съедает 99.45 % цвета, поэтому второй материал означал бы
одну лишнюю грань в проверке и ноль лишней информации в кадре.
"""

from __future__ import annotations

import level_lib  # noqa: E402
import world_layout as W  # noqa: E402

#: Имя файла силуэта. Только те якоря, чья карточка читается (`draw`); список
#: сверяется на сборке, и новый читаемый якорь без имени роняет сборку, а не
#: молча остаётся невидимым.
FILENAMES = {
    "station": "Far_Station.fbx",
    "kosoy": "Far_Kosoy.fbx",
    "far_s": "Far_South.fbx",
}

#: Насколько макушка наклонного якоря («Косой») уползает в сторону от основания,
#: доля высоты. Пятнадцать процентов — это 14 м для 96-метровой карточки: тело
#: читается косым, но не падает.
LEAN_MAX = 0.15

#: Перекрытие пачек по вертикали, доля высоты. Без него верхняя грань нижней
#: пачки лежала бы ровно в одной плоскости с нижней гранью верхней — копланарная
#: пара, которую `check_frontier.py` зовёт мерцанием. С перекрытием нижняя грань
#: верхней пачки сидит внутри тела под ней.
EMBED = 0.03

#: Насколько основание уходит в снег, доля высоты (правило `STYLE.md`: деталь,
#: стоящая на полу, опускается ниже уровня пола, иначе виден шов).
SINK = 0.01

#: Выступ яруса — доля фасада в этом месте (плита, на которую выходит тёплый
#: тамбур). Обход стержня — доля ширины яруса под ним: кольцо шире мачты, но
#: не вылезает за основание, иначе силуэт снова станет «ветками».
STEP_LIP = 0.05
RING_LIP = 0.72

#: Толщины, доля высоты тела. Ярус — плита, кольцо — планка.
STEP_T = 0.030
RING_T = 0.010

#: Доля высоты, до которой тело — обжитый массив с террасами, а выше — стержень.
#: Это дословно то, что говорит раскладка: `STEPS` — «ярусы-ступени нижнего
#: яруса», «выше них тело переходит в стержень», `RINGS` — «кольцевые обходы
#: стержня». Перепад в два с лишним раза и есть то, что читается силуэтом: без
#: него тело в 70-96 м выглядит стопкой равных коробок, и глаз называет это
#: деревом, а не опорой Пояса.
TIER_TOP = W.STEPS[-1]

#: Ширина стержня у своего основания и сужение к макушке, доли ширины яруса под
#: ним. Дальше `tier_width` не работает: он описывает фасад основания, а не мачту.
STEM_W = 0.40
STEM_TAPER = 0.25


def width_at(frac: float, w: float) -> float:
    """Ширина тела на доле высоты: фасад яруса, потом стержень."""
    if frac <= TIER_TOP:
        return W.tier_width(frac, w)
    stem = W.tier_width(TIER_TOP, w) * STEM_W
    k = (frac - TIER_TOP) / (1.0 - TIER_TOP)
    return stem * (1.0 - STEM_TAPER * k)


#: Границы пачек тела: доли высоты от земли до макушки. Одна и та же
#: последовательность задаёт и ступени силуэта, и ширину тела на этой высоте,
#: поэтому карточка наследует раскладку без ручных чисел.
BANDS = (0.0,) + W.STEPS + W.RINGS + (1.0,)

#: Что ставить на каждой доле высоты: природа выступа и его толщина. Ярус —
#: плита шире фасада, кольцо — планка вокруг стержня.
LIPS = dict([(f, ("step", STEP_T)) for f in W.STEPS]
            + [(f, ("ring", RING_T)) for f in W.RINGS])


def lip_width(kind: str, frac: float, w: float) -> float:
    """Ширина выступа: ярус торчит из фасада, кольцо обходит стержень."""
    if kind == "step":
        return width_at(frac, w) * (1.0 + 2.0 * STEP_LIP)
    return width_at(TIER_TOP, w) * RING_LIP


#: Материал силуэта. См. шапку модуля: на 380 м тумана хватает на один.
MAT = "Level_Stone"


def _lean(frac: float, h: float, kind: str) -> float:
    """Смещение оси тела на доле высоты: у основания ноль, у макушки — `LEAN_MAX`."""
    return LEAN_MAX * h * frac * frac if kind == "lean" else 0.0


def _half_width(frac: float, w: float) -> float:
    """Половина ширины самого широкого элемента на уровне: тело или его выступ."""
    half = width_at(frac, w) * 0.5
    lip = LIPS.get(frac)
    if lip:
        half = max(half, lip_width(lip[0], frac, w) * 0.5)
    return half


def _fit(card) -> float:
    """Во сколько раз ужать профиль, чтобы габарит силуэта равнялся `w`.

    Мерой служит полный размах по X (максимум минус минимум), а не «радиус»:
    наклонное тело уходит в одну сторону, и по радиусу его правый край совпал
    бы с `w`, а левый остался бы на месте — силуэт стал бы уже обещанного угла
    и соврал бы про азимут. Жмутся и ширины, и наклон (`place` в билдере),
    поэтому размах делится на `k` целиком.
    """
    (h, w) = (card["h"], card["w"])
    (hi, lo) = (float("-inf"), float("inf"))
    for f in BANDS[1:]:
        off = _lean(f, h, card["kind"])
        half = _half_width(f, w)
        hi = max(hi, off + half)
        lo = min(lo, off - half)
    return (hi - lo) / w


def build_card(materials, card):
    """Один силуэт по записи `far_layer()`: `card` — словарь с `w`, `h`, `kind`."""
    (h, w) = (card["h"], card["w"])
    k = _fit(card)

    def place(frac):
        """X-центр элемента: наклон входит в габарит, поэтому тоже жмётся."""
        return _lean(frac, h, card["kind"]) / k

    b = level_lib.LevelBuilder(materials)

    for (f0, f1) in zip(BANDS, BANDS[1:]):
        width = width_at(f1, w) / k
        z1 = f1 * h
        # Первая пачка уходит основанием в снег, остальные перекрывают нижнюю на
        # `EMBED`: иначе верхняя грань нижней пачки встала бы в одну плоскость с
        # нижней гранью верхней, и проверка выдала бы копланарную пару.
        z0 = f0 * h - EMBED * h if f0 > 0.0 else -SINK * h
        b.box((place(f1), 0.0, (z0 + z1) * 0.5),
              (width, width, z1 - z0), MAT, bevel=0.0)

    for (f, (kind, t)) in LIPS.items():
        width = lip_width(kind, f, w) / k
        b.box((place(f), 0.0, f * h), (width, width, t * h), MAT, bevel=0.0)

    return b.build("Far_%s" % card["k"])
